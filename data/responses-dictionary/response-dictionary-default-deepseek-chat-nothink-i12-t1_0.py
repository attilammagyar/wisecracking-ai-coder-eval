import collections.abc
import re

def is_word_token(token: str) -> bool:
    """Check if the token is a word (not a separator)."""
    return bool(re.fullmatch(r"[^\W_]+", token, flags=re.IGNORECASE))

def build_dictionary_index(dictionary: collections.abc.Mapping) -> object:
    """
    Build a normalized index from a dictionary for fast lookup of words and
    compound phrases.

    The index consists of:
    - single_words: a dict mapping normalized single words to their entries.
    - phrase_index: a trie-like structure for compound phrases.
    - max_phrase_length: the maximum number of words in any phrase.
    """
    single_words = {}
    phrase_index = {}
    max_phrase_length = 0

    for phrase, entry in dictionary.items():
        # Split phrase into tokens, normalizing each token
        tokens = re.findall(r"([^\W_]+|[^\w])", phrase, flags=re.IGNORECASE)
        word_tokens = [token.lower() for token in tokens if is_word_token(token)]
        
        if not word_tokens:
            continue  # skip empty or separator-only phrases
        
        if len(word_tokens) == 1:
            # Single word entry
            word = word_tokens[0]
            if word not in single_words:
                single_words[word] = set()
            single_words[word].add(entry)
        else:
            # Compound phrase entry
            current = phrase_index
            for word in word_tokens:
                if word not in current:
                    current[word] = {}
                current = current[word]
            if None not in current:
                current[None] = set()
            current[None].add(entry)
            max_phrase_length = max(max_phrase_length, len(word_tokens))
    
    return {
        "single_words": single_words,
        "phrase_index": phrase_index,
        "max_phrase_length": max_phrase_length,
    }

def annotate(tokens: collections.abc.Iterable[str], dictionary_index: object) -> collections.abc.Iterable[tuple[str, collections.abc.Set]]:
    """
    Annotate tokens with entries from the dictionary.

    For each token, collect entries from:
    - Single-word matches.
    - All compound phrases the token participates in.
    """
    single_words = dictionary_index["single_words"]
    phrase_index = dictionary_index["phrase_index"]
    max_phrase_length = dictionary_index["max_phrase_length"]
    tokens = list(tokens)
    annotated_tokens = []
    
    # Precompute which tokens are words
    word_flags = [is_word_token(token) for token in tokens]
    
    for i in range(len(tokens)):
        token = tokens[i]
        annotations = set()
        
        # Single-word lookup
        if word_flags[i]:
            normalized = token.lower()
            annotations.update(single_words.get(normalized, set()))
        
        # Compound phrase lookup
        if word_flags[i]:
            current_node = phrase_index
            j = i
            phrase_words = 0
            while j < len(tokens) and phrase_words < max_phrase_length:
                if word_flags[j]:
                    word = tokens[j].lower()
                    if word not in current_node:
                        break
                    current_node = current_node[word]
                    phrase_words += 1
                    if None in current_node:
                        annotations.update(current_node[None])
                elif j > i:  # Inner separator
                    pass  # Skip separators within phrase
                else:  # Leading separator
                    break
                j += 1
        
        annotated_tokens.append((token, annotations))
    
    return annotated_tokens
