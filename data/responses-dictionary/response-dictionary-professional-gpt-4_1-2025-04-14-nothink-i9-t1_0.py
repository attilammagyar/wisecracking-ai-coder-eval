def is_word_token(token):
    # Simple: treat as word token if alphanum (can adjust for locale if needed)
    return any(c.isalnum() for c in token)

def normalize_word(w):
    # Lowercase & strip
    return w.strip().lower()

def split_phrase(phrase):
    """
    Split a phrase string into (words, separators).
    Returns: [word0, sep0, word1, sep1, word2, ...]; separators are kept as a single space
    Since we are only interested in making a trie for words, we will just extract the words in order.
    """
    parts = []
    for m in re.finditer(r'\w+|\W+', phrase, flags=re.UNICODE):
        if m.group().strip() == '':
            continue
        text = m.group()
        if is_word_token(text):
            parts.append(('word', normalize_word(text)))
        else:
            parts.append(('sep', ' '))  # Normalize all separators to a single space placeholder
    # Coalesce multiple consecutive seps
    condensed = []
    last_type = None
    for typ, val in parts:
        if typ == 'sep' and last_type == 'sep':
            continue
        condensed.append((typ, val))
        last_type = typ
    # Remove leading/trailing separators for matching
    while condensed and condensed[0][0] == 'sep':
        condensed = condensed[1:]
    while condensed and condensed and condensed[-1][0] == 'sep':
        condensed = condensed[:-1]
    # Only keep words for trie steps
    wordlist = [val for typ, val in condensed if typ == 'word']
    return wordlist

class TrieNode:
    __slots__ = ('children', 'entries')
    def __init__(self):
        self.children = dict()
        self.entries = set()

    def insert(self, wordlist, entry):
        node = self
        for word in wordlist:
            if word not in node.children:
                node.children[word] = TrieNode()
            node = node.children[word]
        node.entries.add(entry)

