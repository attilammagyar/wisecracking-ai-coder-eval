# Helper: Is token a word? (Alnum-only. No Unicode gymnastics here.)
def is_word_token(token: str) -> bool:
    return token.isalnum()

# Helper: Normalize a list of tokens (lowercase, skip separators if needed)
def normalize_phrase(phrase: str):
    # Split by alnum-runs (phrases like "AAA, BBB" -> ["aaa", "bbb"])
    return [w.lower() for w in re.findall(r'\w+', phrase)]

class TrieNode:
    __slots__ = ['children', 'entries']
    def __init__(self):
        self.children = dict()    # word -> TrieNode
        self.entries = set()      # IDs

def build_dictionary_index(dictionary: collections.abc.Mapping) -> object:
    # Single-word index: word -> set of entries
    word_entries = dict()
    # Trie for multi-word phrases: node path is tuple of normalized words
    root = TrieNode()
    for phrase, entry in dictionary.items():
        wlist = normalize_phrase(phrase)
        if not wlist:
            continue  # Ignore empty dictionary entries.
        if len(wlist) == 1:
            word = wlist[0]
            word_entries.setdefault(word, set()).add(entry)
        else:
            # Insert into trie
            node = root
            for w in wlist:
                if w not in node.children:
                    node.children[w] = TrieNode()
                node = node.children[w]
            node.entries.add(entry)
    # Return both, since single-word lookup is more efficient outside the trie
    return {'word_entries': word_entries, 'trie': root}

def annotate(tokens: collections.abc.Iterable[str], dictionary_index: object) -> collections.abc.Iterable[tuple[str, collections.abc.Set]]:
    # So dry, but so right
    tokens = list(tokens)
    N = len(tokens)
    # Classify tokens as words or not up front (so we can skip separators efficiently)
    types = [is_word_token(tok) for tok in tokens]
    # Prepare per-token annotation sets
    annotations = [set() for _ in range(N)]
    word_entries = dictionary_index['word_entries']
    trie_root = dictionary_index['trie']

    # Step 1: Individual word lookup
    for i, token in enumerate(tokens):
        if types[i]:
            norm = token.lower()
            if norm in word_entries:
                annotations[i].update(word_entries[norm])

    # Step 2: Multi-word phrase (trie) lookup
    # For every possible phrase start at position i (must be a word token)
    i = 0
    while i < N:
        if not types[i]:
            i += 1
            continue
        # Greedy phrase search starting at token i
        node = trie_root
        match_positions = []   # List of token indices for the current candidate
        token_indices = []
        j = i
        word_count = 0
        while j < N:
            if types[j]:
                # Word token: advance trie
                norm_tok = tokens[j].lower()
                if norm_tok not in node.children:
                    break
                node = node.children[norm_tok]
                match_positions.append(j)
                word_count += 1
                token_indices.append(j)
            else:
                # Separator: just skip in trie lookup, but keep position (important for annotation)
                token_indices.append(j)
            # After each addition: if this node completes a phrase,
            # annotate participating tokens (according to the rules)
            # Only annotate if phrase is at least 2 words
            if node.entries and word_count >= 2:
                # Who participates?
                # From i to j, but skip any leading/trailing separators
                idx_first = 0
                idx_last = len(token_indices) - 1
                # Eat leading separators
                while idx_first <= idx_last and not types[token_indices[idx_first]]:
                    idx_first += 1
                # Eat trailing separators
                while idx_last >= idx_first and not types[token_indices[idx_last]]:
                    idx_last -= 1
                # Only annotate if valid phrase
                if idx_last - idx_first + 1 > 0:
                    for idx in range(idx_first, idx_last + 1):
                        k = token_indices[idx]
                        # Annotate all, but only annotate separators if they're inner:
                        if types[k] or (idx_first < idx < idx_last):
                            annotations[k].update(node.entries)
            j += 1
        i += 1

    return list(zip(tokens, annotations))
