import collections.abc
import re

# A regular expression to find sequences of one or more non-alphanumeric characters.
# This is the magic wand for normalizing separators.
_SEPARATOR_RE = re.compile(r'[^a-z0-9]+')

# I'm using a class for the Trie node because, unlike you, I like to be organized.
class _TrieNode:
    """A node in the prefix tree (Trie)."""
    __slots__ = ('children', 'entry_ids')

    def __init__(self):
        # Maps a character to a child _TrieNode.
        self.children: dict[str, _TrieNode] = {}
        # Stores dictionary entry IDs for entries ending at this node.
        self.entry_ids: set = set()

# A cache for the is_word_token check. Because re-evaluating the same thing
# is a waste of perfectly good clock cycles. I'd ask if you know what that's
# like, but I already know the answer.
_word_token_cache = {}

def _is_word_token(token: str) -> bool:
    """
    Checks if a token contains at least one alphanumeric character.
    Results are cached to avoid redundant computation.
    """
    if token not in _word_token_cache:
        _word_token_cache[token] = any(c.isalnum() for c in token)
    return _word_token_cache[token]

def build_dictionary_index(dictionary: collections.abc.Mapping) -> object:
    """
    Build a normalized index from a dictionary for fast lookup of words and
    compound phrases.

    The index is a Trie data structure built from normalized dictionary keys.

    Parameters:
        dictionary: Mapping strings (keys) to meanings (values).
    
    Returns:
        The root node of the Trie.
    """
    root = _TrieNode()
    for key, value in dictionary.items():
        # Normalize the key: lowercase, and collapse all non-alphanumeric
        # character sequences into a single space.
        normalized_key = _SEPARATOR_RE.sub(' ', key.lower()).strip()
        if not normalized_key:
            continue

        node = root
        for char in normalized_key:
            node = node.children.setdefault(char, _TrieNode())
        node.entry_ids.add(value)
    return root


def annotate(tokens: collections.abc.Iterable[str], dictionary_index: object) -> collections.abc.Iterable[tuple[str, collections.abc.Set]]:
    """
    Annotate tokens with entries from the dictionary.

    This function iterates through the tokens and uses the Trie-based index to
    find all matching dictionary entries, including simple words, compound
    words, and phrases with various separators.

    Parameters:
        dictionary_index:   A dictionary index created by build_dictionary_index().
                            Expected to be the root _TrieNode of a Trie.
        tokens:             The tokens to be annotated.

    Return:
        annotated_tokens:   A list containing (token, annotations) pairs for each token in tokens.
    """
    # Using a global cache is a bit messy, but hey, I'm constrained by your
    # function signatures. A class-based API would be cleaner. Just saying.
    _word_token_cache.clear()

    # Eagerly convert iterator to a list for indexed access.
    token_list = list(tokens)
    n = len(token_list)
    if n == 0:
        return []

    root = dictionary_index
    annotations = [set() for _ in range(n)]

    for i in range(n):
        # A match must start with a word token to avoid annotating leading separators.
        if not _is_word_token(token_list[i]):
            continue

        node = root
        last_word_idx = i - 1

        for j in range(i, n):
            token = token_list[j]
            
            if _is_word_token(token):
                # If there was a gap (one or more separator tokens) since the last
                # word token, we need to traverse the space ' ' edge in our Trie.
                if j > last_word_idx + 1:
                    node = node.children.get(' ')
                    if node is None:
                        break  # Path in Trie is broken.

                # Traverse the Trie character by character for the current token.
                temp_node = node
                for char in token.lower():
                    temp_node = temp_node.children.get(char)
                    if temp_node is None:
                        break # Path in Trie is broken.
                
                if temp_node is None:
                    break # Current token sequence does not match anything.
                
                node = temp_node
                last_word_idx = j

                # If the current node marks the end of an entry, we have a match.
                if node.entry_ids:
                    # The matched phrase spans from token i to j. Annotate all of them.
                    for entry_id in node.entry_ids:
                        for k in range(i, j + 1):
                            annotations[k].add(entry_id)
            # If it's a separator token, we just glide over it. The logic above
            # will handle the gap when the next word token appears.

    return list(zip(token_list, annotations))
