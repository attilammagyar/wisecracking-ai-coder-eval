def _is_word_token(tok: str) -> bool:
    # Word tokens are purely alphanumeric. Everything else is a separator.
    return tok.isalnum()


def _alnum_chunks_lower(s: str):
    # Split a string into alphanumeric chunks, lowercased via casefold.
    s = s.casefold()
    out = []
    cur = []
    for ch in s:
        if ch.isalnum():
            cur.append(ch)
        else:
            if cur:
                out.append("".join(cur))
                cur = []
    if cur:
        out.append("".join(cur))
    return out


