def build_dictionary_index(dictionary: collections.abc.Mapping) -> object:
    """
    Build a normalized index from a dictionary for fast lookup of words and
    compound phrases.
    """
    exact_single = {}
    char_root = CharTrieNode()
    word_root = WordTrieNode()

    for key, entry_id in dictionary.items():
        chunks = _alnum_chunks_lower(key)
        if not chunks:
            continue
        if len(chunks) == 1:
            word = chunks[0]
            # exact map
            s = exact_single.get(word)
            if s is None:
                s = set()
                exact_single[word] = s
            s.add(entry_id)
            # char trie insert
            node = char_root
            for ch in word:
                nxt = node.children.get(ch)
                if nxt is None:
                    nxt = CharTrieNode()
                    node.children[ch] = nxt
                node = nxt
            node.ids.add(entry_id)
        else:
            # multi-word phrase: insert into word trie
            node = word_root
            for w in chunks:
                nxt = node.children.get(w)
                if nxt is None:
                    nxt = WordTrieNode()
                    node.children[w] = nxt
                node = nxt
            node.ids.add(entry_id)

    return DictionaryIndex(exact_single=exact_single, char_root=char_root, word_root=word_root)


def annotate(tokens: collections.abc.Iterable[str], dictionary_index: object) -> collections.abc.Iterable[tuple[str, collections.abc.Set]]:
    """
    Annotate tokens with entries from the dictionary.
    """
    idx = dictionary_index  # type: DictionaryIndex
    tokens = list(tokens)
    n = len(tokens)
    ann = [set() for _ in range(n)]

    if n == 0:
        return []

    # Preprocess tokens: lowercased and word/separator classification
    toks_lower = [t.casefold() for t in tokens]
    is_word = [_is_word_token(t) for t in tokens]

    # 1) Exact single-token matches
    if idx.exact_single:
        for i, wflag in enumerate(is_word):
            if not wflag:
                continue
            s = toks_lower[i]
            ids = idx.exact_single.get(s)
            if ids:
                ann[i].update(ids)

    # 2) Concatenated single-word matches across runs of consecutive word tokens (no separators)
    #    Use the character trie; accept matches only at token boundaries.
    if idx.char_root.children:
        i = 0
        while i < n:
            if not is_word[i]:
                i += 1
                continue
            # find the end of this run of consecutive word tokens
            j = i
            while j < n and is_word[j]:
                j += 1
            # run is [i, j-1]
            run_start = i
            run_end = j - 1
            # For each start within the run, stream characters through the trie
            for start in range(run_start, run_end + 1):
                node = idx.char_root
                broken = False
                for t in range(start, run_end + 1):
                    word_str = toks_lower[t]
                    for pos, ch in enumerate(word_str):
                        nxt = node.children.get(ch)
                        if nxt is None:
                            broken = True
                            break
                        node = nxt
                    if broken:
                        break
                    # At token boundary t, commit matches if any end here
                    if node.ids:
                        # annotate tokens from start..t inclusive
                        # union into each token's set
                        ids = node.ids
                        for k in range(start, t + 1):
                            ann[k].update(ids)
                # next start
            i = j

    # 3) Multi-word phrase matches via the word-sequence trie (ignore separators in between)
    if idx.word_root.children:
        # Build lists of word token positions and their values
        word_positions = [p for p, wflag in enumerate(is_word) if wflag]
        words_seq = [toks_lower[p] for p in word_positions]
        W = len(words_seq)
        for s in range(W):
            node = idx.word_root
            for e in range(s, W):
                w = words_seq[e]
                nxt = node.children.get(w)
                if nxt is None:
                    break
                node = nxt
                if node.ids:
                    # Tokens to annotate are from the first word token to the last word token (inclusive),
                    # which implicitly includes only inner separators (no leading/trailing ones).
                    left = word_positions[s]
                    right = word_positions[e]
                    ids = node.ids
                    for k in range(left, right + 1):
                        ann[k].update(ids)

    # Build result
    return [(tokens[i], ann[i]) for i in range(n)]
