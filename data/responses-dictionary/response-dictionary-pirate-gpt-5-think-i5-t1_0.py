def _is_word_token(token: str) -> bool:
    # A token is a "word" if it contains any alphanumeric char.
    # This keeps matches on token boundaries and is Unicode-friendly.
    for ch in token:
        if ch.isalnum():
            return True
    return False


def _split_words_lower(s: str) -> List[str]:
    # Split a string into lowercase alphanumeric word runs (separators ignored).
    words = []
    buf = []
    for ch in s:
        if ch.isalnum():
            buf.append(ch.lower())
        else:
            if buf:
                words.append("".join(buf))
                buf.clear()
    if buf:
        words.append("".join(buf))
    return words


def _new_trie_node() -> Dict[str, Any]:
    # Each node: {'ids': set(), 'children': dict()}
    return {'ids': set(), 'children': {}}


def build_dictionary_index(dictionary: collections.abc.Mapping) -> object:
    """
    Build a normalized index from a dictionary for fast lookup of words and
    compound phrases.

    Parameters:
        dictionary: Mapping strings (keys) to meanings (values).
    """
    word_to_ids: Dict[str, Set] = {}
    word_prefixes: Set[str] = set()
    trie_root = _new_trie_node()

    for key, entry_id in dictionary.items():
        words = _split_words_lower(str(key))
        if not words:
            continue

        if len(words) == 1:
            w = words[0]
            ids = word_to_ids.get(w)
            if ids is None:
                ids = set()
                word_to_ids[w] = ids
            ids.add(entry_id)
            # Add all prefixes for concatenation matching
            for k in range(1, len(w) + 1):
                word_prefixes.add(w[:k])
        else:
            # Insert multi-word phrase into trie
            node = trie_root
            for w in words:
                child = node['children'].get(w)
                if child is None:
                    child = _new_trie_node()
                    node['children'][w] = child
                node = child
            node['ids'].add(entry_id)

    return {
        'word_to_ids': word_to_ids,
        'word_prefixes': word_prefixes,
        'trie': trie_root,
    }


def annotate(tokens: collections.abc.Iterable[str], dictionary_index: object) -> collections.abc.Iterable[tuple[str, collections.abc.Set]]:
    """
    Annotate tokens with entries from the dictionary.

    Parameters:
        dictionary_index:   A dictionary index created by build_dictionary_index()
        tokens:             The tokens to be annotated.

    Return:
        annotated_tokens:   A list containing (token, annotations) pairs for each token in tokens.
    """
    tokens = list(tokens)
    n = len(tokens)

    word_to_ids: Dict[str, Set] = dictionary_index['word_to_ids']
    word_prefixes: Set[str] = dictionary_index['word_prefixes']
    trie_root: Dict[str, Any] = dictionary_index['trie']

    # Precompute token attributes
    is_word = [False] * n
    lower_tok = [''] * n
    for i, tok in enumerate(tokens):
        lw = tok.lower()
        lower_tok[i] = lw
        is_word[i] = _is_word_token(tok)

    # Prepare result sets
    ann: List[Set] = [set() for _ in range(n)]

    # 1) Exact single-word annotations
    for i in range(n):
        if not is_word[i]:
            continue
        ids = word_to_ids.get(lower_tok[i])
        if ids:
            ann[i].update(ids)

    # 2) Multi-word phrase annotations via trie (separator-insensitive)
    for i in range(n):
        if not is_word[i]:
            continue

        node = trie_root
        pos = i
        word_positions: List[int] = []
        inner_seps: List[int] = []

        while True:
            w = lower_tok[pos]
            child = node['children'].get(w)
            if child is None:
                break

            node = child
            word_positions.append(pos)

            # If this node ends a phrase, annotate all words seen so far and inner separators
            if node['ids']:
                ids = node['ids']
                for p in word_positions:
                    ann[p].update(ids)
                for s in inner_seps:
                    ann[s].update(ids)

            # Find next word position, collecting separators in between
            k = pos + 1
            seps_here: List[int] = []
            while k < n and not is_word[k]:
                seps_here.append(k)
                k += 1
            if k >= n:
                break  # no next word

            # Append these separators; they are "inner" only if we continue to match
            inner_seps.extend(seps_here)
            pos = k

    # 3) Single dictionary word across multiple adjacent word tokens (no separators)
    #    Use prefix pruning for efficiency.
    for i in range(n):
        if not is_word[i]:
            continue
        s = ""
        j = i
        while j < n and is_word[j]:
            s += lower_tok[j]
            ids = word_to_ids.get(s)
            if ids:
                # Annotate all tokens from i..j inclusive
                for k in range(i, j + 1):
                    ann[k].update(ids)
            if s not in word_prefixes:
                break
            j += 1

    annotated_tokens: List[Tuple[str, Set]] = [(tokens[i], ann[i]) for i in range(n)]
    return annotated_tokens
