def _normalize_and_split_key(key: str) -> list[str]:
    """
    Turns a dictionary key into a list of normalized words.
    For example, "Once  in a blue-moon!" becomes ["once", "in", "a", "blue", "moon"].
    """
    normalized_chars = []
    for char in key.lower():
        if char.isalnum():
            normalized_chars.append(char)
        else:
            # Replace any non-alnum character with a space, but only one!
            if normalized_chars and normalized_chars[-1] != ' ':
                normalized_chars.append(' ')

    # Split into words and filter out any empty strings that might result.
    return "".join(normalized_chars).split()


def build_dictionary_index(dictionary: collections.abc.Mapping) -> object:
    """
    Build a normalized index from a dictionary for fast lookup of words and
    compound phrases.

    Parameters:
        dictionary: Mapping strings (keys) to meanings (values).
    """
    root = _TrieNode()
    for key, value in dictionary.items():
        words = _normalize_and_split_key(key)
        if not words:
            continue

        node = root
        for word in words:
            if word not in node.children:
                node.children[word] = _TrieNode()
            node = node.children[word]
        node.value = value
    return root

def annotate(tokens: collections.abc.Iterable[str], dictionary_index: object) -> collections.abc.Iterable[tuple[str, collections.abc.Set]]:
    """
    Annotate tokens with entries from the dictionary.

    Parameters:
        dictionary_index:   A dictionary index created by build_dictionary_index()
        tokens:             The tokens to be annotated.

    Return:
        annotated_tokens:   A list containing (token, annotations) pairs for each token in tokens.
    """
    root = dictionary_index
    token_list = list(tokens)
    n = len(token_list)
    annotated_tokens = [(token, set()) for token in token_list]

    def is_word_token(token: str) -> bool:
        # A token is a word if it's not empty and consists of alphanumeric characters.
        return bool(token and token.isalnum())

    for i in range(n):
        # From each position `i`, we can start two types of matches:
        # 1. A phrase match, where `tokens[i]` is the first word.
        # 2. A compound word match, where `tokens[i]` is the first piece.

        # --- Phrase Matching ---
        # A phrase must start with a word token.
        if is_word_token(token_list[i]):
            node = root
            last_word_idx = -1
            # Scan forward from i to find phrases.
            for j in range(i, n):
                token = token_list[j]
                if is_word_token(token):
                    word = token.lower()
                    if word in node.children:
                        node = node.children[word]
                        last_word_idx = j
                        if node.value is not None:
                            # Found a valid phrase. Annotate all tokens from the start
                            # of the phrase `i` to the current token `j`.
                            for k in range(i, last_word_idx + 1):
                                annotated_tokens[k][1].add(node.value)
                    else:
                        # This path in the Trie is a dead end.
                        break
                # If it's a separator, we just sail past it.

        # --- Compound Word Matching ---
        # A compound word is a sequence of adjacent word tokens.
        if is_word_token(token_list[i]):
            node = root
            compound_word = ""
            # Scan forward from i, concatenating adjacent word tokens.
            for j in range(i, n):
                token = token_list[j]
                if is_word_token(token):
                    compound_word += token.lower()
                    if compound_word in node.children:
                        # This could be a complete compound word.
                        compound_node = node.children[compound_word]
                        if compound_node.value is not None:
                            # Found a valid compound word. Annotate all its constituent tokens.
                            for k in range(i, j + 1):
                                annotated_tokens[k][1].add(compound_node.value)
                else:
                    # A separator breaks a compound word.
                    break

    return annotated_tokens
