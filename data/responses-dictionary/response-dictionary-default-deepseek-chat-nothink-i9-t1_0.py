import collections.abc
import re
from typing import Dict, List, Set, Tuple, Any

# Helper to split compound phrases into words while remembering separators
def _split_phrase(phrase: str) -> Tuple[List[str], List[str]]:
    # Split into words and separators (anything not word characters)
    parts = re.split(r'(\W+)', phrase)
    words = []
    separators = []
    for part in parts:
        if not part:
            continue
        if re.match(r'^\W+$', part):
            separators.append(part)
        else:
            words.append(part.lower())
            if len(words) > 1:
                # For each new word, we have a separator before it
                if len(separators) < len(words) - 1:
                    separators.append('')  # default empty separator
    return words, separators

def build_dictionary_index(dictionary: collections.abc.Mapping) -> Dict[str, Any]:
    index = {
        'single_words': {},
        'phrases': {}
    }
    
    for phrase, meaning in dictionary.items():
        normalized_phrase = phrase.lower()
        
        # Add single word entries
        if ' ' not in phrase:
            index['single_words'][normalized_phrase] = meaning
            continue
            
        # Process compound phrases
        words, separators = _split_phrase(phrase)
        
        # Build phrase structure in the index
        current = index['phrases']
        for i, word in enumerate(words):
            if word not in current:
                current[word] = {'meanings': set(), 'next': {}}
            if i == len(words) - 1:
                current[word]['meanings'].add(meaning)
            # Store expected separator if there's a next word
            if i < len(words) - 1:
                sep_key = separators[i] if i < len(separators) else ''
                if 'separators' not in current[word]:
                    current[word]['separators'] = {}
                if sep_key not in current[word]['separators']:
                    current[word]['separators'][sep_key] = []
                current[word]['separators'][sep_key].append(current[word]['next'])
            current = current[word]['next']
    
    return index

def annotate(tokens: collections.abc.Iterable[str], dictionary_index: object) -> collections.abc.Iterable[tuple[str, collections.abc.Set]]:
    if not dictionary_index or not tokens:
        return [ (token, set()) for token in tokens ]
    
    annotated_tokens = []
    active_matches = []
    
    for token in tokens:
        # Prepare new annotations set
        annotations = set()
        
        # Check single word matches (case insensitive)
        lower_token = token.lower()
        if lower_token in dictionary_index['single_words']:
            annotations.add(dictionary_index['single_words'][lower_token])
        
        # Process active phrase matches
        new_active_matches = []
        for match in active_matches:
            node, length, meanings = match
            
            # Check if current token continues any active match
            if lower_token in node:
                next_node = node[lower_token]
                new_meanings = meanings | next_node['meanings']
                new_active_matches.append((next_node['next'], length + 1, new_meanings))
                annotations.update(new_meanings)
            # Also check if token is a separator that continues the match
            elif 'separators' in node:
                for sep, next_nodes in node['separators'].items():
                    if sep and token == sep:
                        for next_node in next_nodes:
                            new_active_matches.append((next_node, length + 1, meanings))
                            annotations.update(meanings)
        
        # Start new phrase matches from current token
        if lower_token in dictionary_index['phrases']:
            node = dictionary_index['phrases'][lower_token]
            new_active_matches.append((node['next'], 1, node['meanings']))
            annotations.update(node['meanings'])
        
        # Only keep matches that haven't exceeded max phrase length
        # (Assuming no phrase is longer than 10 words for practicality)
        active_matches = [m for m in new_active_matches if m[1] < 10]
        
        annotated_tokens.append((token, annotations))
    
    return annotated_tokens
