def _is_word_token(tok: str) -> bool:
    # A token is a "word" if it contains at least one alphanumeric character.
    # All else (spaces, punctuation, markdown, etc.) be separators.
    for ch in tok:
        if ch.isalnum():
            return True
    return False


def _normalize_key_to_symbols(key: str):
    """
    Turn a dictionary key into a sequence of symbols for the trie:
      - lowercase chars for alphanumerics
      - a single _SEP for any run of non-alphanumerics
    Leading/trailing _SEP are removed; internal runs are collapsed.
    """
    s = key.casefold()
    symbols = []
    prev_sep = False
    for ch in s:
        if ch.isalnum():
            symbols.append(ch)
            prev_sep = False
        else:
            if not prev_sep:
                symbols.append(_SEP)
                prev_sep = True
            # else keep collapsing
    # Drop leading/trailing SEP
    while symbols and symbols[0] is _SEP:
        symbols.pop(0)
    while symbols and symbols[-1] is _SEP:
        symbols.pop()
    return symbols


