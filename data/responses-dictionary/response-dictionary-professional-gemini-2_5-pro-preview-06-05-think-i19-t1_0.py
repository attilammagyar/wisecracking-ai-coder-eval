import collections.abc
import re

class _TrieNode:
    """A node in the phrase Trie."""
    def __init__(self):
        self.children = {}
        self.values = set()

class _DictionaryIndex:
    """
    A container for the structured dictionary data.
    - word_dict: For single words and compound words (no separators).
                 Maps a normalized string to a set of dictionary entry IDs.
    - phrase_trie_root: A Trie for compound phrases (with separators).
                        The path in the trie is made of word components.
    """
    def __init__(self):
        self.word_dict = {}
        self.phrase_trie_root = _TrieNode()

def build_dictionary_index(dictionary: collections.abc.Mapping) -> object:
    """
    Build a normalized index from a dictionary for fast lookup of words and
    compound phrases.

    Parameters:
        dictionary: Mapping strings (keys) to meanings (values).
    """
    index = _DictionaryIndex()

    for key, value in dictionary.items():
        # A key is a "phrase" if it contains any non-alphanumeric character.
        # Otherwise, it's a "word" (single or compound).
        is_phrase = any(not char.isalnum() for char in key)
        norm_key = key.lower()

        if is_phrase:
            # Add to phrase_trie. Word parts are sequences of alphanumeric chars.
            parts = [part for part in re.split(r'\W+', norm_key) if part]
            if not parts:
                continue

            node = index.phrase_trie_root
            for part in parts:
                node = node.children.setdefault(part, _TrieNode())
            node.values.add(value)
        else:
            # Add to word_dict.
            index.word_dict.setdefault(norm_key, set()).add(value)

    return index

def annotate(tokens: collections.abc.Iterable[str], dictionary_index: object) -> collections.abc.Iterable[tuple[str, collections.abc.Set]]:
    """
    Annotate tokens with entries from the dictionary.

    Parameters:
        dictionary_index:   A dictionary index created by build_dictionary_index()
        tokens:             The tokens to be annotated.

    Return:
        annotated_tokens:   A list containing (token, annotations) pairs for each token in tokens.
    """
    if not isinstance(dictionary_index, _DictionaryIndex):
        raise TypeError("dictionary_index is not of the expected type.")

    token_list = list(tokens)
    n = len(token_list)
    annotated_tokens = [(token, set()) for token in token_list]
    if n == 0:
        return annotated_tokens

    # --- Pass 1: Match single and compound words (e.g., "cat", "blackswan") ---
    for i in range(n):
        if not token_list[i].isalnum():
            continue

        concatenated_str = ""
        # Lookahead from `i` to form compound words from consecutive word-like tokens.
        for j in range(i, n):
            token = token_list[j]
            if not token.isalnum():
                break

            concatenated_str += token
            norm_word = concatenated_str.lower()

            if norm_word in dictionary_index.word_dict:
                # Found a match spanning from token `i` to `j`.
                values = dictionary_index.word_dict[norm_word]
                for k in range(i, j + 1):
                    annotated_tokens[k][1].update(values)

    # --- Pass 2: Match compound phrases (e.g., "black cat") ---
    for i in range(n):
        if not token_list[i].isalnum():
            continue

        # Start a trie traversal for phrases beginning with the word at token `i`.
        node = dictionary_index.phrase_trie_root
        word_indices = []

        # Scan forward from `i`, picking up word-like tokens to follow a trie path.
        for j in range(i, n):
            token = token_list[j]
            if not token.isalnum():
                continue

            word_part = token.lower()
            current_trie_node = node if word_indices else dictionary_index.phrase_trie_root

            if word_part not in current_trie_node.children:
                break # This path in the trie is not valid.

            node = current_trie_node.children[word_part]
            word_indices.append(j)

            if node.values:
                # Found a valid phrase. Annotate all tokens from its first
                # word-like token to its last, including inner separators.
                start_annot_idx = word_indices[0]
                end_annot_idx = word_indices[-1]
                for k in range(start_annot_idx, end_annot_idx + 1):
                    annotated_tokens[k][1].update(node.values)

    return annotated_tokens
