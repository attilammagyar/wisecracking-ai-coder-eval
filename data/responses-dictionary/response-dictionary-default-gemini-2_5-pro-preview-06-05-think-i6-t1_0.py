def _is_word(token: str) -> bool:
    """
    Determines if a token is a "word" by checking for the presence of any
    alphanumeric character. This helps distinguish words from pure separators
    like " ", "*", or ".".
    """
    return any(c.isalnum() for c in token)


def build_dictionary_index(dictionary: collections.abc.Mapping) -> object:
    """
    Build a normalized index from a dictionary for fast lookup of words and
    compound phrases.

    The index is a dictionary containing two maps:
    - 'words': For dictionary entries that are single words or compound words
               without separators (e.g., "cat", "blackswan"). Keys are lowercased.
    - 'phrases': For dictionary entries that contain separators (e.g.,
                 "black swan", "once-in-a-lifetime"). Keys are normalized by
                 extracting word components, lowercasing them, and joining
                 with single spaces.

    This structure allows the annotation algorithm to efficiently handle
    different matching rules.

    Parameters:
        dictionary: Mapping strings (keys) to meanings (values).
    """
    phrase_map = {}
    word_map = {}

    for key, value in dictionary.items():
        # A key is treated as a phrase if it contains any non-alphanumeric
        # characters, which are assumed to be separators.
        if any(not c.isalnum() for c in key):
            # Normalize the phrase by finding all sequences of alphanumeric
            # characters, converting them to lowercase, and joining with spaces.
            word_parts = re.findall(r'[a-zA-Z0-9]+', key.lower())
            if word_parts:
                normalized_phrase = " ".join(word_parts)
                phrase_map[normalized_phrase] = value
        else:
            # The key is a single word or a compound word without separators.
            # It's stored lowercased in the word map.
            word_map[key.lower()] = value
            
    return {'phrases': phrase_map, 'words': word_map}


