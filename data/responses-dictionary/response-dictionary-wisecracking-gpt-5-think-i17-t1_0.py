import collections.abc

# Internal trie node helper
def _make_node():
    # 'c' = children, 't' = terminal entries (set of dictionary IDs)
    return {"c": {}, "t": set()}

def _is_word_char(ch: str) -> bool:
    return ch.isalnum()

def _split_words_lower(s: str) -> list[str]:
    # Split by non-word chars, keep only alnum runs, lowercased
    words = []
    cur = []
    for ch in s:
        if _is_word_char(ch):
            cur.append(ch.lower())
        else:
            if cur:
                words.append("".join(cur))
                cur = []
    if cur:
        words.append("".join(cur))
    return words

def build_dictionary_index(dictionary: collections.abc.Mapping) -> object:
    """
    Build a normalized index from a dictionary for fast lookup of words and
    compound phrases.

    Parameters:
        dictionary: Mapping strings (keys) to meanings (values).
    """
    word_trie = _make_node()   # trie over words: children keys are words
    char_trie = _make_node()   # trie over characters: children keys are chars

    for key, entry_id in dictionary.items():
        words = _split_words_lower(key)
        if not words:
            continue
        if len(words) == 1:
            # Insert into char trie for single-word entries (to allow spanning multiple tokens)
            node = char_trie
            for ch in words[0]:
                node = node["c"].setdefault(ch, _make_node())
            node["t"].add(entry_id)
        else:
            # Insert into word trie for multi-word phrases
            node = word_trie
            for w in words:
                node = node["c"].setdefault(w, _make_node())
            node["t"].add(entry_id)

    return {"word_trie": word_trie, "char_trie": char_trie}

def annotate(tokens: collections.abc.Iterable[str], dictionary_index: object) -> collections.abc.Iterable[tuple[str, collections.abc.Set]]:
    """
    Annotate tokens with entries from the dictionary.

    Parameters:
        dictionary_index:   A dictionary index created by build_dictionary_index()
        tokens:             The tokens to be annotated.

    Return:
        annotated_tokens:   A list containing (token, annotations) pairs for each token in tokens.
    """
    tokens = list(tokens)
    n = len(tokens)
    if n == 0:
        return []

    word_trie = dictionary_index["word_trie"]
    char_trie = dictionary_index["char_trie"]

    # Classify tokens and prepare lowercase for word tokens
    def is_word_token(tok: str) -> bool:
        # Word token = non-empty and all chars are alphanumeric
        return bool(tok) and all(_is_word_char(c) for c in tok)

    is_word = [is_word_token(t) for t in tokens]
    tokens_lower = [t.lower() if is_word[i] else t for i, t in enumerate(tokens)]

    # Prepare output sets per token
    anns = [set() for _ in range(n)]

    # 1) Single-word entries (including matches spanning multiple adjacent word tokens)
    #    Use char trie over concatenated characters of consecutive word tokens.
    for i in range(n):
        if not is_word[i]:
            continue
        node = char_trie
        j = i
        dead = False
        while j < n and is_word[j] and not dead:
            t = tokens_lower[j]
            # consume the entire token's characters
            for ch in t:
                nxt = node["c"].get(ch)
                if nxt is None:
                    dead = True
                    break
                node = nxt
            if dead:
                break
            # Only record matches at token boundaries (i.e., after finishing j-th token)
            if node["t"]:
                for entry_id in node["t"]:
                    for k in range(i, j + 1):
                        anns[k].add(entry_id)
            j += 1

    # 2) Multi-word phrases (word-trie), insensitive to the separators between words.
    #    We traverse only word tokens but annotate the full span including inner separators.
    word_positions = [idx for idx in range(n) if is_word[idx]]
    for p, start_idx in enumerate(word_positions):
        node = word_trie
        for q in range(p, len(word_positions)):
            widx = word_positions[q]
            w = tokens_lower[widx]
            nxt = node["c"].get(w)
            if nxt is None:
                break
            node = nxt
            if node["t"]:
                # Annotate from first word token to last word token inclusive,
                # which includes only the inner separators by construction.
                end_idx = word_positions[q]
                for entry_id in node["t"]:
                    for k in range(start_idx, end_idx + 1):
                        anns[k].add(entry_id)

    annotated_tokens = [(tokens[i], anns[i]) for i in range(n)]
    return annotated_tokens
