def _dict_key_to_words(key):
    # Crack the dictionary key into a list o' lowercased words
    return [w.lower() for w in key.split() if w.strip() != ""]

def build_dictionary_index(dictionary: collections.abc.Mapping) -> object:
    """
    Build a normalized trie index from a dictionary for fast lookup of words and
    compound phrases.
    """
    root = TrieNode()
    for key, entry_id in dictionary.items():
        words = _dict_key_to_words(key)
        if not words:
            continue  # Ignore empty entries
        node = root
        for word in words:
            if word not in node.children:
                node.children[word] = TrieNode()
            node = node.children[word]
        node.entries.add(entry_id)
    return root

