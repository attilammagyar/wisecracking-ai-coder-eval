import collections.abc
import re

# ARR! Helper to split to (word/non-word) tokens, tolerant of all pirate oddities
def _tokenize_phrase(phrase):
    # Splits by \w+ and non-\w+
    return [t for t in re.findall(r"\w+|[^\w]+", phrase) if t]

# TrieNode class fer phrase matches
class TrieNode:
    __slots__ = ("children", "entries")
    def __init__(self):
        self.children = dict()   # token (str) -> TrieNode
        self.entries = set()     # set of entry ids

def build_dictionary_index(dictionary: collections.abc.Mapping) -> object:
    """
    Build a normalized index from a dictionary fer fast lookup o' words and compound phrases.
    """
    casefold = str.casefold # in py3.3+, properly Unicode
    single = collections.defaultdict(set)   # word -> set(ids)
    root = TrieNode()

    for phrase, entry in dictionary.items():
        tokens = _tokenize_phrase(phrase)
        lowered = [tok.casefold() if re.match(r"\w+$", tok) else tok for tok in tokens]
        # insert to trie
        node = root
        for tok in lowered:
            if tok not in node.children:
                node.children[tok] = TrieNode()
            node = node.children[tok]
        node.entries.add(entry)
        # put single token entries for non-separator single tokens
        if len(lowered) == 1 and re.match(r"\w+$", lowered[0]):
            single[lowered[0]].add(entry)

    return {"single": dict(single), "trie": root}

def annotate(tokens: collections.abc.Iterable[str], dictionary_index: object) -> collections.abc.Iterable[tuple[str, collections.abc.Set]]:
    """
    Annotate tokens with entries from the dictionary.
    """
    # Prepare crew! Convert tokens to list ('tis used a lot)
    tokens = list(tokens)
    N = len(tokens)
    # We'll be collectin' all annotations per token
    annotations = [set() for _ in range(N)]
    # For quick access
    single = dictionary_index["single"]
    trie = dictionary_index["trie"]

    # Determine word vs separator ahead o' time
    def is_word(tok):
        return bool(re.match(r"\w+$", tok))

    # Build a casefolded cache o' tokens so we only casefold once
    lowered = [tok.casefold() if is_word(tok) else tok for tok in tokens]

    # First, mark single-word matches
    for i, tok in enumerate(lowered):
        if is_word(tok):
            if tok in single:
                annotations[i].update(single[tok])

    # Now do phrase matching using the trie
    for start in range(N):
        # Words be able to start phrases, never separators ('ceptin' a phrase that starts with a separator, which is fair game)
        node = trie
        idx = start
        matched = []
        while idx < N:
            tok = lowered[idx]
            if tok in node.children:
                node = node.children[tok]
                matched.append(idx)
                # Check for complete phrase match at this point
                if node.entries:
                    # Determine phrase window
                    # For phrase ["AAA", " ", "BBB"] matched at indices [0,1,2]:
                    # annotate: tokens 0,1,2 (all), but ONLY inner separators; if match starts/ends at a separator, that's leading/trailing!
                    left, right = start, idx
                    # Determine which tokens be "inner" for separator annotation
                    # Outer separators: if left == start and is separator; if right == idx and is separator.
                    # For annotation, all tokens get the entry, but in rule 3: "separators in a compound phrase should also be annotated, but only the inner ones, never the leading or trailing separators"
                    # So: for each matched idx,
                    # if it's a word: always annotate
                    # if it's a separator: annotate only if it's not the first/last in group
                    for j in matched:
                        if is_word(lowered[j]):
                            annotations[j].update(node.entries)
                        else:
                            if j != matched[0] and j != matched[-1]:
                                annotations[j].update(node.entries)
                idx += 1
            else:
                break

    return [(tokens[i], annotations[i]) for i in range(N)]
