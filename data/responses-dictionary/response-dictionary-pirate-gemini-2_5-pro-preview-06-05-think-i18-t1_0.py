import collections.abc
import re
from collections import deque

# A special object to represent a separator in the trie. It's a unique sentinel
# value that won't be confused with any string.
_SEP = object()

class _TrieNode:
    """A node in our custom Trie for token sequences."""
    def __init__(self):
        # Children nodes, keyed by a word (str) or the _SEP object.
        self.children: dict[str | object, _TrieNode] = {}
        # Set of dictionary values for entries ending at this node.
        self.values: set = set()

def _tokenize_key(key: str) -> list[str | object]:
    """
    Converts a dictionary key string into a canonical list of words and
    separator markers (_SEP). This is the heart of the normalization logic.
    """
    lkey = key.lower()
    # Find all sequences of alphanumeric characters (words).
    words = re.findall(r'[a-zA-Z0-9]+', lkey)

    # If the key is just a single alphanumeric word, the token is the key itself.
    # This distinguishes "bluemoon" from "blue moon".
    if len(words) == 1 and words[0] == lkey:
        return [lkey]

    # If the key contains separators, we represent them with _SEP.
    # We create a list of words interleaved with the _SEP marker.
    # E.g., "word1-word2" -> ['word1', _SEP, 'word2']
    result = []
    if not words:
        return []

    for word in words:
        result.append(word)
        result.append(_SEP)

    # A key like "word1 word2" becomes ['word1', _SEP, 'word2', _SEP],
    # so we chop off the trailing separator.
    return result[:-1]

def build_dictionary_index(dictionary: collections.abc.Mapping) -> object:
    """
    Build a normalized index from a dictionary for fast lookup of words and
    compound phrases.

    Parameters:
        dictionary: Mapping strings (keys) to meanings (values).
    """
    root = _TrieNode()
    for key, value in dictionary.items():
        if not key:
            continue

        tokenized_key = _tokenize_key(key)
        node = root
        for part in tokenized_key:
            if part not in node.children:
                node.children[part] = _TrieNode()
            node = node.children[part]
        node.values.add(value)
    return root

def annotate(tokens: collections.abc.Iterable[str], dictionary_index: object) -> collections.abc.Iterable[tuple[str, collections.abc.Set]]:
    """
    Annotate tokens with entries from the dictionary.

    Parameters:
        dictionary_index:   A dictionary index created by build_dictionary_index()
        tokens:             The tokens to be annotated.

    Return:
        annotated_tokens:   A list containing (token, annotations) pairs for each token in tokens.
    """
    tokens = list(tokens)
    if not tokens:
        return []

    root = dictionary_index
    annotated_tokens = [(token, set()) for token in tokens]
    n = len(tokens)

    for i in range(n):
        # We start a new search from every token to find all possible matches,
        # including overlapping ones.
        # The queue holds tuples for a Breadth-First Search:
        # (current_token_idx, current_trie_node, list_of_matched_token_indices)
        q = deque([(i, root, [])])

        # A visited set to avoid redundant searches from the same state.
        # A state is defined by the token index and the trie node.
        # id(node) is used to make the node hashable.
        visited = set([(i, id(root))])

        while q:
            tok_idx, node, matched_indices = q.popleft()

            # If the current trie node holds values, we've found a match.
            # We add the values to the annotations of all tokens in the match.
            if node.values:
                for value in node.values:
                    for matched_tok_idx in matched_indices:
                        annotated_tokens[matched_tok_idx][1].add(value)

            if tok_idx >= n:
                continue

            # --- Exploration Step from the current state ---

            # 1. Try to match a sequence of one or more WORD tokens.
            #    This handles single words ("swan"), and also compound words
            #    formed by concatenating tokens (e.g., 'AAABBB' from ['AAA', 'BBB']).
            concatenated_word = ""
            current_word_indices = []
            for j in range(tok_idx, n):
                token = tokens[j]
                if not token.isalnum():
                    break  # Word sequence is broken by a separator.

                concatenated_word += token.lower()
                current_word_indices.append(j)

                if concatenated_word in node.children:
                    next_node = node.children[concatenated_word]
                    next_tok_idx = j + 1
                    if (next_tok_idx, id(next_node)) not in visited:
                        q.append((next_tok_idx, next_node, matched_indices + current_word_indices))
                        visited.add((next_tok_idx, id(next_node)))

            # 2. Try to match a sequence of one or more SEPARATOR tokens.
            #    Any such sequence corresponds to a single _SEP marker in the trie.
            if _SEP in node.children:
                # Find the end of the current block of separator tokens.
                j = tok_idx
                while j < n and not tokens[j].isalnum():
                    j += 1

                # If we found at least one separator token...
                if j > tok_idx:
                    next_node = node.children[_SEP]
                    next_tok_idx = j
                    if (next_tok_idx, id(next_node)) not in visited:
                        separator_indices = list(range(tok_idx, j))
                        q.append((next_tok_idx, next_node, matched_indices + separator_indices))
                        visited.add((next_tok_idx, id(next_node)))

    return annotated_tokens
