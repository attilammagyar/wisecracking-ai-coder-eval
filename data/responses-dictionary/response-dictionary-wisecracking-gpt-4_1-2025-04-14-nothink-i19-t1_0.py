def build_dictionary_index(dictionary: collections.abc.Mapping):
    """
    Build a normalized index (trie) from a dictionary for fast lookup of words and compound phrases.
    """

    # Define what is a "word" token: assume token is "word" if it has any unicode alphanum
    def is_word(token):
        return any(ch.isalnum() for ch in token)
    
    # Helper to tokenize and normalize phrase string ('AAA, BBB' -> ['aaa', SEP, 'bbb'])
    SEP = "<SEP>"  # internal separator marker

    def phrase_tokens(phrase):
        # Collapse all runs of non-word into single SEP between word groups
        out = []
        acc = ""
        for ch in phrase:
            if ch.isalnum():
                acc += ch
            else:
                if acc:
                    out.append(acc.lower())
                    acc = ""
                # only append a single SEP for each group of non-word chars
                if not out or out[-1] != SEP:
                    out.append(SEP)
        if acc:
            out.append(acc.lower())
        # Remove leading/trailing SEP (for phrases like " AAA " or ",AAA,")
        if out and out[0] == SEP:
            out = out[1:]
        if out and out[-1] == SEP:
            out = out[:-1]
        return out

    # Build a trie for [normalized tokens/SEPs] -> set(entry_ids)
    trie = {}
    entry_ends = collections.defaultdict(set)
    maxlen = 1  # track max phrase len for later optimization

    for phrase, entry_id in dictionary.items():
        toks = phrase_tokens(phrase)
        maxlen = max(maxlen, len(toks))
        cur = trie
        for t in toks:
            if t not in cur:
                cur[t] = {}
            cur = cur[t]
        # Mark phrase-end here
        cur.setdefault("_ends", set()).add(entry_id)

    # We want: 
    # - trie (nested dicts),
    # - is_word function,
    # - phrase_tokens for annotation lookup
    return {
        "trie": trie,
        "is_word": is_word,
        "maxlen": maxlen,
        "phrase_tokens": phrase_tokens,
    }

