def _get_word_parts(text: str) -> list[str]:
    """
    Normalizes and splits a dictionary key into its constituent word parts.
    It converts text to lowercase and extracts sequences of word characters.
    Example: "Black Swan, Event" -> ['black', 'swan', 'event']
             "blackswan" -> ['blackswan']
    """
    # \w+ matches one or more word characters (alphanumeric + underscore).
    return re.findall(r'\w+', text.lower())

