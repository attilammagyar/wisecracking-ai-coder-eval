class TrieNode:
    def __init__(self):
        self.children = {}
        self.entries = set()  # Dictionary entries that end at this node

def build_dictionary_index(dictionary: collections.abc.Mapping) -> object:
    """
    Build a normalized index from a dictionary for fast lookup of words and
    compound phrases.

    Parameters:
        dictionary: Mapping strings (keys) to meanings (values).
    """
    root = TrieNode()
    
    for phrase, entry_id in dictionary.items():
        # Normalize the phrase: split into words, convert to lowercase
        words = []
        current_word = []
        
        for char in phrase:
            if char.isalpha():
                current_word.append(char.lower())
            elif current_word:
                words.append(''.join(current_word))
                current_word = []
        
        if current_word:
            words.append(''.join(current_word))
        
        # Insert into trie
        if words:
            node = root
            for word in words:
                if word not in node.children:
                    node.children[word] = TrieNode()
                node = node.children[word]
            node.entries.add(entry_id)
    
    return root

