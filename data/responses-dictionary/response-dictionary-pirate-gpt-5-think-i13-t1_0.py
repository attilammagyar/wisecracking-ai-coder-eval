import collections.abc

class _TrieNode:
    __slots__ = ("ids", "kids")
    def __init__(self):
        self.ids = set()            # set of entry IDs ending here
        self.kids = {}              # dict[word: str -> _TrieNode]


def _split_words_casefold(s: str) -> list[str]:
    # Keep only alphanumeric runs as "words", ignore separators.
    words = []
    cur = []
    for ch in s:
        if ch.isalnum():
            cur.append(ch)
        elif cur:
            words.append(''.join(cur).casefold())
            cur = []
    if cur:
        words.append(''.join(cur).casefold())
    return words


def build_dictionary_index(dictionary: collections.abc.Mapping) -> object:
    """
    Build a normalized index (trie) from a dictionary for fast lookup of words and phrases.
    Case-insensitive, separator-insensitive (in dictionary keys).
    """
    root = _TrieNode()
    for key, value in dictionary.items():
        words = _split_words_casefold(key)
        if not words:
            continue
        node = root
        for w in words:
            nxt = node.kids.get(w)
            if nxt is None:
                nxt = _TrieNode()
                node.kids[w] = nxt
            node = nxt
        node.ids.add(value)
    return root


def annotate(tokens: collections.abc.Iterable[str], dictionary_index: object) -> collections.abc.Iterable[tuple[str, collections.abc.Set]]:
    """
    Annotate tokens with entries from the dictionary index.
    """
    toks = list(tokens)
    n = len(toks)
    annotations = [set() for _ in range(n)]

    # Classify into blocks: ('W' or 'S', start_idx, end_idx, word_string_if_W_else_None)
    blocks = []
    i = 0
    while i < n:
        t = toks[i]
        if t.isalnum():  # word token
            start = i
            parts = []
            while i < n and toks[i].isalnum():
                parts.append(toks[i].casefold())
                i += 1
            word_str = ''.join(parts)
            blocks.append(('W', start, i - 1, word_str))
        else:
            start = i
            while i < n and (not toks[i].isalnum()):
                i += 1
            blocks.append(('S', start, i - 1, None))

    # Helper: add ids to all tokens spanning blocks [b0..b1]
    def add_ids_over_blocks(ids, b0, b1):
        for bi in range(b0, b1 + 1):
            _, s, e, _ = blocks[bi]
            for ti in range(s, e + 1):
                annotations[ti].update(ids)

    root = dictionary_index  # _TrieNode

    # Walk the trie starting at each W block.
    for b_idx, (kind, s, e, wstr) in enumerate(blocks):
        if kind != 'W':
            continue
        node = root.kids.get(wstr)
        if node is None:
            continue

        end_block = b_idx
        if node.ids:
            add_ids_over_blocks(node.ids, b_idx, end_block)

        # Extend across alternating S then W blocks
        while True:
            next_w_block = end_block + 2
            if next_w_block >= len(blocks):
                break
            if blocks[end_block + 1][0] != 'S' or blocks[next_w_block][0] != 'W':
                break
            next_wstr = blocks[next_w_block][3]
            child = node.kids.get(next_wstr)
            if child is None:
                break
            node = child
            end_block = next_w_block
            if node.ids:
                add_ids_over_blocks(node.ids, b_idx, end_block)

    # Return (token, annotations_set) for each token
    return [(toks[i], annotations[i]) for i in range(n)]
