import collections.abc
import re

def build_dictionary_index(dictionary: collections.abc.Mapping) -> object:
    """
    Build a normalized index from a dictionary for fast lookup of words and
    compound phrases.

    Parameters:
        dictionary: Mapping strings (keys) to meanings (values).
    """
    # Separate single words from phrases
    single_words = {}  # normalized_word -> set of entry IDs
    phrases = []  # list of (normalized_words_list, separator_pattern, entry_id)
    
    for key, value in dictionary.items():
        # Split by word boundaries
        parts = re.split(r'(\W+)', key)
        words = [p for p in parts if p and re.match(r'\w', p)]
        
        if len(words) == 1:
            # Single word
            normalized = words[0].lower()
            if normalized not in single_words:
                single_words[normalized] = set()
            single_words[normalized].add(value)
        else:
            # Phrase
            normalized_words = [w.lower() for w in words]
            phrases.append((normalized_words, value))
    
    return {
        'single_words': single_words,
        'phrases': phrases
    }

def annotate(tokens: collections.abc.Iterable[str], dictionary_index: object) -> collections.abc.Iterable[tuple[str, collections.abc.Set]]:
    """
    Annotate tokens with entries from the dictionary.

    Parameters:
        dictionary_index:   A dictionary index created by build_dictionary_index()
        tokens:             The tokens to be annotated.

    Return:
        annotated_tokens:   A list containing (token, annotations) pairs for each token in tokens.
    """
    tokens = list(tokens)
    n = len(tokens)
    annotations = [set() for _ in range(n)]
    
    if n == 0:
        return []
    
    single_words = dictionary_index['single_words']
    phrases = dictionary_index['phrases']
    
    def is_word_token(token):
        return bool(token and re.match(r'\w', token))
    
    # Annotate single words
    for i, token in enumerate(tokens):
        if is_word_token(token):
            normalized = token.lower()
            if normalized in single_words:
                annotations[i].update(single_words[normalized])
    
    # Find compound words (adjacent word tokens)
    i = 0
    while i < n:
        if is_word_token(tokens[i]):
            # Start of a potential compound word
            j = i
            compound = tokens[i]
            while j + 1 < n and is_word_token(tokens[j + 1]):
                j += 1
                compound += tokens[j]
            
            # Check if this compound exists in single_words
            normalized_compound = compound.lower()
            if normalized_compound in single_words:
                for k in range(i, j + 1):
                    annotations[k].update(single_words[normalized_compound])
            
            i = j + 1
        else:
            i += 1
    
    # Find phrases
    for phrase_words, entry_id in phrases:
        phrase_len = len(phrase_words)
        
        # Try to match phrase starting at each position
        for start_pos in range(n):
            if not is_word_token(tokens[start_pos]):
                continue
                
            # Try to match the phrase
            word_positions = []
            word_idx = 0
            pos = start_pos
            
            while pos < n and word_idx < phrase_len:
                if is_word_token(tokens[pos]):
                    if tokens[pos].lower() == phrase_words[word_idx]:
                        word_positions.append(pos)
                        word_idx += 1
                    else:
                        break
                pos += 1
            
            # Check if we matched all words
            if word_idx == phrase_len:
                # Annotate all tokens in the phrase (including separators)
                # But not leading/trailing separators
                first_word_pos = word_positions[0]
                last_word_pos = word_positions[-1]
                
                for k in range(first_word_pos, last_word_pos + 1):
                    annotations[k].add(entry_id)
    
    return [(token, annot) for token, annot in zip(tokens, annotations)]
