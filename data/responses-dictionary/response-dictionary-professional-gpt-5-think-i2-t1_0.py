def _split_words(s: str) -> List[str]:
    """Split a string into alphanumeric word runs, lowercased via casefold()."""
    s = s.casefold()
    words = []
    start = -1
    for i, ch in enumerate(s):
        if ch.isalnum():
            if start < 0:
                start = i
        else:
            if start >= 0:
                words.append(s[start:i])
                start = -1
    if start >= 0:
        words.append(s[start:])
    return words


def _is_word_token(token: str) -> bool:
    """A token is a 'word token' if it consists only of alphanumeric chars and is non-empty."""
    if not token:
        return False
    return all(c.isalnum() for c in token)


