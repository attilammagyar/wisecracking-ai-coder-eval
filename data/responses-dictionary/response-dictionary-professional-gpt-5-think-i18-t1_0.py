import collections.abc

# Helper: classify tokens. A "word" token has at least one alphanumeric char.
def _is_word_token(tok: str) -> bool:
    for ch in tok:
        if ch.isalnum():
            return True
    return False

# Helper: extract normalized words from a dictionary key (case-insensitive).
def _extract_words(text: str):
    words = []
    cur = []
    for ch in text:
        if ch.isalnum():
            cur.append(ch.lower())
        else:
            if cur:
                words.append("".join(cur))
                cur = []
    if cur:
        words.append("".join(cur))
    return words


class _TrieNode:
    __slots__ = ("children", "ids")
    def __init__(self):
        self.children = {}  # word -> _TrieNode
        self.ids = set()    # set of dictionary entry ids ending here


def build_dictionary_index(dictionary: collections.abc.Mapping) -> object:
    """
    Build a normalized index from a dictionary for fast lookup of words and
    compound phrases.

    Parameters:
        dictionary: Mapping strings (keys) to meanings (values).
    """
    root = _TrieNode()
    single_word_map = {}   # normalized single word -> set(ids)
    single_prefixes = set()  # prefixes of single-word entries (including full word)

    for key, val in dictionary.items():
        words = _extract_words(key)
        if not words:
            continue
        if len(words) == 1:
            w = words[0]
            s = single_word_map.get(w)
            if s is None:
                s = set()
                single_word_map[w] = s
            s.add(val)
            # Add all prefixes including full word to allow extension during concatenation.
            for i in range(1, len(w) + 1):
                single_prefixes.add(w[:i])
        else:
            # Insert into multi-word trie
            node = root
            for w in words:
                child = node.children.get(w)
                if child is None:
                    child = _TrieNode()
                    node.children[w] = child
                node = child
            node.ids.add(val)

    return {
        "root": root,
        "single_map": single_word_map,
        "single_prefixes": single_prefixes,
    }


def annotate(tokens: collections.abc.Iterable[str], dictionary_index: object) -> collections.abc.Iterable[tuple[str, collections.abc.Set]]:
    """
    Annotate tokens with entries from the dictionary.

    Parameters:
        dictionary_index:   A dictionary index created by build_dictionary_index()
        tokens:             The tokens to be annotated.

    Return:
        annotated_tokens:   A list containing (token, annotations) pairs for each token in tokens.
    """
    toks = list(tokens)
    n = len(toks)
    anns = [set() for _ in range(n)]
    if n == 0:
        return []

    root = dictionary_index["root"]
    single_map = dictionary_index["single_map"]
    single_prefixes = dictionary_index["single_prefixes"]

    is_word = [_is_word_token(t) for t in toks]
    lower_tok = [t.lower() if is_word[i] else None for i, t in enumerate(toks)]

    # Collect positions of word tokens.
    word_pos = [i for i, w in enumerate(is_word) if w]

    # 1) Single-word entries (including concatenation across adjacent word tokens with no separators).
    i = 0
    while i < n:
        if not is_word[i]:
            i += 1
            continue
        # Find maximal run of consecutive word tokens [i, j]
        j = i
        while j + 1 < n and is_word[j + 1]:
            j += 1
        # For each start k in [i..j], grow concatenation up to j
        for k in range(i, j + 1):
            s = ""
            for m in range(k, j + 1):
                s += lower_tok[m]
                # Stop early if no single-word can start with this prefix
                if s not in single_prefixes:
                    break
                # If exactly a single-word entry, annotate tokens [k..m]
                ids = single_map.get(s)
                if ids:
                    for x in range(k, m + 1):
                        anns[x].update(ids)
        i = j + 1

    # 2) Multi-word phrases via trie (require at least one separator between consecutive dictionary words).
    L = len(word_pos)
    for wi_start in range(L):
        start_tok_idx = word_pos[wi_start]
        node = root

        # Step through words starting from wi_start
        wi = wi_start
        prev_tok_idx = None
        while wi < L:
            tok_idx = word_pos[wi]
            w = lower_tok[tok_idx]
            child = node.children.get(w)
            if child is None:
                break
            node = child
            # For phrases, we need at least 2 words; however we inserted into trie only for len >= 2,
            # so node.ids will be non-empty only after the second (or later) word.
            if node.ids:
                # Annotate span from first word to current word (inclusive): includes only inner separators.
                for t in range(start_tok_idx, tok_idx + 1):
                    anns[t].update(node.ids)
            # Prepare to move to next word; ensure at least one separator between consecutive words.
            prev_tok_idx = tok_idx
            wi_next = wi + 1
            if wi_next >= L:
                break
            next_tok_idx = word_pos[wi_next]
            # Require there to be at least one separator between prev and next words.
            if next_tok_idx == prev_tok_idx + 1:
                break
            wi = wi_next

    return [(toks[i], anns[i]) for i in range(n)]
