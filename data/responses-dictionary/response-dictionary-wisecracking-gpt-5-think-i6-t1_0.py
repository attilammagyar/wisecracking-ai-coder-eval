import collections.abc

def _is_word_token(tok: str) -> bool:
    # A "word token" is entirely alphanumeric (letters/digits). Everything else is a separator.
    # This keeps logic simple and aligns with tests.
    return tok.isalnum()


def _extract_words(s: str) -> list[str]:
    """
    Split a dictionary key into lowercase word segments (contiguous alnum runs).
    Separators are discarded; we only track word chunks to define required structure.
    """
    words = []
    buf = []
    in_word = False
    for ch in s:
        if ch.isalnum():
            if not in_word:
                # switching from sep to word
                in_word = True
                buf = [ch.lower()]
            else:
                buf.append(ch.lower())
        else:
            if in_word:
                words.append("".join(buf))
                buf = []
                in_word = False
            # else: still in separators; ignore
    if in_word and buf:
        words.append("".join(buf))
    return words


def build_dictionary_index(dictionary: collections.abc.Mapping) -> object:
    """
    Build a normalized index from a dictionary for fast lookup of words and
    compound phrases.

    Parameters:
        dictionary: Mapping strings (keys) to meanings (values).
    """
    # Index 1: direct single-word lookup (token -> set(ids))
    single_word_map = {}
    # Index 2: first-word -> list of (tuple(words), id)
    first_word_index = {}

    for key, entry_id in dictionary.items():
        words = _extract_words(key)
        if not words:
            # No actual word segments; cannot match anything meaningful.
            continue
        first = words[0]
        # Store in the first-word index (for compound phrases and also single-word spanning multiple tokens)
        first_word_index.setdefault(first, []).append((tuple(words), entry_id))
        # If this dictionary entry is a single word (no separators), allow direct single-token lookup.
        if len(words) == 1:
            single_word_map.setdefault(first, set()).add(entry_id)

    return {
        "single": single_word_map,
        "first": first_word_index,
    }


def annotate(tokens: collections.abc.Iterable[str], dictionary_index: object) -> collections.abc.Iterable[tuple[str, collections.abc.Set]]:
    """
    Annotate tokens with entries from the dictionary.

    Parameters:
        dictionary_index:   A dictionary index created by build_dictionary_index()
        tokens:             The tokens to be annotated.

    Return:
        annotated_tokens:   A list containing (token, annotations) pairs for each token in tokens.
    """
    # Normalize input
    toks = list(tokens)
    n = len(toks)
    if n == 0:
        return []

    # Extract indexes
    single_word_map = dictionary_index.get("single", {})
    first_word_index = dictionary_index.get("first", {})

    # Precompute token metadata
    is_word = [ _is_word_token(t) for t in toks ]
    lowers = [ t.lower() for t in toks ]

    # Prepare result containers
    annotations = [set() for _ in range(n)]

    # Direct single-token annotations for words
    for i, (tok, w) in enumerate(zip(lowers, is_word)):
        if w:
            ids = single_word_map.get(tok)
            if ids:
                annotations[i].update(ids)

    # Phrase and compound matching
    # For each starting index i at a word token, attempt to match patterns whose first word
    # equals the concatenation of tokens[i..j] (j increases while tokens are words).
    for i in range(n):
        if not is_word[i]:
            continue

        s = ""
        j = i
        # Extend across the uninterrupted run of word tokens
        while j < n and is_word[j]:
            s += lowers[j]
            candidates = first_word_index.get(s)
            if candidates:
                # Try each candidate pattern
                for words_tuple, entry_id in candidates:
                    # words_tuple[0] == s by construction
                    k = j + 1  # next token position after the matched first word
                    matched = True

                    # Match subsequent words, enforcing at least one separator token between them
                    for w_idx in range(1, len(words_tuple)):
                        # Require at least one separator between words
                        if k >= n or is_word[k]:
                            matched = False
                            break
                        # Skip one or more separators (inner separators should be annotated if matched)
                        sep_pos = k
                        while sep_pos < n and not is_word[sep_pos]:
                            sep_pos += 1
                        # Now sep_pos must point to the start of the next word token
                        if sep_pos >= n or not is_word[sep_pos]:
                            matched = False
                            break

                        # Match the next dictionary word across one or more word tokens (no separators allowed within)
                        target = words_tuple[w_idx]
                        accum = ""
                        t = sep_pos
                        # Build until we either match exactly at a token boundary or fail
                        while True:
                            # We must have a word token to continue
                            if t >= n or not is_word[t]:
                                matched = False
                                break
                            accum += lowers[t]
                            # If accum is no longer a prefix of target, fail
                            if not target.startswith(accum):
                                matched = False
                                break
                            # If we reached full equality at a token boundary, accept this word
                            if accum == target:
                                t += 1
                                k = t  # update current position to just after the last consumed token
                                break
                            # Otherwise need another word token to continue
                            t += 1

                        if not matched:
                            break

                    if matched:
                        # Annotate all tokens from i up to (but including) the last consumed token (k - 1).
                        # This range includes inner separators for multi-word phrases and excludes any leading/trailing separators.
                        for r in range(i, k):
                            annotations[r].add(entry_id)

            j += 1

    # Build output
    return [(toks[i], annotations[i]) for i in range(n)]
