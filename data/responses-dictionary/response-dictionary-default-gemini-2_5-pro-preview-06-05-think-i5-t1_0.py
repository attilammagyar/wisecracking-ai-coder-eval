import collections.abc
import re

class _TrieNode:
    """A node in the dictionary Trie."""
    def __init__(self):
        # Maps a word to the next Trie node
        self.children: dict[str, _TrieNode] = {}
        # Set of dictionary entry IDs for phrases/words ending at this node
        self.entries: set = set()

def _is_word(token: str) -> bool:
    """
    Checks if a token is a word (consists of alphanumeric characters).
    This helps distinguish words from separators and punctuation.
    """
    return token.isalnum()

def build_dictionary_index(dictionary: collections.abc.Mapping) -> object:
    """
    Build a normalized index from a dictionary for fast lookup of words and
    compound phrases.

    The index is a Trie data structure where each edge represents a word.
    Dictionary keys are normalized by converting to lowercase and splitting
    into word tokens.

    Parameters:
        dictionary: Mapping strings (keys) to meanings (values).

    Returns:
        The root node of the constructed Trie.
    """
    root = _TrieNode()
    for phrase, entry in dictionary.items():
        # Normalize the dictionary key into a sequence of lower-case words.
        # This makes matching insensitive to case and separator types.
        # For example, "Black Swan" and "black, swan" both become ['black', 'swan'].
        # A compound word like "blackswan" becomes ['blackswan'].
        words = re.findall(r'\w+', phrase.lower())
        if not words:
            continue

        node = root
        for word in words:
            if word not in node.children:
                node.children[word] = _TrieNode()
            node = node.children[word]
        node.entries.add(entry)
    return root

def annotate(
    tokens: collections.abc.Iterable[str],
    dictionary_index: object
) -> collections.abc.Iterable[tuple[str, collections.abc.Set]]:
    """
    Annotate tokens with entries from the dictionary.

    This function iterates through the tokens and, for each token, attempts to
    find all matching dictionary entries (single words, phrases, and compound
    words) that start at that token. It uses the pre-built Trie index for
    efficient lookups.

    Parameters:
        dictionary_index: A dictionary index (Trie root) created by build_dictionary_index().
        tokens: The tokens to be annotated.

    Return:
        annotated_tokens: A list containing (token, annotations) pairs for each token.
    """
    if not isinstance(dictionary_index, _TrieNode):
        raise TypeError("dictionary_index must be a _TrieNode instance")

    token_list = list(tokens)
    n = len(token_list)
    annotated_tokens = [(token, set()) for token in token_list]

    for i in range(n):
        # A match can only start with a word token.
        if not _is_word(token_list[i]):
            continue

        # --- 1. Phrase Matching ---
        # Tries to match a sequence of words separated by any non-word tokens.
        # e.g., dict key "black swan" matches tokens ["black", " ", "swan"].
        node = dictionary_index
        for j in range(i, n):
            token = token_list[j]
            if _is_word(token):
                word = token.lower()
                if word in node.children:
                    node = node.children[word]
                    if node.entries:
                        # Match found. Annotate all tokens from the start of the
                        # phrase (i) to the current token (j).
                        for k in range(i, j + 1):
                            annotated_tokens[k][1].update(node.entries)
                else:
                    # No further phrase match possible from this path.
                    break
        
        # --- 2. Compound Word Matching ---
        # Tries to match a sequence of adjacent word tokens that form a single
        # dictionary word when concatenated.
        # e.g., dict key "blackswan" matches tokens ["black", "swan"].
        concatenated_word = ""
        last_word_idx = -1
        for j in range(i, n):
            token = token_list[j]
            if _is_word(token):
                concatenated_word += token.lower()
                last_word_idx = j
                # Check if the concatenated string is a word in the dictionary (a direct child of the root).
                if concatenated_word in dictionary_index.children:
                    node = dictionary_index.children[concatenated_word]
                    if node.entries:
                        # Match found. Annotate all tokens from the start of the
                        # compound word (i) to the last word token forming it.
                        for k in range(i, last_word_idx + 1):
                            annotated_tokens[k][1].update(node.entries)
            else:
                # Separators break a compound word.
                break

    return annotated_tokens
