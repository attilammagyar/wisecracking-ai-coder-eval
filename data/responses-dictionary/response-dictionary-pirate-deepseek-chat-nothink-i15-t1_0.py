def is_word_token(token: str) -> bool:
    """Check if a token is a word (as opposed to a separator)."""
    return bool(re.fullmatch(r'\w+', token))

def build_dictionary_index(dictionary: collections.abc.Mapping) -> Dict[str, List[Tuple[int, int]]]:
    """
    Build a normalized index from a dictionary for fast lookup of words and compound phrases.

    The index maps each starting word (lowercase) to a list of tuples where:
    - first element is the phrase length in tokens
    - second element is the dictionary value
    """
    index = {}
    for phrase, value in dictionary.items():
        # Split phrase into tokens (words and separators)
        tokens = re.findall(r'\w+|\W+', phrase.strip())
        if not tokens:
            continue
        
        first_word = tokens[0].lower()
