import re
from collections import defaultdict

def build_dictionary_index(dictionary: dict) -> object:
    """Builds index from dictionary with phrase sequences and concatenated entries"""
    normalized = {k.lower(): v for k, v in dictionary.items()}
    
    # Phrase mapping: {(word1, word2, ...), ... : {id1, id2, ...}}
    phrase_map = defaultdict(set)
    # Max phrase length for phrase matching
    max_phrase_length = 0
    # Store phrase lengths to compute max
    phrase_lengths = []
    
    # Build phrase_map by splitting entries into words
    for entry, ids in normalized.items():
        words = re.split(r'\W+', entry.strip())
        words = tuple([w for w in words if w])
        if len(words) > 0:
            phrase_map[words].add(ids)
            phrase_lengths.append(len(words))
    max_phrase_length = max(phrase_lengths) if phrase_lengths else 0
    
    # Build concatenated string set: {normalized_string -> {ids}}
    concat_set = defaultdict(set)
    for entry, ids in normalized.items():
        concat_set[entry].add(ids)
        
    return {
        'phrase_map': phrase_map,
        'max_phrase_length': max_phrase_length,
        'concat_set': concat_set
    }

