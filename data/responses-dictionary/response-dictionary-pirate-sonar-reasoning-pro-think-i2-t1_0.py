            if start_idx < 0:
                continue
            # Get starting position in word list
            s = start_idx
            if s < len(word_positions):
                # Get end word position
                e = min(start_idx + length -1, len(word_positions)-1)
                # Check if all intermediate tokens are separators
                is_phrase = True
