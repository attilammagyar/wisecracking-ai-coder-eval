def is_word_token(token):
    # Token with at least an alphanumeric character is considered a word.
    return any(c.isalnum() for c in token)

def normalize_token(token):
    return token.casefold()  # case-insensitive compare

def tokenize_phrase(phrase):
    # Split a phrase into a sequence of word/separator tokens.
    # e.g. "AAA BBB" -> ["AAA", " ", "BBB"]
    tokens = []
    current = ''
    prev_is_word = None
    for c in phrase:
        is_word = c.isalnum()
        if prev_is_word is None:
            current = c
            prev_is_word = is_word
            continue
        if is_word == prev_is_word:
            current += c
        else:
            tokens.append(current)
            current = c
            prev_is_word = is_word
    if current:
        tokens.append(current)
    return tokens

