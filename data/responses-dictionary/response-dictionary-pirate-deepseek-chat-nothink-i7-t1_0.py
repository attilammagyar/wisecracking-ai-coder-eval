def is_word_token(token):
    """Check if a token is a word (contains at least one alphanumeric character)."""
    return bool(re.search(r'\w', token))

def normalize_key(key):
    """Normalize dictionary keys to lowercase for case-insensitive lookup."""
    return key.lower()

def build_dictionary_index(dictionary: collections.abc.Mapping) -> object:
    """
    Build a normalized index from a dictionary for fast lookup of words and
    compound phrases.
    """
    # Create a case-insensitive single word index
    word_index = defaultdict(set)
    for key, value in dictionary.items():
        word_index[normalize_key(key)].add(value)
    
    # Create a trie for phrase lookup
    phrase_trie = {}
    for key, value in dictionary.items():
        # Split the key into words (ignoring separators)
        words = [normalize_key(w) for w in re.findall(r'\w+|\W+', key) if is_word_token(w)]
