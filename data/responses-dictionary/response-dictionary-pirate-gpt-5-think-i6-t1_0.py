def build_dictionary_index(dictionary: collections.abc.Mapping) -> object:
    """
    Build a normalized index from a dictionary for fast lookup of words and
    compound phrases.
    """
    single_word_map: dict[str, set] = {}      # normalized single-word -> set(ids)
    char_trie_root = _make_node()             # for glued-word matches across word tokens
    phrase_trie_root = _make_node()           # for multi-word phrase matches (2+ words)

    for key, entry_id in dictionary.items():
        words = _split_dict_key_into_words(key)
        if not words:
            continue
        if len(words) == 1:
            w = words[0]
            single_word_map.setdefault(w, set()).add(entry_id)
            # Also index in char trie to support concatenation across word tokens
