def annotate(tokens: collections.abc.Iterable[str], dictionary_index: object) -> collections.abc.Iterable[tuple[str, collections.abc.Set]]:
    """
    Annotate tokens with entries from the dictionary.
    """
    tokens = list(tokens)
    n = len(tokens)

    single = dictionary_index["single"]
    char_trie = dictionary_index["char_trie"]
    phrase_trie = dictionary_index["phrase_trie"]

    norm_tokens = [_norm(t) for t in tokens]
    is_word = [_is_word_token(t) for t in tokens]
    annotations = [set() for _ in range(n)]

    # 1) Direct single-word matches
    for i in range(n):
        if is_word[i]:
            ids = single.get(norm_tokens[i])
            if ids:
                annotations[i].update(ids)

    # 2) Glued-word matches across consecutive word tokens (no separators)
    for i in range(n):
        if not is_word[i]:
            continue
        node = char_trie
        k = i
        dead = False
        while k < n and is_word[k] and not dead:
            tok = norm_tokens[k]
            # Consume the whole token's characters
            for ch in tok:
                nxt = node["children"].get(ch)
                if nxt is None:
                    dead = True
                    break
                node = nxt
            if dead:
                break
            # If a word ends here in the trie, accept it (token-end boundary)
            if node["ids"]:
                for t in range(i, k + 1):
                    annotations[t].update(node["ids"])
            k += 1

    # 3) Multi-word phrase matches (separator-insensitive), annotate words and inner separators
    word_positions = [idx for idx in range(n) if is_word[idx]]
    W = len(word_positions)

    for s_idx in range(W):
        start_tok_idx = word_positions[s_idx]
        node = phrase_trie
        e_idx = s_idx
        while e_idx < W:
            wi = word_positions[e_idx]
            wnorm = norm_tokens[wi]
            nxt = node["children"].get(wnorm)
            if nxt is None:
                break
            node = nxt
            if node["ids"]:
                # Annotate from first word token to last word token inclusive (words + inner separators)
                end_tok_idx = word_positions[e_idx]
                for t in range(start_tok_idx, end_tok_idx + 1):
                    annotations[t].update(node["ids"])
            e_idx += 1

    # Prepare output
    annotated_tokens = [(tokens[i], annotations[i]) for i in range(n)]
    return annotated_tokens
