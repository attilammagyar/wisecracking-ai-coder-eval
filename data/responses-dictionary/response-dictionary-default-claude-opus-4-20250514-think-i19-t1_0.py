import collections.abc

def is_word_token(token):
    """Check if a token is a word (contains alphabetic characters)."""
    return any(c.isalpha() for c in token)

def extract_words(phrase):
    """Extract words from a phrase, ignoring non-alphabetic characters."""
    words = []
    current_word = []
    for char in phrase:
        if char.isalpha():
            current_word.append(char)
        else:
            if current_word:
                words.append(''.join(current_word))
                current_word = []
    if current_word:
        words.append(''.join(current_word))
    return words

def build_dictionary_index(dictionary: collections.abc.Mapping) -> object:
    """
    Build a normalized index from a dictionary for fast lookup of words and
    compound phrases.

    Parameters:
        dictionary: Mapping strings (keys) to meanings (values).
    """
    index = {
        'entries': {},  # normalized_key -> list of values
        'compound_phrases': []  # (normalized_words, value)
    }
    
    for key, value in dictionary.items():
        normalized_key = key.lower()
        
        # Store in entries dict for direct lookups
        if normalized_key not in index['entries']:
            index['entries'][normalized_key] = []
        index['entries'][normalized_key].append(value)
        
        # Extract words for compound phrase matching
        words = extract_words(key)
        if len(words) > 1:
            normalized_words = [w.lower() for w in words]
            index['compound_phrases'].append((normalized_words, value))
    
    return index

def match_compound_phrase(tokens, start, normalized_words):
    """
    Try to match a compound phrase starting at the given position.
    Returns the positions that should be annotated if match is successful, or None if no match.
    """
    word_idx = 0
    pos = start
    positions = []
    
    # Try to match all words in sequence
    while pos < len(tokens) and word_idx < len(normalized_words):
        if is_word_token(tokens[pos]):
            if tokens[pos].lower() == normalized_words[word_idx]:
                positions.append(pos)
                word_idx += 1
            else:
                return None  # Word doesn't match
        else:
            # Separator - include in positions for now
            positions.append(pos)
        pos += 1
    
    # Check if we matched all words
    if word_idx != len(normalized_words):
        return None
    
    # Find first and last word positions
    first_word_pos = None
    last_word_pos = None
    for p in positions:
        if is_word_token(tokens[p]):
            if first_word_pos is None:
                first_word_pos = p
            last_word_pos = p
    
    # Filter out leading and trailing separators
    result = []
    for p in positions:
        if first_word_pos <= p <= last_word_pos:
            result.append(p)
    
    return result

def annotate(tokens: collections.abc.Iterable[str], dictionary_index: object) -> collections.abc.Iterable[tuple[str, collections.abc.Set]]:
    """
    Annotate tokens with entries from the dictionary.

    Parameters:
        dictionary_index:   A dictionary index created by build_dictionary_index()
        tokens:             The tokens to be annotated.

    Return:
        annotated_tokens:   A list containing (token, annotations) pairs for each token in tokens.
    """
    tokens = list(tokens)
    n = len(tokens)
    annotations = [set() for _ in range(n)]
    
    # Try to match at each starting position
    for start in range(n):
        # 1. Try single token match
        token_lower = tokens[start].lower()
        if token_lower in dictionary_index['entries']:
            for value in dictionary_index['entries'][token_lower]:
                annotations[start].add(value)
        
        # 2. Try compound phrase matches
        for normalized_words, value in dictionary_index['compound_phrases']:
            matched_positions = match_compound_phrase(tokens, start, normalized_words)
            if matched_positions:
                for pos in matched_positions:
                    annotations[pos].add(value)
        
        # 3. Try compound word matches (concatenating consecutive word tokens)
        if is_word_token(tokens[start]):
            concatenated = ""
            for end in range(start, n):
                if is_word_token(tokens[end]):
                    concatenated += tokens[end]
                    concatenated_lower = concatenated.lower()
                    if concatenated_lower in dictionary_index['entries']:
                        for value in dictionary_index['entries'][concatenated_lower]:
                            for idx in range(start, end + 1):
                                annotations[idx].add(value)
                else:
                    break
    
    annotated_tokens = [(tokens[i], annotations[i]) for i in range(n)]
    return annotated_tokens
