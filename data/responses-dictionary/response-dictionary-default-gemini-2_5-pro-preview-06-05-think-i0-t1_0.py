def _get_word_parts(key: str) -> list[str]:
    """
    Splits a dictionary key into a list of its word components.
    Word components are sequences of alphanumeric characters.
    All other characters are treated as separators and are not included.
    
    Example: "once in a blue-moon" -> ["once", "in", "a", "blue", "moon"]
    """
    # Using re.findall is a concise way to extract all alphanumeric sequences.
    return [part.lower() for part in re.findall(r'[a-zA-Z0-9]+', key)]


