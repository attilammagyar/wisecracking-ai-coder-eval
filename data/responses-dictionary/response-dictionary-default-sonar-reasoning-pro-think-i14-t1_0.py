import collections.abc

def build_dictionary_index(dictionary: collections.abc.Mapping) -> dict:
    def normalize(word: str) -> str:
        return ''.join([c.lower() if c.isalnum() else ' ' for c in word]).strip()
    
    norm_dict = {}
    max_len = 0
    
    for key, val in dictionary.items():
        if not key:
            continue
        norm_key = normalize(key)
        if norm_key:
            norm_dict[norm_key] = val
            parts = norm_key.split()
            max_len = max(max_len, len(parts))
    
    return {
        'dictionary': norm_dict,
        'max_len': max_len
    }

def annotate(
    tokens: collections.abc.Iterable[str],
    dictionary_index: dict
) -> collections.abc.Iterable[tuple[str, collections.abc.Set]]:
    norm_tokens = []
    for t in tokens:
        normalized = ''.join([c.lower() if c.isalnum() else ' ' for c in t]).strip()
        norm_tokens.append(normalized)
    
    annotations = [set() for _ in tokens]
    max_len = dictionary_index['max_len']
    norm_dict = dictionary_index['dictionary']
    
    for i in range(len(tokens)):
        for l in range(max_len, 0, -1):
            if i + l > len(tokens):
                continue
            
            start = norm_tokens[i]
            end = norm_tokens[i + l - 1]
            if not start or not end:
                continue
            
            span_norms = norm_tokens[i:i+l]
            normalized_span = ' '.join(span_norms).strip()
            normalized_span = ' '.join(normalized_span.split())
            
            if normalized_span in norm_dict:
                entry_id = norm_dict[normalized_span]
                for j in range(i, i + l):
                    annotations[j].add(entry_id)
    
    return [(tokens[i], annotations[i]) for i in range(len(tokens))]
