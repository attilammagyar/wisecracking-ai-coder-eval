import re
import collections.abc

# Internal node factory for the trie
def _new_node():
    return {"ch": {}, "ids": set()}

def build_dictionary_index(dictionary: collections.abc.Mapping) -> object:
    """
    Build a normalized trie-based index and auxiliary lookup sets for fast
    case-insensitive matching of words and compound phrases, ignoring
    separators in dictionary entries.
    """
    # Unicode-aware "word" chunks: letters/digits/underscore
    word_re = re.compile(r"\w+", re.UNICODE)

    def split_words(text: str):
        # Normalize to casefolded words
        return [m.group(0).casefold() for m in word_re.finditer(text)]

    root = _new_node()
    word_vocab = set()

    # Build trie and collect word vocabulary
    for key, entry_id in dictionary.items():
        words = split_words(key)
        if not words:
            continue
        for w in words:
            word_vocab.add(w)
        node = root
        for w in words:
            node = node["ch"].setdefault(w, _new_node())
        node["ids"].add(entry_id)

    # Prefixes for early pruning when concatenating tokens into dictionary words
    prefixes = set()
    max_word_len = 0
    for w in word_vocab:
        max_word_len = max(max_word_len, len(w))
        # include all non-empty prefixes (including the full word)
        for i in range(1, len(w) + 1):
            prefixes.add(w[:i])

    return {
        "root": root,
        "word_re": re.compile(r"\w+", re.UNICODE),  # store our definition
        "word_vocab": word_vocab,
        "prefixes": prefixes,
        "max_word_len": max_word_len,
    }

def annotate(tokens: collections.abc.Iterable[str], dictionary_index: object) -> collections.abc.Iterable[tuple[str, collections.abc.Set]]:
    """
    Annotate tokens with dictionary entries. See build_dictionary_index() for
    the index format and logic described above.
    """
    toks = list(tokens)
    n = len(toks)
    annotated = [set() for _ in range(n)]

    if n == 0:
        return []

    root = dictionary_index["root"]
    word_re = dictionary_index["word_re"]
    word_vocab = dictionary_index["word_vocab"]
    prefixes = dictionary_index["prefixes"]
    max_word_len = dictionary_index["max_word_len"]

    # Classify tokens and normalize
    is_word = [bool(word_re.fullmatch(tok)) for tok in toks]
    norm = [tok.casefold() if is_word[i] else "" for i, tok in enumerate(toks)]

    # Fast "next word index from i" lookup (smallest j >= i with is_word[j], else n)
    next_word_from = [n] * (n + 1)
    next_word_from[n] = n
    for i in range(n - 1, -1, -1):
        next_word_from[i] = i if is_word[i] else next_word_from[i + 1]

    if max_word_len == 0:
        # Empty dictionary; return tokens with empty annotations
        return list(zip(toks, annotated))

    # Precompute all dictionary word forms that can start at each index i
    # Each entry is a list of tuples: (normalized_word, end_index_q)
    forms_from = [[] for _ in range(n)]
    for i in range(n):
        if not is_word[i]:
            continue
        acc = ""
        total_len = 0
        k = i
        # Concatenate consecutive word tokens only (stop at first separator)
        while k < n and is_word[k]:
            seg = norm[k]
            total_len += len(seg)
            if total_len > max_word_len:
                break
            acc += seg
            # If current acc isn't a prefix of any dictionary word, no point continuing
            if acc not in prefixes:
                break
            if acc in word_vocab:
                forms_from[i].append((acc, k))
            k += 1

    # Walk the trie from each word-token start position
    for s in range(n):
        if not is_word[s]:
            continue
        stack = [(root, s)]
        while stack:
            node, p = stack.pop()
            if p >= n or not is_word[p]:
                continue
            # Try every dictionary word that can start at position p
            for w, q in forms_from[p]:
                child = node["ch"].get(w)
                if child is None:
                    continue
                # Record any entries ending here
                if child["ids"]:
                    # Annotate tokens from s through q inclusive
                    for idx in range(s, q + 1):
                        annotated[idx].update(child["ids"])
                # Try to extend the phrase: skip any number of separators
                r = next_word_from[q + 1]
                if r < n:
                    stack.append((child, r))

    return list(zip(toks, annotated))
