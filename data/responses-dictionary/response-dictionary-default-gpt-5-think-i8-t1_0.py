def build_dictionary_index(dictionary: collections.abc.Mapping) -> object:
    """
    Build a normalized index from a dictionary for fast lookup of words and
    compound phrases.

    Parameters:
        dictionary: Mapping strings (keys) to meanings (values).
    """
    root = _TrieNode()
    for key, value in dictionary.items():
        words = _extract_words_casefolded(key)
        if not words:
            # Ignore entries that do not contain any word characters.
            continue
        node = root
        last_idx = len(words) - 1
        for idx, w in enumerate(words):
            # add characters of this word
            for ch in w:
                nxt = node.children.get(ch)
                if nxt is None:
                    nxt = _TrieNode()
