def _is_word_char(ch: str) -> bool:
    # Define "word" characters: ASCII/Unicode letters, digits, underscore.
    return ch.isalnum() or ch == "_"

def _is_word_token(tok: str) -> bool:
    # A token is a "word token" iff it consists entirely of word chars.
    if not tok:
        return False
    for ch in tok:
        if not _is_word_char(ch):
            return False
    return True

def _extract_words_casefolded(s: str) -> list[str]:
    # Split the dictionary key into runs of word chars; casefold for CI.
    s_cf = s.casefold()
    words = []
    i = 0
    n = len(s_cf)
    while i < n:
        # skip non-word chars
        while i < n and not _is_word_char(s_cf[i]):
            i += 1
        if i >= n:
            break
        j = i
        while j < n and _is_word_char(s_cf[j]):
            j += 1
        words.append(s_cf[i:j])
        i = j
    return words

