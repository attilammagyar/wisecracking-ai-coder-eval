import collections.abc
import re

class _DictionaryIndex:
    """
    A helper class to store the dictionary index, our treasure map.
    It separates the dictionary into single words/compounds and multi-word phrases
    for efficient searching.
    """
    def __init__(self):
        # A simple map for single words or compounds that don't have spaces.
        # e.g., "word", "compoundword". Key: normalized word, Value: list of entries.
        self.word_dict: dict[str, list] = {}
        # A trie for phrases made of multiple words, our phrase chart.
        # e.g., "a phrase of words". Structure: dict of dicts.
        self.phrase_trie: dict = {'_value': []}

def build_dictionary_index(dictionary: collections.abc.Mapping) -> object:
    """
    Build a normalized index from a dictionary for fast lookup of words and
    compound phrases.

    Parameters:
        dictionary: Mapping strings (keys) to meanings (values).
    """
    index = _DictionaryIndex()

    for key, value in dictionary.items():
        # We be takin' the key, makin' it lowercase, and lookin' for wordy bits.
        norm_key = key.lower()
        words = re.findall(r'\w+', norm_key)

        if not words:
            # If the key is just separators like "---", we treat it as a single token.
            if norm_key not in index.word_dict:
                index.word_dict[norm_key] = []
            index.word_dict[norm_key].append(value)
            continue
        
        if len(words) > 1:
            # If we find more than one word, 'tis a phrase! We'll chart it in our trie.
            node = index.phrase_trie
            for word in words:
                # Each word in the phrase be a step on our map.
                node = node.setdefault(word, {'_value': []})
            # At the end of the path, we bury the treasure (the dictionary entry).
            node['_value'].append(value)
        else:
            # A single word, could be simple like "rum" or a compound like "landlubber".
            # We stash it in our word dictionary.
            word = words[0]
            if word not in index.word_dict:
                index.word_dict[word] = []
            index.word_dict[word].append(value)
            
    return index

def annotate(tokens: collections.abc.Iterable[str], dictionary_index: object) -> collections.abc.Iterable[tuple[str, collections.abc.Set]]:
    """
    Annotate tokens with entries from the dictionary.

    Parameters:
        dictionary_index:   A dictionary index created by build_dictionary_index()
        tokens:             The tokens to be annotated.

    Return:
        annotated_tokens:   A list containing (token, annotations) pairs for each token in tokens.
    """
    if not isinstance(dictionary_index, _DictionaryIndex):
        # If the index isn't what we expect, we can't do nothin'.
        # This be a safeguard, savvy?
        return [(token, set()) for token in tokens]
        
    word_dict = dictionary_index.word_dict
    phrase_trie = dictionary_index.phrase_trie
    
    # We need to list our tokens to access 'em by index.
    tokens_list = list(tokens)
    annotated_tokens = [(token, set()) for token in tokens_list]
    num_tokens = len(tokens_list)

    def is_word_token(token: str) -> bool:
        """A helper to tell if a token is a word or just a separator."""
        return any(c.isalnum() for c in token)

    # First, let's find the phrases, the big treasures!
    # We gather all word tokens and their original positions on the ship's deck.
    word_tokens_with_indices = [
        (token.lower(), i) for i, token in enumerate(tokens_list) if is_word_token(token)
    ]

    for i in range(len(word_tokens_with_indices)):
        node = phrase_trie
        # For each word, we start a new voyage on our phrase map (trie).
        for j in range(i, len(word_tokens_with_indices)):
            word, _ = word_tokens_with_indices[j]
            if word in node:
                node = node[word]
                if node['_value']:
                    # Treasure found! A phrase match.
                    start_word_info = word_tokens_with_indices[i]
                    end_word_info = word_tokens_with_indices[j]
                    start_token_idx = start_word_info[1]
                    end_token_idx = end_word_info[1]
                    
                    # We annotate all tokens in the phrase, includin' the separators between words.
                    for k in range(start_token_idx, end_token_idx + 1):
                        for entry in node['_value']:
                            annotated_tokens[k][1].add(entry)
            else:
                # Dead end, this path leads to nowhere.
                break

    # Next, we look for single words and compounds.
    for i in range(num_tokens):
        token = tokens_list[i]
        token_lower = token.lower()

        # Check if the token itself is a word in our dictionary.
        # This be for simple words like "ahoy" or even separators like "." if they be in the dict.
        if token_lower in word_dict:
            for entry in word_dict[token_lower]:
                annotated_tokens[i][1].add(entry)

        # Now for compound words, formed by stickin' tokens together without separators.
        # e.g., "land" and "lubber" makin' "landlubber".
        if is_word_token(token):
            concatenated_word = ""
            indices_in_compound = []
            for j in range(i, num_tokens):
                sub_token = tokens_list[j]
                if is_word_token(sub_token):
                    concatenated_word += sub_token.lower()
                    indices_in_compound.append(j)
                    if concatenated_word in word_dict:
                        # Ho ho! A compound word match!
                        for entry in word_dict[concatenated_word]:
                            for k in indices_in_compound:
                                annotated_tokens[k][1].add(entry)
                else:
                    # A separator breaks the chain.
                    break
                    
    return annotated_tokens
