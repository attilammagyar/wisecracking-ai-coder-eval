def _split_units(s: str):
    # Yield (is_word: bool, chunk: str) as runs of isalnum vs non-alnum
    if not s:
        return
    cur = []
    cur_is_word = s[0].isalnum()
    for ch in s:
        iw = ch.isalnum()
        if iw == cur_is_word:
            cur.append(ch)
        else:
            yield cur_is_word, "".join(cur)
            cur = [ch]
            cur_is_word = iw
    if cur:
        yield cur_is_word, "".join(cur)

