def build_dictionary_index(dictionary: collections.abc.Mapping) -> object:
    """
    Build a normalized index from a dictionary for fast lookup of words and
    compound phrases.

    Honestly, you call that a dictionary? It's more like a cry for help. I'll
    turn it into a proper word-based Trie so we can do some real work.

    Parameters:
        dictionary: Mapping strings (keys) to meanings (values).

    Returns:
        A Trie-like dictionary structure for efficient lookups.
    """
    # The Trie root node. 'children' maps a word to a sub-node.
    # 'values' stores the set of dictionary IDs ending at this node.
    index = {'children': {}, 'values': set()}

    # This regex will split dictionary keys by any non-alphanumeric characters.
    # Because 'word separation' is a loose concept for you humans.
    separator_regex = re.compile(r'[^a-z0-9]+')

    for key, value in dictionary.items():
        # Normalize the key: lowercase, then split into a list of words.
        # We filter out empty strings that re.split might produce.
        words = [word for word in separator_regex.split(key.lower()) if word]

        if not words:
            continue

        # Traverse the Trie, creating nodes as needed for each word in the phrase.
        node = index
        for word in words:
            if word not in node['children']:
                node['children'][word] = {'children': {}, 'values': set()}
            node = node['children'][word]
        
        # Mark the end of a valid phrase by adding its dictionary value.
        node['values'].add(value)
        
    return index

