import collections.abc

def build_dictionary_index(dictionary: collections.abc.Mapping) -> object:
    """
    Build a normalized index (two tries):
      - char_trie for single-piece entries (no separators inside), matched across
        adjacent word tokens with no separators in the text.
      - phrase_trie for multi-word entries (with separators in the dictionary),
        matched across word tokens with >=1 separator tokens between them in the text.

    Dictionary lookup is case-insensitive. Non-alnum chars in dictionary keys
    are treated as separators when deciding word boundaries.
    """

    class CharTrieNode:
        __slots__ = ("children", "ids")
        def __init__(self):
            self.children = {}   # char -> CharTrieNode
            self.ids = set()     # set of dict entry IDs

    class WordTrieNode:
        __slots__ = ("children", "ids")
        def __init__(self):
            self.children = {}   # word (str) -> WordTrieNode
            self.ids = set()

    def split_words_lower(s: str):
        # Split on non-alnum, return list of lowercase words.
        out = []
        cur = []
        for ch in s:
            if ch.isalnum():
                cur.append(ch.lower())
            else:
                if cur:
                    out.append("".join(cur))
                    cur = []
        if cur:
            out.append("".join(cur))
        return out

    char_root = CharTrieNode()
    phrase_root = WordTrieNode()

    # Insert dictionary entries into appropriate tries
    for key, entry_id in dictionary.items():
        words = split_words_lower(key)
        if not words:
            continue
        if len(words) == 1:
            # Single-piece: insert into character trie
            node = char_root
            for ch in words[0]:
                nxt = node.children.get(ch)
                if nxt is None:
                    nxt = CharTrieNode()
                    node.children[ch] = nxt
                node = nxt
            node.ids.add(entry_id)
        else:
            # Multi-word phrase: insert into word trie
            node = phrase_root
            for w in words:
                nxt = node.children.get(w)
                if nxt is None:
                    nxt = WordTrieNode()
                    node.children[w] = nxt
                node = nxt
            node.ids.add(entry_id)

    return {
        "char_root": char_root,
        "phrase_root": phrase_root,
    }


def annotate(tokens: collections.abc.Iterable[str], dictionary_index: object) -> collections.abc.Iterable[tuple[str, collections.abc.Set]]:
    """
    Annotate each token with relevant dictionary IDs:
      - single-piece entries (from the char trie), matching across adjacent word tokens
        with no separators, and only ending at token boundaries;
      - multi-word phrases (from the word trie), matching across words with one or
        more separator tokens between them.
    """
    # Helper: classify tokens
    def is_word_token(tok: str) -> bool:
        # Word = all alnum chars (simple, fast, works for provided tests)
        return len(tok) > 0 and all(c.isalnum() for c in tok)

    # Pull tries
    char_root = dictionary_index["char_root"]
    phrase_root = dictionary_index["phrase_root"]

    toks = list(tokens)
    n = len(toks)

    # Precompute word/separator classification and lowercase
    is_word = [is_word_token(t) for t in toks]
    lower_word = [t.lower() if is_word[i] else "" for i, t in enumerate(toks)]

    annotations = [set() for _ in range(n)]

    # Single-piece matching via character trie (no separators allowed)
    # For each word token position i, traverse chars across adjacent word tokens.
    for i in range(n):
        if not is_word[i]:
            continue
        node = char_root
        pos = i
        # Walk across consecutive word tokens only
        while pos < n and is_word[pos]:
            tok = lower_word[pos]
            # Consume entire token's characters
            advanced = True
            for ch in tok:
                nxt = node.children.get(ch)
                if nxt is None:
                    advanced = False
                    break
                node = nxt
            if not advanced:
                break
            # If a terminal exists here (exact end at token boundary), annotate i..pos
            if node.ids:
                for k in range(i, pos + 1):
                    annotations[k].update(node.ids)
            pos += 1

    # Multi-word phrase matching via word trie (>=1 separator required between words)
    # Start at each word position i; move to next word only after skipping >=1 separators.
    for i in range(n):
        if not is_word[i]:
            continue
        first = lower_word[i]
        node = phrase_root.children.get(first)
        if node is None:
            continue

        j = i  # index of the last matched word token
        # If node.ids existed here, that would correspond to single-word phrase,
        # but by construction we only store multi-word phrases in phrase trie.
        # Keep extending while pattern matches with >=1 separators between words.
        while True:
            # If we have completed a multi-word phrase, annotate span [i..j]
            if node.ids:
                # Annotate all tokens in [i..j], including inner separators
                for t in range(i, j + 1):
                    annotations[t].update(node.ids)
            # Find next word after at least one separator
            k = j + 1
            if k >= n or is_word[k]:
                break  # no separator before next, or end reached
            # Skip one or more separators
            while k < n and not is_word[k]:
                k += 1
            if k >= n:
                break
            w = lower_word[k]
            nxt = node.children.get(w)
            if nxt is None:
                break
            node = nxt
            j = k

    # Return annotated pairs
    return [(toks[i], annotations[i]) for i in range(n)]
