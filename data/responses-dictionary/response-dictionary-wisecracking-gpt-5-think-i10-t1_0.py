def _new_char_node():
    # Node for character trie: { 'ch': {char: node}, 'ids': set() }
    return {'ch': {}, 'ids': set()}

def _new_word_node():
    # Node for word trie: { 'kids': {word: node}, 'ids': set() }
    return {'kids': {}, 'ids': set()}

_WORD_RE = re.compile(r'[A-Za-z0-9]+')

def _dict_key_to_words(key: str):
    # Case-insensitive normalization, extract alnum "words"
    return _WORD_RE.findall(key.lower())

def _is_word_token(tok: str) -> bool:
    # Keep it simple and fast; matches tests well
    return tok.isalnum()


