    anns = [set() for _ in range(n)]

    # Helper to add ids to a contiguous token range [i..j]
    def add_ids(i: int, j: int, ids: set):
        for k in range(i, j + 1):
            anns[k].update(ids)

    # Pass 1: Character-trie matches for single-word entries
    # Matches can span multiple consecutive word tokens but may not cross a separator.
    for i in range(n):
        if not is_word[i]:
            continue
        node = char_root
        ok_first = True
        j = i
        while True:
            t = low[j]  # lowercased word token
            # Early reject: first character must exist in trie
            if ok_first and t and t[0] not in node['ch']:
                break
            ok_first = False
            # Consume the whole token
            for ch in t:
                nxt = node['ch'].get(ch)
                if nxt is None:
                    # dead end; stop scanning from this start
                    node = None
                    break
                node = nxt
            if node is None:
                break
            # At end of this token boundary: valid place to accept terminal words
            if node['ids']:
                add_ids(i, j, node['ids'])
            # Try to continue only if the next token exists and is a word (no separators in between)
            j += 1
            if j >= n or not is_word[j]:
                break
            # else loop continues, reading next token characters

    # Pass 2: Word-trie matches for multiword phrases with separators
    for i in range(n):
        if not is_word[i]:
            continue
        first_word = low[i]
        node = phrase_root['kids'].get(first_word)
        if node is None:
            continue

        last_word_idx = i
        p = i + 1
        # We must find at least one separator before the next word
        while True:
            # Require at least one separator between words
            if p >= n or is_word[p]:
                # No separator -> cannot extend to a phrase
                break
            # Skip one or more separators
            sep_start = p
            while p < n and not is_word[p]:
                p += 1
            if p >= n:
                break
            next_word_idx = p
            next_word = low[next_word_idx]

            nxt = node['kids'].get(next_word)
            if nxt is None:
                break

            node = nxt
            last_word_idx = next_word_idx

            # If a phrase ends here, annotate:
            # - both word tokens in range
            # - all separator tokens between them (inner separators)
            if node['ids']:
                add_ids(i, last_word_idx, node['ids'])

            p = last_word_idx + 1
            # and loop to look for a longer phrase (nested phrases allowed)

    annotated_tokens = [(toks[i], anns[i]) for i in range(n)]
    return annotated_tokens
