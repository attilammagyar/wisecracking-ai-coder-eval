def build_dictionary_index(dictionary: collections.abc.Mapping) -> object:
    """
    Build a normalized index from a dictionary for fast lookup of words and
    compound phrases.

    Parameters:
        dictionary: Mapping strings (keys) to meanings (values).
    """
    char_root = _new_char_node()   # For single-word entries (concatenation across tokens allowed)
    phrase_root = _new_word_node() # For multiword phrases (require separators between words)

    for k, v in dictionary.items():
        words = _dict_key_to_words(str(k))
        if not words:
            continue  # nothing to match
        if len(words) == 1:
            # Insert into character trie
            w = words[0]
            node = char_root
            for c in w:
                node = node['ch'].setdefault(c, _new_char_node())
            node['ids'].add(v)
        else:
            # Insert into word trie (phrase)
            node = phrase_root
            for w in words:
                node = node['kids'].setdefault(w, _new_word_node())
            node['ids'].add(v)

    return {'char_root': char_root, 'phrase_root': phrase_root}


def annotate(tokens: collections.abc.Iterable[str], dictionary_index: object) -> collections.abc.Iterable[tuple[str, collections.abc.Set]]:
    """
    Annotate tokens with entries from the dictionary.

    Parameters:
        dictionary_index:   A dictionary index created by build_dictionary_index()
        tokens:             The tokens to be annotated.

    Return:
        annotated_tokens:   A list containing (token, annotations) pairs for each token in tokens.
    """
    toks = list(tokens)
    n = len(toks)
    if n == 0:
        return []

    char_root = dictionary_index['char_root']
    phrase_root = dictionary_index['phrase_root']

    # Precompute token types and lowercase forms
    is_word = [_is_word_token(t) for t in toks]
