def _split_words(s: str) -> list[str]:
    """
    Split string into lowercase alphanumeric word chunks, dropping separators.
    Example: "AAA, BBB" -> ["aaa", "bbb"]
             "AAABBB"   -> ["aaabbb"]
    """
    words = []
    buf = []
    for ch in s:
        if ch.isalnum():
            buf.append(ch.lower())
        else:
            if buf:
                words.append("".join(buf))
                buf = []
    if buf:
        words.append("".join(buf))
    return words


