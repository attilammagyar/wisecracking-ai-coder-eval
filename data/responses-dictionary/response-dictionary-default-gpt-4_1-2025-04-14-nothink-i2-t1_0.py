# Helper function: classify a token as a word token - those that can match dictionary "words"
def is_word_token(token):
    # Definition: a word token is non-empty and contains at least one alphanum character
    # This is broad enough for language learners (to handle e.g. 'don't', 'él', etc.)
    return any(c.isalnum() for c in token)

def normalize_word(word):
    return word.lower()

def split_dict_phrase(phrase):
    # Split a dictionary phrase into its word tokens (ignore separators for trie)
    # e.g. "AAA, BBB" => ["aaa", "bbb"]
    # Use regex for robustness; treat consecutive runs of alphanums as words
    return [normalize_word(w) for w in re.findall(r"\w+", phrase)]

