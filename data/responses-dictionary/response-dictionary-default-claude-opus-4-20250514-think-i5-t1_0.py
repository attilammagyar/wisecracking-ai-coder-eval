import collections.abc
import re

def is_word_token(token):
    """Check if a token consists only of word characters."""
    return bool(re.match(r'^\w+$', token))

def extract_words(text):
    """Extract all word tokens from text."""
    return re.findall(r'\w+', text)

def normalize_key(text):
    """Normalize text for case-insensitive lookup."""
    return text.lower()

def build_dictionary_index(dictionary):
    """
    Build a normalized index from a dictionary for fast lookup of words and
    compound phrases.

    Parameters:
        dictionary: Mapping strings (keys) to meanings (values).
    """
    index = {
        'single_words': {},      # word -> set of entry IDs
        'compound_words': {},    # concatenated words -> set of entry IDs
        'compound_phrases': {}   # space-joined words -> set of entry IDs
    }
    
    for key, value in dictionary.items():
        # Extract words from the key
        words = extract_words(key)
        
        if not words:
            continue
            
        if len(words) == 1:
            # Single word entry
            normalized = normalize_key(words[0])
            if normalized not in index['single_words']:
                index['single_words'][normalized] = set()
            index['single_words'][normalized].add(value)
        else:
            # Multiple words - check if it's a compound word or phrase
            # Split the original key into tokens to check for separators
            tokens = re.findall(r'\w+|\W+', key)
            
            # If there are only word tokens (no separators), it's a compound word
            if all(is_word_token(t) for t in tokens):
                # Compound word - concatenate all words
                normalized = normalize_key(''.join(words))
                if normalized not in index['compound_words']:
                    index['compound_words'][normalized] = set()
                index['compound_words'][normalized].add(value)
            else:
                # Compound phrase - normalize to space-separated words
                normalized = ' '.join(normalize_key(w) for w in words)
                if normalized not in index['compound_phrases']:
                    index['compound_phrases'][normalized] = set()
                index['compound_phrases'][normalized].add(value)
    
    return index

def annotate(tokens, dictionary_index):
    """
    Annotate tokens with entries from the dictionary.

    Parameters:
        dictionary_index:   A dictionary index created by build_dictionary_index()
        tokens:             The tokens to be annotated.

    Return:
        annotated_tokens:   A list containing (token, annotations) pairs for each token in tokens.
    """
    tokens = list(tokens)
    n = len(tokens)
    annotations = [set() for _ in range(n)]
    
    # Process each position as a potential start of a match
    for start in range(n):
        if not is_word_token(tokens[start]):
            continue
            
        # 1. Check single word match
        word_normalized = normalize_key(tokens[start])
        if word_normalized in dictionary_index['single_words']:
            annotations[start].update(dictionary_index['single_words'][word_normalized])
        
        # 2. Check compound word matches (adjacent word tokens only)
        compound = word_normalized
        end = start
        for i in range(start + 1, n):
            if is_word_token(tokens[i]):
                compound += normalize_key(tokens[i])
                end = i
                if compound in dictionary_index['compound_words']:
                    # Annotate all tokens in the compound word
                    for j in range(start, end + 1):
                        annotations[j].update(dictionary_index['compound_words'][compound])
            else:
                # Stop at first non-word token
                break
        
        # 3. Check compound phrase matches
        # Collect all words from start position onwards
        words_collected = [word_normalized]
        word_positions = [start]
        
        for i in range(start + 1, n):
            if is_word_token(tokens[i]):
                words_collected.append(normalize_key(tokens[i]))
                word_positions.append(i)
                
                # Check if current sequence of words matches a phrase
                phrase_key = ' '.join(words_collected)
                if phrase_key in dictionary_index['compound_phrases']:
                    # Annotate all tokens from start to current position (inclusive)
                    for j in range(start, i + 1):
                        annotations[j].update(dictionary_index['compound_phrases'][phrase_key])
    
    annotated_tokens = [(tokens[i], annotations[i]) for i in range(n)]
    return annotated_tokens
