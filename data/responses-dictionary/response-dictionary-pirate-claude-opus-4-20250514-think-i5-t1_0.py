import collections.abc

def is_word_token(token):
    """Check if a token be a word (contains alphabetic characters)."""
    return any(c.isalpha() for c in token)

def normalize_word(word):
    """Normalize a word for case-insensitive matching."""
    return word.lower()

def extract_words_from_phrase(phrase):
    """Extract normalized words from a phrase, ignorin' separators."""
    words = []
    current_word = []
    
    for char in phrase:
        if char.isalpha():
            current_word.append(char.lower())
        else:
            if current_word:
                words.append(''.join(current_word))
                current_word = []
    
    if current_word:
        words.append(''.join(current_word))
    
    return words

def has_separators(phrase):
    """Check if a phrase contains non-alphabetic characters."""
    return any(not c.isalpha() for c in phrase)

def build_dictionary_index(dictionary: collections.abc.Mapping) -> object:
    """
    Build a normalized index from a dictionary for fast lookup of words and
    compound phrases.

    Parameters:
        dictionary: Mapping strings (keys) to meanings (values).
    """
    index = {
        'single_words': {},  # normalized_word -> set of entries
        'compound_phrases': [],  # list of (normalized_words_list, entry_id)
        'compound_words': {}  # normalized_compound_word -> set of entries
    }
    
    for phrase, entry_id in dictionary.items():
        words = extract_words_from_phrase(phrase)
        
        if len(words) == 1 and not has_separators(phrase):
            # Single word entry (no separators)
            word = words[0]
            if word not in index['single_words']:
                index['single_words'][word] = set()
            index['single_words'][word].add(entry_id)
            
            # Also add to compound_words for matching concatenated tokens
            if word not in index['compound_words']:
                index['compound_words'][word] = set()
            index['compound_words'][word].add(entry_id)
        elif has_separators(phrase):
            # Compound phrase (has separators)
            index['compound_phrases'].append((words, entry_id))
        else:
            # Compound word (no separators, multiple words concatenated)
            compound = normalize_word(phrase)
            if compound not in index['compound_words']:
                index['compound_words'][compound] = set()
            index['compound_words'][compound].add(entry_id)
    
    return index

def annotate(tokens: collections.abc.Iterable[str], dictionary_index: object) -> collections.abc.Iterable[tuple[str, collections.abc.Set]]:
    """
    Annotate tokens with entries from the dictionary.

    Parameters:
        dictionary_index:   A dictionary index created by build_dictionary_index()
        tokens:             The tokens to be annotated.

    Return:
        annotated_tokens:   A list containing (token, annotations) pairs for each token in tokens.
    """
    tokens = list(tokens)  # Convert to list for indexing
    n = len(tokens)
    annotations = [set() for _ in range(n)]
    
