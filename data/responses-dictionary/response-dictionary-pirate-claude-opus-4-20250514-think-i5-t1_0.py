    for i, token in enumerate(tokens):
        if is_word_token(token):
            normalized = normalize_word(token)
            if normalized in dictionary_index['single_words']:
                annotations[i].update(dictionary_index['single_words'][normalized])
    
    # Check compound phrase matches
    for start_idx in range(n):
        # Skip if starting with a separator
        if not is_word_token(tokens[start_idx]):
            continue
        
        # Try to match compound phrases starting at this position
        for phrase_words, entry_id in dictionary_index['compound_phrases']:
            # Try to match this phrase starting at start_idx
            word_idx = 0
            token_idx = start_idx
            matched_token_indices = []
            
            while token_idx < n and word_idx < len(phrase_words):
                if is_word_token(tokens[token_idx]):
                    # This is a word token
                    if normalize_word(tokens[token_idx]) == phrase_words[word_idx]:
                        matched_token_indices.append(token_idx)
                        word_idx += 1
                    else:
                        # Word doesn't match
                        break
                else:
                    # This is a separator token
                    # Only include if we're between words (not leading or trailing)
                    if word_idx > 0 and word_idx < len(phrase_words):
                        matched_token_indices.append(token_idx)
                
                token_idx += 1
            
            # Check if we matched all words in the phrase
            if word_idx == len(phrase_words):
                # Add annotations to all matched tokens
                for idx in matched_token_indices:
                    annotations[idx].add(entry_id)
    
    # Check compound word matches (concatenated tokens)
    for start_idx in range(n):
        # Try different lengths of token sequences
        for end_idx in range(start_idx + 1, n + 1):
            # Concatenate tokens in this range
            concat = ''.join(tokens[start_idx:end_idx])
            normalized_concat = normalize_word(concat)
            
            if normalized_concat in dictionary_index['compound_words']:
                # Add annotations to all tokens in this range
                for idx in range(start_idx, end_idx):
                    annotations[idx].update(dictionary_index['compound_words'][normalized_concat])
    
    # Build result
    annotated_tokens = []
    for token, annot_set in zip(tokens, annotations):
        annotated_tokens.append((token, annot_set))
    
    return annotated_tokens
