import collections.abc

def is_word_token(token):
    """Check if a token contains any alphabetic characters."""
    return any(c.isalpha() for c in token)

def normalize_token(token):
    """Normalize a token for case-insensitive matching."""
    return token.lower()

def extract_words_from_phrase(phrase):
    """Extract word tokens from a phrase, ignoring separators."""
    words = []
    current_word = []
    
    for char in phrase:
        if char.isalpha():
            current_word.append(char)
        else:
            if current_word:
                words.append(''.join(current_word).lower())
                current_word = []
    
    if current_word:
        words.append(''.join(current_word).lower())
    
    return tuple(words)

def build_dictionary_index(dictionary: collections.abc.Mapping) -> object:
    """
    Build a normalized index from a dictionary for fast lookup of words and
    compound phrases.

    Parameters:
        dictionary: Mapping strings (keys) to meanings (values).
    """
    index = {
        'entries': {},  # normalized_entry -> set of entry_ids
        'phrases': {},  # (word1, word2, ...) -> set of entry_ids
    }
    
    for entry, entry_id in dictionary.items():
        # Store the normalized full entry
        normalized_entry = entry.lower()
        if normalized_entry not in index['entries']:
            index['entries'][normalized_entry] = set()
        index['entries'][normalized_entry].add(entry_id)
        
        # Also store as word sequence for phrase matching
        words = extract_words_from_phrase(entry)
        if len(words) > 1:
            if words not in index['phrases']:
                index['phrases'][words] = set()
            index['phrases'][words].add(entry_id)
    
    return index

def annotate(tokens: collections.abc.Iterable[str], dictionary_index: object) -> collections.abc.Iterable[tuple[str, collections.abc.Set]]:
    """
    Annotate tokens with entries from the dictionary.

    Parameters:
        dictionary_index:   A dictionary index created by build_dictionary_index()
        tokens:             The tokens to be annotated.

    Return:
        annotated_tokens:   A list containing (token, annotations) pairs for each token in tokens.
    """
    tokens = list(tokens)  # Convert to list for indexing
    n = len(tokens)
    annotations = [set() for _ in range(n)]
    
    # Identify word tokens
    is_word = [is_word_token(token) for token in tokens]
    
    # Match individual tokens
    for i in range(n):
        normalized = normalize_token(tokens[i])
        if normalized in dictionary_index['entries']:
            annotations[i].update(dictionary_index['entries'][normalized])
    
    # Match concatenated word tokens
    for start in range(n):
        if not is_word[start]:
            continue
        
        concatenated = normalize_token(tokens[start])
        for end in range(start + 1, n):
            if not is_word[end]:
                break
            concatenated += normalize_token(tokens[end])
            
            if concatenated in dictionary_index['entries']:
                # Annotate all tokens in this range
                for j in range(start, end + 1):
                    annotations[j].update(dictionary_index['entries'][concatenated])
    
    # Match compound phrases
    for start in range(n):
        if not is_word[start]:
            continue
        
        # Build sequences of words starting from this position
        words = [normalize_token(tokens[start])]
        word_positions = [start]
        
        for i in range(start + 1, n):
            if is_word[i]:
                words.append(normalize_token(tokens[i]))
                word_positions.append(i)
                
                # Check if this sequence of words matches a compound phrase
                words_tuple = tuple(words)
                if words_tuple in dictionary_index['phrases']:
                    # Annotate all tokens from first word to last word
                    first_word_pos = word_positions[0]
                    last_word_pos = word_positions[-1]
                    
                    for j in range(first_word_pos, last_word_pos + 1):
                        annotations[j].update(dictionary_index['phrases'][words_tuple])
    
    # Create annotated tokens
    annotated_tokens = []
    for i in range(n):
        annotated_tokens.append((tokens[i], annotations[i]))
    
    return annotated_tokens
