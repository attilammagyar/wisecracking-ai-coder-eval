import collections.abc
from collections import defaultdict

def build_dictionary_index(dictionary: collections.abc.Mapping) -> object:
    """
    Builds an index that lets us find:
    - individual words (case-insensitive)
    - phrases of N words (with normalized separators)
    """
    index = {
        'words': set(),  # individual words (lowercase)
        'phrases': defaultdict(dict),  # phrase_length -> {normalized_phrase: value}
        'max_phrase_length': 0
    }
    
    for phrase, value in dictionary.items():
        # Normalize to lowercase and split into components
        components = []
        current_word = []
        for c in phrase.lower():
            if c.isalpha():
                current_word.append(c)
            else:
                if current_word:
                    components.append(''.join(current_word))
                    current_word = []
                components.append(' ')  # normalize all separators to space
        if current_word:
            components.append(''.join(current_word))
        
        # Handle single-word entries
        if len(components) == 1:
            index['words'].add(components[0])
            continue
        
        # Handle multi-word phrases
        # Rebuild the normalized phrase (with single spaces)
        normalized_phrase = ' '.join(components)
        phrase_length = sum(1 for c in components if c != ' ')
        index['phrases'][phrase_length][normalized_phrase] = value
        index['max_phrase_length'] = max(index['max_phrase_length'], phrase_length)
    
    return index

def is_word_token(token: str) -> bool:
    """Because apparently we need to define what a word is. Who knew?"""
    return any(c.isalpha() for c in token)

def annotate(tokens: collections.abc.Iterable[str], dictionary_index: object) -> collections.abc.Iterable[tuple[str, collections.abc.Set]]:
    """
    The main event: annotate tokens with dictionary entries.
    Works by:
    1. Checking each token as individual word
    2. Looking ahead for possible phrases starting at each token
    """
    tokens = list(tokens)  # because we need random access
    annotated_tokens = []
    n = len(tokens)
    
    # First pass: find all possible phrase matches
    phrase_matches = defaultdict(list)  # token_index -> list of (length, value)
    
    for i in range(n):
        if not is_word_token(tokens[i]):
            continue  # phrases can't start with separators
        
        # Check all possible phrase lengths
        max_possible_length = min(
            dictionary_index['max_phrase_length'],
            n - i
        )
        
        for length in range(1, max_possible_length + 1):
            # Build normalized candidate phrase
            components = []
            word_count = 0
            valid = True
            
            for j in range(i, i + length):
                token = tokens[j]
                if is_word_token(token):
                    components.append(token.lower())
                    word_count += 1
                else:
                    components.append(' ')
            
            # Only consider if we got the right number of words
            if word_count != length:
                continue
            
            normalized_phrase = ' '.join(components)
            
            # Check if this phrase exists
            if normalized_phrase in dictionary_index['phrases'][length]:
                value = dictionary_index['phrases'][length][normalized_phrase]
                # Record this match for all participating tokens
                for j in range(i, i + length):
                    # Only include separators that are between words
                    if j > i and j < i + length - 1 or is_word_token(tokens[j]):
                        phrase_matches[j].append(value)
    
    # Second pass: build annotations
    for i, token in enumerate(tokens):
        annotations = set()
        
        # Add individual word matches
        if is_word_token(token) and token.lower() in dictionary_index['words']:
            annotations.add(dictionary_index['dictionary'][token.lower()])
        
        # Add phrase matches
        for value in phrase_matches.get(i, []):
            annotations.add(value)
        
        annotated_tokens.append((token, annotations))
    
    return annotated_tokens
