import collections.abc
import re

def build_dictionary_index(dictionary: collections.abc.Mapping) -> object:
    """
    Build a normalized index from a dictionary for fast lookup of words and
    compound phrases.

    Parameters:
        dictionary: Mapping strings (keys) to meanings (values).
    """
    # Regex to identify word characters
    word_pattern = re.compile(r'\w+', re.UNICODE)
    
    normalized_dict = {}
    word_entries = {}
    phrase_entries = []
    
    for key, value in dictionary.items():
        # Normalize the key
        normalized_key = key.lower()
        normalized_dict[normalized_key] = value
        
        # Extract words from the key
        words = word_pattern.findall(normalized_key)
        
        if len(words) == 1:
            # Single word entry
            word = words[0]
            if word not in word_entries:
                word_entries[word] = []
            word_entries[word].append(value)
        elif len(words) > 1:
            # Compound phrase
            phrase_entries.append((words, value))
    
    return {
        'normalized_dict': normalized_dict,
        'word_entries': word_entries,
        'phrase_entries': phrase_entries,
        'word_pattern': word_pattern
    }

def annotate(tokens: collections.abc.Iterable[str], dictionary_index: object) -> collections.abc.Iterable[tuple[str, collections.abc.Set]]:
    """
    Annotate tokens with entries from the dictionary.

    Parameters:
        dictionary_index:   A dictionary index created by build_dictionary_index()
        tokens:             The tokens to be annotated.

    Return:
        annotated_tokens:   A list containing (token, annotations) pairs for each token in tokens.
    """
    tokens = list(tokens)
    n = len(tokens)
    
    if n == 0:
        return []
    
    normalized_dict = dictionary_index['normalized_dict']
    word_entries = dictionary_index['word_entries']
    phrase_entries = dictionary_index['phrase_entries']
    word_pattern = dictionary_index['word_pattern']
    
    # Initialize annotations for each token
    annotations = [set() for _ in range(n)]
    
    # Classify tokens as word or non-word
    is_word_token = [bool(word_pattern.fullmatch(token)) for token in tokens]
    
    # Process each starting position
    for start in range(n):
        if not is_word_token[start]:
            continue
            
        # Try to match sequences starting from this position
        words_from_start = []
        token_indices = []
        
        for i in range(start, n):
            if is_word_token[i]:
                words_from_start.append(tokens[i].lower())
                token_indices.append(i)
                
                # Check for individual word match
                if len(words_from_start) == 1:
                    word = words_from_start[0]
                    if word in word_entries:
                        for entry_id in word_entries[word]:
                            annotations[i].add(entry_id)
                
                # Check for compound word match (concatenated tokens)
                if len(token_indices) > 1:
                    # Check if all tokens from start to current are consecutive words
                    all_consecutive = True
                    for j in range(len(token_indices) - 1):
                        if token_indices[j+1] - token_indices[j] != 1:
                            all_consecutive = False
                            break
                    
                    if all_consecutive:
                        concatenated = ''.join(tokens[token_indices[0]:token_indices[-1]+1])
                        if concatenated.lower() in normalized_dict:
                            entry_id = normalized_dict[concatenated.lower()]
                            for idx in token_indices:
                                annotations[idx].add(entry_id)
                
                # Check for compound phrase matches
                for phrase_words, entry_id in phrase_entries:
                    if words_from_start == phrase_words:
                        # Found a match - annotate all tokens in the range
                        for idx in range(start, i + 1):
                            annotations[idx].add(entry_id)
    
    # Create the result
    annotated_tokens = [(token, ann) for token, ann in zip(tokens, annotations)]
    return annotated_tokens
