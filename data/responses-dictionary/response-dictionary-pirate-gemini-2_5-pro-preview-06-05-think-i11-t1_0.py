            chunk_start_idx = j
            
            # Skip any separators to find the beginning of the next word chunk.
            while chunk_start_idx < num_tokens and not _is_wordy(tokens[chunk_start_idx]):
                chunk_start_idx += 1
            
            if chunk_start_idx >= num_tokens:
                break # No more wordy tokens ahead.

            # Now, form the chunk by concatenating consecutive wordy tokens.
            current_chunk_indices = []
            chunk_str_list = []
            k = chunk_start_idx
