import collections.abc
import re

class _TrieNode:
    """A node in the Trie structure used for the dictionary index."""
    def __init__(self):
        # Maps a word part (str) to the next _TrieNode
        self.children = {}
        # Set of dictionary entry IDs for phrases that end at this node
        self.entries = set()

def build_dictionary_index(dictionary: collections.abc.Mapping) -> object:
    """
    Build a normalized index from a dictionary for fast lookup of words and
    compound phrases.

    The index is a Trie data structure where each path from the root represents a
    sequence of normalized "word parts" from a dictionary key.

    Parameters:
        dictionary: A mapping of strings (keys) to dictionary entry IDs (values).

    Returns:
        The root of the Trie index.
    """
    root = _TrieNode()
    for phrase, entry_id in dictionary.items():
        # Normalize the phrase: convert to lowercase and extract alphanumeric parts.
        # This handles both spaced phrases ("a b c") and concatenated words ("abc")
        # by creating a canonical sequence of word parts. For example,
        # "black swan" -> ['black', 'swan']
        # "blackswan"  -> ['blackswan']
        word_parts = re.findall(r'[a-zA-Z0-9]+', phrase.lower())
        
        if not word_parts:
            continue

        node = root
        for part in word_parts:
            if part not in node.children:
                node.children[part] = _TrieNode()
            node = node.children[part]
        node.entries.add(entry_id)
    return root

def annotate(tokens: collections.abc.Iterable[str], dictionary_index: object) -> collections.abc.Iterable[tuple[str, collections.abc.Set]]:
    """
    Annotate tokens with entries from the dictionary using the pre-built index.

    This function iterates through the tokens and, for each potential starting
    position, performs two types of searches:
    1. A search for spaced phrases (e.g., "black swan").
    2. A search for concatenated words (e.g., "blackswan" from ["black", "swan"]).

    Parameters:
        dictionary_index: A dictionary index created by build_dictionary_index().
        tokens: The tokens to be annotated.

    Returns:
        A list of (token, annotations) pairs.
    """
    token_list = list(tokens)
    n = len(token_list)
    if n == 0:
        return []

    annotated_tokens = [(token, set()) for token in token_list]
    root: _TrieNode = dictionary_index

    def is_word(token: str) -> bool:
        """Checks if a token is a 'word' (i.e., alphanumeric)."""
        return token.isalnum()

    for i in range(n):
        # A match can only start with a word token.
        if not is_word(token_list[i]):
            continue

        # --- Search 1: Spaced phrases ---
        # This search finds phrases composed of word tokens separated by non-words.
        node = root
        word_indices_in_phrase = []
        for j in range(i, n):
            token = token_list[j]
            if is_word(token):
                word_lower = token.lower()
                if word_lower in node.children:
                    node = node.children[word_lower]
                    word_indices_in_phrase.append(j)
                    if node.entries:
                        # Found a valid phrase. Annotate all tokens from the
                        # start of the phrase to its end.
                        start_idx = word_indices_in_phrase[0]
                        end_idx = word_indices_in_phrase[-1]
                        for k in range(start_idx, end_idx + 1):
                            annotated_tokens[k][1].update(node.entries)
                else:
                    # This sequence of words is not a valid prefix in the dictionary.
                    break
        
        # --- Search 2: Concatenated words ---
        # This search finds dictionary entries formed by concatenating adjacent word tokens.
        node = root
        concatenated_word = ""
        word_indices_in_concat = []
        for j in range(i, n):
            token = token_list[j]
            if is_word(token):
                concatenated_word += token.lower()
                word_indices_in_concat.append(j)
                
                # A concatenated word corresponds to a single-step lookup in the Trie.
                if concatenated_word in node.children:
                    match_node = node.children[concatenated_word]
                    if match_node.entries:
                        # Found a match. Annotate all the word tokens that
                        # formed this concatenated entry.
                        for k in word_indices_in_concat:
                            annotated_tokens[k][1].update(match_node.entries)
            else:
                # A non-word token breaks the concatenation sequence.
                break

    return annotated_tokens
