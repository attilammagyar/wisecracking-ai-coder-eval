# Trie node helpers
def _make_trie_node():
    # 'n' => children dict, 'e' => set of entry ids that end here
    return {'n': {}, 'e': set()}

def _insert_word_sequence(trie_root: Dict[str, Any], words: List[str], entry_id):
    node = trie_root
    for w in words:
        node = node['n'].setdefault(w, _make_trie_node())
    node['e'].add(entry_id)

def _insert_char_sequence(trie_root: Dict[str, Any], chars: str, entry_id):
    node = trie_root
    for ch in chars:
        node = node['n'].setdefault(ch, _make_trie_node())
    node['e'].add(entry_id)

def _split_words_lower(s: str) -> List[str]:
    # Split into contiguous alphabetic sequences, lowercased
    out = []
    cur = []
    for ch in s:
        if ch.isalpha():
            cur.append(ch.lower())
        else:
            if cur:
                out.append(''.join(cur))
                cur = []
    if cur:
        out.append(''.join(cur))
    return out

def build_dictionary_index(dictionary: collections.abc.Mapping) -> object:
    """
    Build a normalized index from a dictionary for fast lookup of words and
    compound phrases.

    Parameters:
        dictionary: Mapping strings (keys) to meanings (values).
    """
    # Two tries:
    # - single_word_trie: char-level trie for single-word entries
    # - phrase_trie: word-level trie for multi-word entries (len >= 2)
    single_word_trie = _make_trie_node()
    phrase_trie = _make_trie_node()

    for key, entry_id in dictionary.items():
        words = _split_words_lower(key)
        if not words:
            continue
        if len(words) == 1:
            _insert_char_sequence(single_word_trie, words[0], entry_id)
        else:
            _insert_word_sequence(phrase_trie, words, entry_id)

    # Return a simple dict as the index object
    return {
        'single_word_trie': single_word_trie,
        'phrase_trie': phrase_trie,
    }

def annotate(tokens: collections.abc.Iterable[str], dictionary_index: object) -> collections.abc.Iterable[tuple[str, collections.abc.Set]]:
    """
    Annotate tokens with entries from the dictionary.

    Parameters:
        dictionary_index:   A dictionary index created by build_dictionary_index()
        tokens:             The tokens to be annotated.

    Return:
        annotated_tokens:   A list containing (token, annotations) pairs for each token in tokens.
    """
    toks: List[str] = list(tokens)
    n = len(toks)
    annotations: List[Set] = [set() for _ in range(n)]

    if n == 0:
        return []

    single_word_trie = dictionary_index['single_word_trie']
    phrase_trie = dictionary_index['phrase_trie']

    # Classify tokens
    is_word: List[bool] = [t.isalpha() for t in toks]
    lower_word: List[Optional[str]] = [t.lower() if is_word[i] else None for i, t in enumerate(toks)]

    # Precompute next word token index at or after position i
    next_word_from: List[Optional[int]] = [None] * (n + 1)
    next_idx: Optional[int] = None
    for i in range(n - 1, -1, -1):
        if is_word[i]:
            next_idx = i
        next_word_from[i] = next_idx
    next_word_from[n] = None  # sentinel

    # Helper to annotate a phrase match spanning word positions in word_pos list
    def annotate_phrase_span(word_pos: List[int], entry_ids: Set):
        # Annotate word tokens
        for wp in word_pos:
            annotations[wp].update(entry_ids)
        # Annotate inner separators between consecutive word tokens
        for a, b in zip(word_pos, word_pos[1:]):
            for t in range(a + 1, b):
                # These are the inner separators; may be empty if words are adjacent
                annotations[t].update(entry_ids)

    # 1) Single-word matching using char trie (supports concatenation across adjacent word tokens)
    for i in range(n):
        if not is_word[i]:
            continue
        node = single_word_trie
        j = i
        while True:
            s = lower_word[j]  # type: ignore
            # Stream characters of current token
            progressed = True
            for ch in s:  # type: ignore
                nxt = node['n'].get(ch)
                if nxt is None:
                    progressed = False
                    break
                node = nxt
            if not progressed:
                break
            # At end of token boundary: accept matches that end exactly here
            if node['e']:
                # Annotate all word tokens from i..j (no separators possible between word tokens here)
                for k in range(i, j + 1):
                    annotations[k].update(node['e'])
            # Move to next adjacent word token; stop if there is any separator
            nj = next_word_from[j + 1]
            if nj is None or nj != j + 1:  # either end or a separator in between
                break
            j = nj

    # 2) Multi-word phrase matching using word trie (insensitive to separator tokens between words)
    for i in range(n):
        if not is_word[i]:
            continue
        first_word = lower_word[i]  # type: ignore
        node = phrase_trie['n'].get(first_word)
        if node is None:
            continue
        # Build list of matched word positions as we advance
        word_pos = [i]
        # If a multi-word phrase ends at the first word (shouldn't happen since len>=2), still handle generically
        if node['e']:
            annotate_phrase_span(word_pos, node['e'])

        j = i
        while True:
            # Find the next word token after j (skipping any separators)
            next_j = next_word_from[j + 1]
            if next_j is None:
                break
            next_w = lower_word[next_j]  # type: ignore
            child = node['n'].get(next_w)
            if child is None:
                break
            # Extend match
            node = child
            j = next_j
            word_pos.append(j)
            if node['e']:
                annotate_phrase_span(word_pos, node['e'])

    # Produce output
    annotated_tokens: List[Tuple[str, Set]] = [(toks[i], annotations[i]) for i in range(n)]
    return annotated_tokens
