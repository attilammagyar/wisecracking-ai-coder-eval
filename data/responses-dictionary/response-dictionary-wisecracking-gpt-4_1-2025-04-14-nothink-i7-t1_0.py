def annotate(tokens: collections.abc.Iterable[str], dictionary_index: object) -> collections.abc.Iterable[tuple[str, collections.abc.Set]]:
    """
    Annotate every token, building up phrases using the trie.
    """
    tokens = list(tokens)  # May need random access. Sorry about your RAM, but it's 2024.
    n = len(tokens)
    trie = dictionary_index["trie"]
    single_word = dictionary_index["single_word"]
    phrase_word_lengths = dictionary_index["phrase_word_lengths"]

    # Pre-classify tokens as word/separator for fast access
    token_is_word = [is_word_token(token) for token in tokens]
    token_norm = [normalize_token(token) for token in tokens] # Lower-case for matching
    
    # Each token will accumulate its annotations here
    annotations: List[Set[Any]] = [set() for _ in range(n)]

    # First, annotate single words (needed for both single and compound words)
    for i, (norm, is_word) in enumerate(zip(token_norm, token_is_word)):
        if is_word and norm in single_word:
            annotations[i].update(single_word[norm])

    # Now, find all matching phrases, possibly multi-word, starting at every word
    for start in range(n):
        # Only start a phrase match at a word token
        if not token_is_word[start]:
            continue

        node = trie
        idx = start
        match_len = 0  # Number of word tokens matched in current phrase
        positions = [] # List of indices of tokens in this phrase match (includes separators)

        word_token_positions = []  # List of indices of *word* tokens matched

        while idx < n:
            # Skip all consecutive separators—except at phrase start
            if not token_is_word[idx]:
                # Always record separator if part of a phrase
                if match_len > 0:     # Only if at least one word found
                    positions.append(idx)
                idx += 1
                continue

            # Next word token! Try to descend Trie
            norm = token_norm[idx]
            if norm not in node.children:
                break
            node = node.children[norm]
            positions.append(idx)
            word_token_positions.append(idx)
            match_len += 1

            # If this node completes a phrase, annotate it!
            for entry_id in node.entry_ids:
                num_phrase_words = phrase_word_lengths[entry_id]
                # The phrase must have exactly num_phrase_words matched
                if match_len == num_phrase_words:
                    # Only annotate tokens *within* current phrase span (from start to idx), with correct rules:
                    # * All word tokens within the span get annotation.
                    # * All *inner* separators (between the first and last matched word token) get annotation.
                    first_pos, last_pos = word_token_positions[0], word_token_positions[-1]
                    # For the span, mark tokens as phrase-annotated
                    for i2 in range(first_pos, last_pos+1):
                        if token_is_word[i2]:
                            annotations[i2].add(entry_id)
                        elif (i2 > first_pos and i2 < last_pos):
                            annotations[i2].add(entry_id)
            idx += 1

    # Return annotated tokens as list of (original_token, set of entry_ids)
    return [(token, annotation) for token, annotation in zip(tokens, annotations)]
