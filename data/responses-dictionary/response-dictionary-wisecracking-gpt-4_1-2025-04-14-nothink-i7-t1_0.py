def build_dictionary_index(dictionary: collections.abc.Mapping) -> object:
    """
    Build trie, and single-word lookup for fast annotation.
    Both keyed on lower-case tokens.
    """
    # Single word/compound lookup
    root = TrieNode()
    # Single-word direct map: word_token -> set(entry_ids)
    single_word_map: Dict[str, Set[Any]] = collections.defaultdict(set)
    # Keep track of the word count for each phrase, for separator annotation
    phrase_word_lengths: Dict[Any, int] = dict()    # entry_id -> number of word tokens

    for phrase, entry_id in dictionary.items():
        words = [normalize_token(w) for w in tokenize_phrase(phrase)]
        if not words:
            continue
        # Trie insertion
        node = root
        for w in words:
            if w not in node.children:
                node.children[w] = TrieNode()
            node = node.children[w]
        node.entry_ids.add(entry_id)
        phrase_word_lengths[entry_id] = len(words)
        # If this is a single word, note in single word map too
        if len(words) == 1:
            single_word_map[words[0]].add(entry_id)

    return {
        "trie": root,
        "single_word": single_word_map,
        "phrase_word_lengths": phrase_word_lengths
        # We don't need the original dictionary anymore.
    }


