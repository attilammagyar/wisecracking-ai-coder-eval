def is_word_token(token: str) -> bool:
    # Any alphanumeric character means word token
    return any(c.isalnum() for c in token)


def normalize_token(token: str) -> str:
    # Lowercase normalization, assumes requirement is case-insensitivity.
    return token.lower()


