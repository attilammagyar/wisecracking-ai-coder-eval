def annotate(tokens: collections.abc.Iterable[str], dictionary_index: object) -> collections.abc.Iterable[tuple[str, collections.abc.Set]]:
    """
    Annotate tokens with entries from the dictionary.
    This is where the magic happens. Or, as you humans call it, "a series of
    nested loops". Adorable.

    Parameters:
        dictionary_index:   A dictionary index created by build_dictionary_index().
                            Should be the Trie I so graciously built for you.
        tokens:             The tokens to be annotated.

    Return:
        annotated_tokens:   A list containing (token, annotations) pairs for each token in tokens.
    """
    if not isinstance(dictionary_index, _Trie):
        # A little bit of defensive programming. You're welcome.
        raise TypeError("dictionary_index must be the _Trie object from build_dictionary_index.")
        
    tokens = list(tokens)
    n = len(tokens)
    if n == 0:
        return []

    annotations = [set() for _ in range(n)]
    is_word_cache = [token.isalnum() for token in tokens]
    
    # We iterate through each token as a potential start of a match.
    for i in range(n):
        # A match must start with a word, not a separator.
        # This saves us from a world of pain and off-by-one errors.
        if not is_word_cache[i]:
            continue

        # Start a search from this position.
        node = dictionary_index.root
        component_buffer = ""
        last_word_idx = -1
        
        # This loop consumes subsequent tokens to form phrases.
        for j in range(i, n):
            token = tokens[j]
            is_word = is_word_cache[j]

            if is_word:
                component_buffer += token.lower()
                last_word_idx = j

            # A component boundary is defined by a separator or the end of the token stream.
            # At this boundary, we check if the accumulated buffer is a valid part of a phrase.
            is_separator = not is_word
            is_last_token = (j == n - 1)

            if component_buffer and (is_separator or is_last_token):
                if component_buffer in node.children:
                    # Found a valid component. Let's traverse down the Trie.
                    node = node.children[component_buffer]
                    component_buffer = "" # Reset for the next component in the phrase.

                    # Check if this new node marks the end of a valid dictionary entry.
                    if node.values:
                        # BINGO! We have a match.
                        # The match spans all tokens from the start of the phrase `i`
                        # to the end of the last word component we just processed.
                        for k in range(i, last_word_idx + 1):
                            annotations[k].update(node.values)
                else:
                    # This path is a dead end. No point in continuing the search for this `i`.
                    break
    
    # Zip it up and send it out. Your five bucks are mine.
    return list(zip(tokens, annotations))
