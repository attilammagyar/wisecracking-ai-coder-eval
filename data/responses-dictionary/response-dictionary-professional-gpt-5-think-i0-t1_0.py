def _is_word_token(token: str) -> bool:
    # A token is a "word token" if all its characters are alphanumeric.
    # Empty strings are treated as non-word tokens.
    return bool(token) and token.isalnum()

def _split_words_normalized(s: str) -> list[str]:
    # Split a string into word pieces using the same notion as _is_word_token:
    # contiguous runs of alphanumeric characters, lowercased (casefolded).
    words = []
    cur = []
    for ch in s:
        if ch.isalnum():
            cur.append(ch)
        else:
            if cur:
                words.append("".join(cur).casefold())
                cur = []
    if cur:
        words.append("".join(cur).casefold())
    return words

class _TrieNode:
    __slots__ = ("children", "ids")
    def __init__(self):
        self.children: dict[str, _TrieNode] = {}
        self.ids: set = set()

class _DictIndex:
    __slots__ = ("root",)
    def __init__(self, root: _TrieNode):
        self.root = root

def build_dictionary_index(dictionary: collections.abc.Mapping) -> object:
    """
    Build a normalized index (trie) from a dictionary for fast lookup of words and
    compound phrases. Dictionary keys are split into word pieces (alphanumeric runs),
    separators are ignored, and matching is case-insensitive.
    """
    root = _TrieNode()
    for key, entry_id in dictionary.items():
        words = _split_words_normalized(str(key))
        if not words:
            continue  # ignore entries that have no word pieces
        node = root
        for w in words:
            nxt = node.children.get(w)
            if nxt is None:
                nxt = _TrieNode()
                node.children[w] = nxt
            node = nxt
        node.ids.add(entry_id)
    return _DictIndex(root)

def annotate(tokens: collections.abc.Iterable[str], dictionary_index: object) -> collections.abc.Iterable[tuple[str, collections.abc.Set]]:
    """
    Annotate tokens with entries from the dictionary index. Words and phrases
    are matched case-insensitively across token boundaries, respecting word/separator
    structure, and annotating inner separators of phrases only.
    """
    if not isinstance(dictionary_index, _DictIndex):
        # Defensive: accept only indices produced by build_dictionary_index
        dictionary_index = dictionary_index  # let it fail naturally below if misused

    tok_list = list(tokens)
    n = len(tok_list)
    if n == 0:
        return []

    # Precompute token properties
    is_word = [_is_word_token(t) for t in tok_list]
    cf = [t.casefold() for t in tok_list]

    # Precompute, for each index that starts at a word token, all possible
    # concatenations of consecutive word tokens until a separator occurs.
    # concats_by_start[i] = list of (end_index, concatenated_string) for starts at i.
    concats_by_start: list[list[tuple[int, str]] | None] = [None] * n

    i = 0
    while i < n:
        if not is_word[i]:
            concats_by_start[i] = []
            i += 1
            continue
        # Find the end of this run of word tokens
        j = i
        while j < n and is_word[j]:
            j += 1
        run_start, run_end = i, j - 1
        # For each start in the run, build cumulative concatenations up to run_end
        for start in range(run_start, run_end + 1):
            acc = []
            lst = []
            for end in range(start, run_end + 1):
                acc.append(cf[end])
                lst.append((end, "".join(acc)))
            concats_by_start[start] = lst
        i = run_end + 1

    # Prepare annotation sets
    annotations = [set() for _ in range(n)]
    root = dictionary_index.root

    def _annotate_range(start_idx: int, end_idx: int, ids: collections.abc.Set):
        if not ids:
            return
        for k in range(start_idx, end_idx + 1):
            annotations[k].update(ids)

    # DFS extension for multi-word phrases from a given start
    def _extend_from(node: _TrieNode, start_idx: int, prev_end: int):
        pos = prev_end + 1
        # Require at least one separator between phrase words
        if pos >= n or is_word[pos]:
            return
        # Consume one or more separators
        k = pos
        while k < n and not is_word[k]:
            k += 1
        if k >= n:
            return
        # Next word starts at k
        next_options = concats_by_start[k]
        if not next_options:
            return
        for end2, s2 in next_options:
            child = node.children.get(s2)
            if child is None:
                continue
            if child.ids:
                _annotate_range(start_idx, end2, child.ids)
            _extend_from(child, start_idx, end2)

    # Try all phrase starts at each word token
    for start in range(n):
        if not is_word[start]:
            continue
        options = concats_by_start[start]
        if not options:
            continue
        for end1, s1 in options:
            node1 = root.children.get(s1)
            if node1 is None:
                continue
            # Single-word (possibly spanning multiple tokens) matches
            if node1.ids:
                _annotate_range(start, end1, node1.ids)
            # Try extending to multi-word phrases (require at least one separator)
            _extend_from(node1, start, end1)

    # Produce final annotated list
    return [(tok_list[i], annotations[i]) for i in range(n)]
