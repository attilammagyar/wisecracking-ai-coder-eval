import re
from collections import defaultdict
from collections.abc import Iterable, Mapping

def build_dictionary_index(dictionary: Mapping) -> object:
    """Preprocess dictionary into structural indices"""
    compound_index = defaultdict(set)
    concatenated_map = {}
    max_compound_length = 0

    # Process compound phrases (sequences of word parts)
    for entry, entry_id in dictionary.items():
        parts = [p.lower() for p in re.findall(r"\w+", entry)]
        if not parts:
            continue
        key = tuple(parts)
        compound_index[key].add(entry_id)
        if len(parts) > max_compound_length:
            max_compound_length = len(parts)

    # Process concatenated single-word entries
    for entry, entry_id in dictionary.items():
        normalized = re.sub(r"\W+", "", entry).lower()
        if normalized:
            concatenated_map.setdefault(normalized, set()).add(entry_id)

    return {
        "compound_index": compound_index,
        "concatenated_map": concatenated_map,
        "max_compound_length": max_compound_length
    }

def annotate(tokens: Iterable[str], dictionary_index: object) -> Iterable[tuple[str, set]]:
    """Core annotation engine"""
    word_tokens = [(idx, token.lower()) for idx, token in enumerate(tokens) if re.fullmatch(r"\w+", token)]
    annotations = [set() for _ in tokens]
    
    # Check compound phrases
    compound_index = dictionary_index["compound_index"]
    max_compound_length = dictionary_index["max_compound_length"]
    for i in range(len(word_tokens)):
        for l in range(1, max_compound_length + 1):
            if i + l > len(word_tokens):
                break
            seq_parts = [word_tokens[i + j][1] for j in range(l)]
            seq = tuple(seq_parts)
            if seq in compound_index:
                start_idx = word_tokens[i][0]
                end_idx = word_tokens[start_idx + l - 1][0]
                entry_ids = compound_index[seq]
                for idx in range(start_idx, end_idx + 1):
                    annotations[idx].update(entry_ids)

    # Check concatenated single-word entries
    concatenated_map = dictionary_index["concatenated_map"]
    for i in range(len(word_tokens)):
        current = []
        for j in range(i, len(word_tokens)):
            current.append(word_tokens[j][1].lower())
            concatenated_str = "".join(current)
            if concatenated_str in concatenated_map:
                start_idx = word_tokens[i][0]
                end_idx = word_tokens[j][0]
                entry_ids = concatenated_map[concatenated_str]
                for idx in range(start_idx, end_idx + 1):
                    annotations[idx].update(entry_ids)

    return [(token, entries) for token, entries in zip(tokens, annotations)]
