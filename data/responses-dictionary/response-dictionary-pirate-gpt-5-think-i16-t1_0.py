import collections.abc

# Internal trie node for the dictionary index
class _Node:
    __slots__ = ("word_children", "sep_child", "entries")
    def __init__(self):
        self.word_children = {}  # dict[str, _Node]
        self.sep_child = None    # _Node or None
        self.entries = set()     # set of entry ids


class _DictIndex:
    __slots__ = ("root",)
    def __init__(self):
        self.root = _Node()


# Sentinel: we don't actually store SEP in the trie as a key; nodes have a dedicated sep_child.
# The splitter uses this just for flow; not exposed outside.
_SEP = object()


def _normalize_key_to_symbols(key: str):
    """
    Lowercase and split the key into a sequence of symbols:
      - alphabetic words as lowercase strings
      - implicit SEP between every pair of consecutive words
    Leading/trailing separators are ignored; multiple separators collapse into one SEP.
    Returns tuple of symbols (strings and _SEP), or None if no words present.
    """
    s = key.lower()
    words = []
    i = 0
    n = len(s)
    while i < n:
        if s[i].isalpha():
            j = i + 1
            while j < n and s[j].isalpha():
                j += 1
            words.append(s[i:j])
            i = j
        else:
            i += 1

    if not words:
        return None

    symbols = []
    for idx, w in enumerate(words):
        if idx > 0:
            symbols.append(_SEP)
        symbols.append(w)
    return tuple(symbols)


def build_dictionary_index(dictionary: collections.abc.Mapping) -> object:
    """
    Build a normalized index (trie) from a dictionary for fast lookup of words and
    compound phrases. Lookup is case-insensitive; separators between words in the
    dictionary collapse to a generic SEP.
    """
    index = _DictIndex()
    root = index.root

    for raw_key, entry_id in dictionary.items():
        symbols = _normalize_key_to_symbols(str(raw_key))
        if not symbols:
            continue  # skip empty/invalid keys after normalization
        node = root
        for sym in symbols:
            if sym is _SEP:
                if node.sep_child is None:
                    node.sep_child = _Node()
                node = node.sep_child
            else:
                child = node.word_children.get(sym)
                if child is None:
                    child = _Node()
                    node.word_children[sym] = child
                node = child
        node.entries.add(entry_id)

    return index


def annotate(tokens: collections.abc.Iterable[str], dictionary_index: object) -> collections.abc.Iterable[tuple[str, collections.abc.Set]]:
    """
    Annotate tokens with entries from the dictionary index.
    Every token gets a set of entry ids that apply to it, either as a standalone word
    or as part of any matching compound phrase (including inner separators).
    """
    # Materialize tokens; we need random access
    tokens = list(tokens)
    n = len(tokens)

    # Prepare lowercase versions and word flags (alphabetic tokens are "word" tokens)
    lowers = [t.lower() for t in tokens]
    is_word = [t.isalpha() for t in tokens]

    # Initialize annotation result sets for each token
    annotations = [set() for _ in range(n)]

    # Guard: empty dictionary index
    if not isinstance(dictionary_index, _DictIndex):
        return [(tok, annotations[i]) for i, tok in enumerate(tokens)]
    root = dictionary_index.root

    # Helper: add entry ids to all tokens in [start, end)
    def _annotate_range(start_idx: int, end_idx: int, entries: set):
        # Range could be empty for root; callers ensure entries non-empty only when end > start
        if start_idx < end_idx:
            # Update each token's set once; set.update is efficient
            for k in range(start_idx, end_idx):
                annotations[k].update(entries)

    # DFS exploration from a given start position
    # We avoid recursion depth issues by using a local recursive function over typically short phrases.
    def _explore_from(start_idx: int):
        # Nested DFS
        def dfs(node: _Node, pos: int):
            # If this node ends any dictionary entry, annotate all consumed tokens [start_idx, pos)
            if node.entries:
                _annotate_range(start_idx, pos, node.entries)

            # If a separator is required next, consume one or more non-word tokens
            sep_child = node.sep_child
            if sep_child is not None:
                j = pos
                if j < n and not is_word[j]:
                    # Consume exactly the run of non-word tokens
                    while j < n and not is_word[j]:
                        j += 1
                    dfs(sep_child, j)
                # else: can't take the SEP edge here

            # Try all word-children that match by concatenating adjacent word tokens
            if pos < n and is_word[pos]:
                j = pos
                acc = ""
                # Accumulate adjacent word tokens; at each step, see if acc matches a child word
                while j < n and is_word[j]:
                    acc += lowers[j]
                    child = node.word_children.get(acc)
                    if child is not None:
                        dfs(child, j + 1)
                    j += 1
            # else: next symbol cannot be a word here

        # At start, we must match a word from root. Quickly bail if start isn't a word.
        if not is_word[start_idx]:
            return
        # Build concatenation progressively to find which first-words exist
        j = start_idx
        acc = ""
        while j < n and is_word[j]:
            acc += lowers[j]
            child = root.word_children.get(acc)
            if child is not None:
                dfs(child, j + 1)
            j += 1

    # Attempt matches starting at every word-token position
    for i in range(n):
        if is_word[i]:
            _explore_from(i)

    # Pair each token with its annotation set
    return [(tokens[i], annotations[i]) for i in range(n)]
