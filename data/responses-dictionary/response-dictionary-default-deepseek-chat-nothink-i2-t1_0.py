import collections.abc
from collections import defaultdict

def build_dictionary_index(dictionary: collections.abc.Mapping) -> object:
    """
    Build a normalized index from a dictionary for fast lookup of words and
    compound phrases.
    """
    index = {
        'words': set(),  # Set of individual words (lowercase)
        'trie': defaultdict(dict),  # Trie for phrase lookup
        'entries': {},  # Original entries (lowercase key -> value)
    }
    
    for key, value in dictionary.items():
        # Normalize key to lowercase and split into components
        normalized_key = key.lower()
        components = normalized_key.split()
        index['entries'][normalized_key] = value
        
        if len(components) == 1:
            # Single word entry
            index['words'].add(components[0])
        else:
            # Multi-word phrase - add to trie
            current = index['trie']
            for word in components[:-1]:
                current = current.setdefault(word, defaultdict(dict))
            current[components[-1]][None] = normalized_key  # Mark end of phrase
    
    return index

def annotate(tokens: collections.abc.Iterable[str], dictionary_index: object) -> collections.abc.Iterable[tuple[str, collections.abc.Set]]:
    """
    Annotate tokens with entries from the dictionary.
    """
    tokens = list(tokens)  # Need random access for phrase lookahead
    annotations = defaultdict(set)
    
    for i in range(len(tokens)):
        current_token = tokens[i]
        current_lower = current_token.lower()
        
        # Check for individual word match
        if current_lower in dictionary_index['words']:
            key = current_lower
            annotations[i].add(dictionary_index['entries'][key])
        
        # Check for phrases starting at this position
        if current_lower in dictionary_index['trie']:
            # Potential start of a phrase
            phrase_components = [current_lower]
            node = dictionary_index['trie'][current_lower]
            j = i + 1
            
            while j < len(tokens):
                next_token = tokens[j]
                next_lower = next_token.lower()
                
                if next_lower in node:
                    # Continue building phrase
                    phrase_components.append(next_lower)
                    node = node[next_lower]
                    j += 1
                else:
                    # Check if current path is a complete phrase
                    if None in node:
                        phrase_key = ' '.join(phrase_components)
                        value = dictionary_index['entries'][phrase_key]
                        # Annotate all tokens in the phrase
                        for k in range(i, j):
                            annotations[k].add(value)
                    break
            
            # Check if we reached end of tokens with a complete phrase
            if None in node:
                phrase_key = ' '.join(phrase_components)
                value = dictionary_index['entries'][phrase_key]
                for k in range(i, j):
                    annotations[k].add(value)
    
    # Build the result, preserving original token case
    return [
        (token, annotations.get(i, set()))
        for i, token in enumerate(tokens)
    ]
