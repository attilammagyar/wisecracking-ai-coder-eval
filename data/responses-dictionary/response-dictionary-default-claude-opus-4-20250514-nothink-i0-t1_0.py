def _is_word_token(token):
    """Check if a token contains any alphanumeric characters."""
    return bool(re.search(r'\w', token))

def _normalize_word(word):
    """Normalize a word for case-insensitive matching."""
    return word.lower()

def _extract_words(text):
    """Extract normalized words from text, ignoring separators."""
    words = []
    for match in re.finditer(r'\w+', text):
        words.append(_normalize_word(match.group()))
    return words

