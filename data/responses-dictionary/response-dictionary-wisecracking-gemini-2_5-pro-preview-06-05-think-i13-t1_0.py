    # Turning the iterator into a list. Don't worry, I won't tell anyone you
    # passed me a lazy generator. We need random access, so list it is.
    tokens = list(tokens)
    n = len(tokens)
    annotated_tokens = [(token, set()) for token in tokens]

    # We'll march through the tokens one by one. For each starting position `i`,
    # we'll launch two search parties: one for phrases and one for compound words.
    for i in range(n):
        # --- Search Party 1: The Phrase Hunters ---
        # They look for sequences of word tokens, gracefully ignoring separators.
        phrase_node = phrases_trie
        first_word_idx = -1
        for j in range(i, n):
            token = tokens[j]
            if _is_word_token(token):
                if first_word_idx == -1:
                    first_word_idx = j
                
                ltoken = token.lower()
                if ltoken in phrase_node:
                    phrase_node = phrase_node.get(ltoken, {})
                    if _END in phrase_node:
                        # Bingo! Found a phrase. Annotate everything from the
                        # first word of the phrase to this one.
                        for k in range(first_word_idx, j + 1):
                            annotated_tokens[k][1].update(phrase_node[_END])
                else:
                    # Dead end. This sequence of words isn't in our phrase book.
                    break
        
        # --- Search Party 2: The Compound Word Conjoiners ---
        # They look for adjacent word tokens that can be squished together to form a word.
        # This search only makes sense if we start on a word token.
        if not _is_word_token(tokens[i]):
            continue

        word_node = words_trie
        word_token_indices = []
        for j in range(i, n):
            token = tokens[j]
            if _is_word_token(token):
                ltoken = token.lower()
                
                # Let's see if this token can extend our current word match.
                # We traverse the trie character by character for the current token.
                temp_node = word_node
                is_match_possible = True
                for char in ltoken:
                    if char in temp_node:
                        temp_node = temp_node[char]
                    else:
                        is_match_possible = False
                        break
                
                if is_match_possible:
                    # The token fits! We've advanced.
                    word_node = temp_node
                    word_token_indices.append(j)
                    if _END in word_node:
                        # Found a complete word! Annotate all tokens that formed it.
                        for k in word_token_indices:
                            annotated_tokens[k][1].update(word_node[_END])
                else:
                    # This token breaks the chain. Retreat!
                    break
            else:
                # A separator! Compound words can't have those. The horror!
                break
                
    return annotated_tokens
