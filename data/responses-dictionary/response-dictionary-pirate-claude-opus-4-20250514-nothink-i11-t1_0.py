def is_word_token(token: str) -> bool:
    """Check if a token contains any alphanumeric characters."""
    return any(c.isalnum() for c in token)

def normalize_phrase(tokens: list[str], start: int, end: int) -> str:
    """Normalize a sequence of tokens by joining word tokens with single spaces."""
