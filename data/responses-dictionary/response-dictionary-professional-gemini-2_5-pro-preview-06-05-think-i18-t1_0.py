import collections.abc
import re

def build_dictionary_index(dictionary: collections.abc.Mapping) -> object:
    """
    Build a normalized index from a dictionary for fast lookup of words and
    compound phrases.

    Parameters:
        dictionary: Mapping strings (keys) to meanings (values).
    """
    index = {}
    for key, value in dictionary.items():
        # A key is treated as a "phrase" if it contains any non-alphanumeric
        # characters. Otherwise, it's a single word or a solid compound word.
        if re.search(r'[^a-zA-Z0-9]', key):
            # For phrases, normalize by splitting at any non-alphanumeric sequence
            # and joining with single spaces. This makes separator usage consistent.
            # E.g., "black-swan", "black, swan" both become "black swan".
            normalized_key = " ".join(filter(None, re.split(r'[^a-zA-Z0-9]+', key.lower())))
        else:
            # For solid words/compounds, just lowercase.
            # E.g., "BlackSwan" becomes "blackswan".
            normalized_key = key.lower()
        
        if not normalized_key:
            continue
            
        if normalized_key not in index:
            index[normalized_key] = set()
        index[normalized_key].add(value)
        
    return index

