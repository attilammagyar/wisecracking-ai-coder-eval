    # 'i' is the start of the sub-sequence, 'j' is the end.
    for i in range(num_words):
        start_word_token_idx = word_indices[i]
        for j in range(i, num_words):
            end_word_token_idx = word_indices[j]

            # The current sequence of word tokens being considered for a match.
            word_tokens_lower = [tokens[word_indices[k]].lower() for k in range(i, j + 1)]

            # --- 1. Check for a phrase match ---
            # A phrase is formed by joining word tokens with spaces.
            # E.g., from ["black", "swan"] -> "black swan"
            phrase_key = " ".join(word_tokens_lower)
            if phrase_key in dictionary_index:
                # For a multi-word phrase, the constituent word tokens must be
                # separated by at least one non-word token in the input.
                # A single-word match (i == j) is always considered valid.
                is_valid_phrase = True
                if i < j:  # It's a multi-word phrase
                    for k in range(i, j):
                        # Check if there is a gap between adjacent word tokens
                        if word_indices[k+1] <= word_indices[k] + 1:
                            is_valid_phrase = False
                            break
                
                if is_valid_phrase:
                    entries = dictionary_index[phrase_key]
                    # Annotate all tokens spanning the match, including inner separators.
                    for k_tok in range(start_word_token_idx, end_word_token_idx + 1):
                        annotated_tokens[k_tok][1].update(entries)

            # --- 2. Check for a compound word match ---
            # A compound word is formed by concatenating word tokens.
            # E.g., from ["black", "swan"] -> "blackswan"
            # This check is only meaningful for sequences of two or more words.
            if i < j:
                compound_key = "".join(word_tokens_lower)
                if compound_key in dictionary_index:
                    # For a compound word, the constituent word tokens must be
                    # directly adjacent in the input, with no separators.
                    is_adjacent = True
                    for k in range(i, j):
                        if word_indices[k+1] != word_indices[k] + 1:
                            is_adjacent = False
                            break
                    
