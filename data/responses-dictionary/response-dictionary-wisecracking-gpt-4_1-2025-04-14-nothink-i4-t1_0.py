import collections.abc

def normalize_token(token):
    """Returns a lowercased equivalent suitable for case-insensitive match."""
    return token.lower()

def is_word_token(token):
    """Checks if token is a 'word' token (i.e., part of words/phrases)."""
    return token.isalnum()

def tokenize_dictionary_entry(entry):
    """
    Tokenizes a dictionary phrase into a list of 'word' tokens, skipping separators.
    (For simplicity, assume dictionary entries are split on spaces and only words remain.)
    """
    # Remove multiple spaces, strip, and split on space.
    return [normalize_token(tok) for tok in entry.strip().split() if tok]

