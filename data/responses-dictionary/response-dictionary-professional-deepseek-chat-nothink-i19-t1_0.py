def build_dictionary_index(dictionary: collections.abc.Mapping) -> object:
    # Normalize all dictionary keys to lowercase and build two structures:
    # 1. A set of individual words
    # 2. A trie for compound phrases
    
    word_set = set()
    trie_root = TrieNode()
    
    for phrase, entry_id in dictionary.items():
        normalized = phrase.lower()
        parts = re.split(r'(\W+)', normalized)  # Split on word boundaries but keep separators
        words = [part for part in parts if part.strip()]
        
        if len(words) == 1 and not words[0].isspace():
            # Single word entry
            word_set.add(words[0])
            # Also add to trie for consistency in lookup
            node = trie_root
            for word in words:
                if word not in node.children:
                    node.children[word] = TrieNode()
                node = node.children[word]
            node.entry_ids.add(entry_id)
        else:
            # Compound phrase
            node = trie_root
            for word in words:
                if word not in node.children:
                    node.children[word] = TrieNode()
                node = node.children[word]
            node.entry_ids.add(entry_id)
    
    return {
        'word_set': word_set,
        'trie_root': trie_root,
        'max_phrase_length': max(len(phrase.split()) for phrase in dictionary.keys()) if dictionary else 0
    }

def is_word_token(token: str) -> bool:
    return any(c.isalpha() for c in token)

