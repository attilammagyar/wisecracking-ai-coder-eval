import collections.abc
import re

def _is_word(token: str) -> bool:
    """Checks if a token consists only of alphanumeric characters."""
    return token.isalnum()


def build_dictionary_index(dictionary: collections.abc.Mapping) -> object:
    """
    Build a normalized index from a dictionary for fast lookup of words and
    compound phrases.

    The index is a dictionary (hash map) that maps a normalized, canonical
    representation of a dictionary phrase to its corresponding set of entry IDs.
    This normalization handles case-insensitivity and variations in separators.

    Two types of keys are generated:
    1. For phrases with separators (e.g., "black swan"), the key is a
       space-separated string of the lowercased word parts ("black swan").
    2. For compound words without separators (e.g., "blackswan"), the key
       is the concatenated lowercased string itself ("blackswan").

    This allows the annotation step to handle different text tokenizations
    and separators consistently.

    Parameters:
        dictionary: Mapping strings (keys) to meanings (values).

    Returns:
        An object representing the dictionary index, in this case, a dict.
    """
    lookup_map = {}
    for phrase, entry_id in dictionary.items():
        # A phrase is considered to have separators if it contains any non-alphanumeric character.
        has_separator = any(not char.isalnum() for char in phrase)
        
        # Extract alphanumeric parts of the phrase and convert to lowercase.
        word_parts = re.findall(r'[a-zA-Z0-9]+', phrase.lower())

        if not word_parts:
            continue

        if has_separator:
            # Canonical key for phrases with separators.
            lookup_key = " ".join(word_parts)
        else:
            # Canonical key for compound words without separators.
            lookup_key = "".join(word_parts)

        if lookup_key not in lookup_map:
            lookup_map[lookup_key] = set()
        lookup_map[lookup_key].add(entry_id)
        
    return lookup_map


def annotate(tokens: collections.abc.Iterable[str], dictionary_index: object) -> collections.abc.Iterable[tuple[str, collections.abc.Set]]:
    """
    Annotate tokens with entries from the dictionary.

    This function iterates through all possible sub-sequences of tokens
    that start and end with a word token (alphanumeric). For each such
    sub-sequence, it generates a normalized lookup key and checks for a match
    in the dictionary index. If a match is found, all tokens in the
    sub-sequence (including internal separators) are annotated with the
    corresponding dictionary entry IDs.

    Parameters:
        dictionary_index: A dictionary index created by build_dictionary_index().
        tokens:           The tokens to be annotated.

    Return:
        A list containing (token, annotations) pairs for each token in tokens.
    """
    lookup_map = dictionary_index
    token_list = list(tokens)
    n = len(token_list)
    annotated_tokens = [(token, set()) for token in token_list]

    if n == 0:
        return []

    # Iterate through all possible starting positions of a match.
    for i in range(n):
        # A valid match must start with a word token. This handles cases with
        # leading separators.
        if not _is_word(token_list[i]):
            continue

        current_word_parts = []
        has_separator_in_sequence = False
        
        # Extend the match from the starting position to all possible endpoints.
        for j in range(i, n):
            token = token_list[j]

            if _is_word(token):
                current_word_parts.append(token.lower())
            else:
                # A separator contributes to making a sequence a "phrase" if it's
                # not the very first token of the sequence being considered.
                if j > i:
                    has_separator_in_sequence = True
            
            # A valid match must also end with a word token. This handles
            # trailing separators.
            if not _is_word(token):
                continue
            
            # Generate the canonical lookup key for the current token sub-sequence.
            if has_separator_in_sequence:
                lookup_key = " ".join(current_word_parts)
            else:
                lookup_key = "".join(current_word_parts)
            
            # If a match is found, apply the annotations.
            if lookup_key in lookup_map:
                entries = lookup_map[lookup_key]
                # Annotate all tokens that are part of the matched phrase,
                # including internal separators.
                for k in range(i, j + 1):
                    annotated_tokens[k][1].update(entries)
                    
    return annotated_tokens
