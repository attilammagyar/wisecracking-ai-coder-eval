def build_dictionary_index(dictionary: collections.abc.Mapping) -> object:
    """
    Build a normalized index from a dictionary for fast lookup of words and
    compound phrases.

    Parameters:
        dictionary: Mapping strings (keys) to meanings (values).
    """
    # Helpers kept local to keep the surface small.
    def split_into_word_segments(s: str) -> list[str]:
        # Extract contiguous runs of alphanumeric characters (Unicode-aware).
        s = s.lower()
        segs = []
        cur = []
        for ch in s:
            if ch.isalnum():
                cur.append(ch)
            else:
                if cur:
                    segs.append("".join(cur))
                    cur = []
        if cur:
            segs.append("".join(cur))
        return segs

    class TrieNode:
        __slots__ = ("children", "ids")
        def __init__(self):
            self.children: dict[str, TrieNode] = {}
            self.ids: set = set()

    class DictIndex:
        __slots__ = ("single_words", "max_single_len", "multi_root")
        def __init__(self):
            self.single_words: dict[str, set] = {}   # word -> set(ids)
            self.max_single_len: int = 0
            self.multi_root: TrieNode = TrieNode()

    index = DictIndex()

    # Build indices.
    for k, v in dictionary.items():
        segs = split_into_word_segments(k)
        if not segs:
            # No alphanumeric content -> cannot anchor to tokens; ignore.
            continue
        if len(segs) == 1:
            w = segs[0]
            if w:
                ids = index.single_words.get(w)
                if ids is None:
                    ids = index.single_words[w] = set()
                ids.add(v)
                if len(w) > index.max_single_len:
                    index.max_single_len = len(w)
        else:
            # Insert into trie by word segments.
            node = index.multi_root
            for seg in segs:
                child = node.children.get(seg)
                if child is None:
                    child = TrieNode()
                    node.children[seg] = child
                node = child
            node.ids.add(v)

    return index


def annotate(tokens: collections.abc.Iterable[str], dictionary_index: object) -> collections.abc.Iterable[tuple[str, collections.abc.Set]]:
    """
    Annotate tokens with entries from the dictionary.

    Parameters:
        dictionary_index:   A dictionary index created by build_dictionary_index()
        tokens:             The tokens to be annotated.

    Return:
        annotated_tokens:   A list containing (token, annotations) pairs for each token in tokens.
    """
    # Convert iterable to list for indexed access.
    toks = list(tokens)
    n = len(toks)
    ann = [set() for _ in range(n)]
    if n == 0:
        return []

    # Unpack dictionary index.
    idx = dictionary_index
    single_map = idx.single_words
    max_single_len = idx.max_single_len
    trie_root = idx.multi_root

    # Precompute lowercased tokens and word flags.
    lows = [t.lower() for t in toks]
    is_word = [any(ch.isalnum() for ch in t) for t in toks]

    # 1) Single-word matches (including concatenations across adjacent word tokens with no separators).
    # Process runs of consecutive word tokens.
    i = 0
    while i < n:
        if not is_word[i]:
            i += 1
            continue
        # Find end of the current run of consecutive word tokens (no separators).
        j = i
        while j + 1 < n and is_word[j + 1]:
            j += 1
        # For each start in the run, grow concatenation forward until max_single_len.
        for a in range(i, j + 1):
            s = ""
            # Early exit if no single-word dictionary at all.
            if max_single_len == 0:
                break
            for b in range(a, j + 1):
                s += lows[b]
                if len(s) > max_single_len:
                    break
                ids = single_map.get(s)
                if ids:
                    # Annotate all tokens from a..b (inclusive).
                    for k in range(a, b + 1):
                        ann[k].update(ids)
        i = j + 1

    # 2) Multi-word phrase matches (sequence of word tokens separated by one or more separators).
    # Build positions of word tokens for efficient stepping between words.
    word_pos = [idx for idx, w in enumerate(is_word) if w]

    # For each starting word position, walk the trie across successive word tokens.
    W = len(word_pos)
    for wi in range(W):
        node = trie_root
        # Step across subsequent word tokens, but require at least one separator between consecutive words for phrases.
        for wj in range(wi, W):
            # Enforce that for multi-word phrases, consecutive words must be separated by >=1 non-word token.
            if wj > wi:
                # If there is no separator between these two word tokens, multi-word phrase cannot include them contiguously.
                if word_pos[wj] == word_pos[wj - 1] + 1:
                    break
            word_l = lows[word_pos[wj]]
            child = node.children.get(word_l)
            if child is None:
                break
            node = child
            if node.ids:
                start_tok = word_pos[wi]
                end_tok = word_pos[wj]
                for t in range(start_tok, end_tok + 1):
                    ann[t].update(node.ids)

    # Assemble the final annotated list.
    return [(toks[i], ann[i]) for i in range(n)]
