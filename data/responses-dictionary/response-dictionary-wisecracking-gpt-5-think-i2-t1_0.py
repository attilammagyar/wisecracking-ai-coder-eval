def build_dictionary_index(dictionary: collections.abc.Mapping) -> object:
    """
    Build a normalized index from a dictionary for fast lookup of words and
    compound phrases.

    Parameters:
        dictionary: Mapping strings (keys) to meanings (values).
    """
    # Normalize keys: extract alphabetic "words" and lowercase them
    word_re = re.compile(r"[A-Za-z]+")
    root = _TrieNode()
    dict_words = set()
    for key, entry_id in dictionary.items():
        words = [w.lower() for w in word_re.findall(key)]
        if not words:
            continue
        # Insert into trie
        node = root
        for w in words:
            node = node.children.setdefault(w, _TrieNode())
            dict_words.add(w)
        node.ids.add(entry_id)

    # Build prefix set for all dictionary words (proper prefixes only)
    prefixes = set()
    for w in dict_words:
        # add proper prefixes
        for k in range(1, len(w)):
            prefixes.add(w[:k])

    return {
        "trie": root,
        "words": dict_words,
        "prefixes": prefixes,
    }


def annotate(tokens: collections.abc.Iterable[str], dictionary_index: object) -> collections.abc.Iterable[tuple[str, collections.abc.Set]]:
    """
    Annotate tokens with entries from the dictionary.

    Parameters:
        dictionary_index:   A dictionary index created by build_dictionary_index()
        tokens:             The tokens to be annotated.

    Return:
        annotated_tokens:   A list containing (token, annotations) pairs for each token in tokens.
    """
    tokens = list(tokens)
    n = len(tokens)
    annotations = [set() for _ in range(n)]
    if n == 0:
        return []

    # Pull index parts
    root: _TrieNode = dictionary_index["trie"]
    dict_words = dictionary_index["words"]
    prefixes = dictionary_index["prefixes"]

    # Precompute helpers
    lower = [t.lower() for t in tokens]
    is_word = [t.isalpha() for t in tokens]

    # Build runs of word vs separator tokens
    runs = []  # list of dicts: {'is_word': bool, 'indices': [token_indices]}
    for i, w in enumerate(is_word):
        if not runs or runs[-1]['is_word'] != w:
            runs.append({'is_word': w, 'indices': []})
        runs[-1]['indices'].append(i)

    # Candidate generator: within a word-run, from a start offset, enumerate
    # all possible dictionary words formed by concatenating consecutive tokens.
    def candidates_in_run(run_idx: int, start_off: int):
        inds = runs[run_idx]['indices']
        res = []
        conc = ""
        # Grow by whole tokens only; no mid-token matches
        for off in range(start_off, len(inds)):
            conc += lower[inds[off]]
            if conc in dict_words:
                res.append((off, conc))
            if (conc not in dict_words) and (conc not in prefixes):
                break  # cannot grow into any dictionary word
        return res

    # Annotate the tokens for a found phrase given its word segments.
    # segments: list of tuples (word_run_idx, start_off, end_off) per word
    def annotate_phrase(segments, ids):
        # annotate all word tokens in each segment
        for (wr_idx, start_off, end_off) in segments:
            word_run = runs[wr_idx]
            word_inds = word_run['indices']
            for off in range(start_off, end_off + 1):
                annotations[word_inds[off]].update(ids)
        # annotate inner separators between consecutive words
        for k in range(len(segments) - 1):
            wr_idx = segments[k][0]
            sep_run_idx = wr_idx + 1
            # Safety check; structure should alternate word/sep/word
            if 0 <= sep_run_idx < len(runs) and not runs[sep_run_idx]['is_word']:
                for ti in runs[sep_run_idx]['indices']:
                    annotations[ti].update(ids)

    # DFS to extend phrases across word runs separated by at least one sep run
    def extend(node: _TrieNode, segments):
        # Every terminal node corresponds to a valid phrase; annotate it
        if node.ids:
            annotate_phrase(segments, node.ids)

        # Try to extend to the next word (must cross a separator run)
        last_wrun_idx = segments[-1][0]
        sep_run_idx = last_wrun_idx + 1
        next_wrun_idx = last_wrun_idx + 2
        if next_wrun_idx >= len(runs):
            return
        if runs[sep_run_idx]['is_word'] or not runs[next_wrun_idx]['is_word']:
            return  # should not happen if runs alternate, but be defensive

        # Next word must start at the beginning of the next word-run, but may span multiple tokens
        for end_off, word in candidates_in_run(next_wrun_idx, 0):
            child = node.children.get(word)
            if child is not None:
                segments.append((next_wrun_idx, 0, end_off))
                extend(child, segments)
                segments.pop()

    # Attempt matches starting at every position inside word runs
    for run_idx, run in enumerate(runs):
        if not run['is_word']:
            continue
        run_len = len(run['indices'])
        for start_off in range(run_len):
            # First dictionary "word" may span multiple tokens
            for end_off, word in candidates_in_run(run_idx, start_off):
                node = root.children.get(word)
                if node is None:
                    continue
                segments = [(run_idx, start_off, end_off)]
                extend(node, segments)

    # Package output
    annotated_tokens = [(tokens[i], annotations[i]) for i in range(n)]
    return annotated_tokens
