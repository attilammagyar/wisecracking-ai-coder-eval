import collections.abc

# --- Helpers for token classification ---

def is_word_token(token):
    """Returns True if token looks like a word, False for separator."""
    # Most realistic: Token is alphanumeric (word) vs else (sep)
    # Could be more permissive depending on text, but this fits given test.
    return any(char.isalnum() for char in token)

def normalize_word(w):
    return w.lower()

def tokenize_dictionary_phrase(phrase):
    """
    Convert a dictionary phrase string into a sequence of word/separator tokens,
    so that separators (spaces, punctuation between words) are preserved.
    E.g. "AAA, BBB" -> ["AAA", ",", "BBB"]
    """
    tokens = []
    current = []
    for ch in phrase:
        if ch.isalnum():
            current.append(ch)
        else:
            if current:
                tokens.append(''.join(current))
                current = []
            if ch.strip() != '':
                tokens.append(ch)
            # else: ch is space, treat as space sep (skip)
    if current:
        tokens.append(''.join(current))
    return tokens

def iter_dictionary_tokens(phrase):
    """
    Iterate with grouping, so multi-space and separators yielded as individual tokens.
    This builds a more robust token sequence compatible with flexible separators in input.
    """
    import re
    # Split word boundaries, keep separators as tokens.
    return [t for t in re.findall(r'\w+|[^\w\s]', phrase, flags=re.UNICODE)]

def phrase_to_normalized_token_sequence(phrase):
    # Lowercase everything, preserve separator tokens
    # Accept words and non-words in original order, separated
    out = []
    for t in iter_dictionary_tokens(phrase):
        if is_word_token(t):
            out.append(normalize_word(t))
        else:
            out.append(t)
    return out

# --- Trie construction and structure ---

class DictTrieNode:
    __slots__ = ('children', 'entries')

    def __init__(self):
        self.children = {}          # token (str) -> DictTrieNode
        self.entries = set()        # set of meaning IDs

def build_dictionary_index(dictionary: collections.abc.Mapping) -> object:
    """
    Build a normalized index from dictionary keyed by lowercased word/separator token tuples.
    Use a trie on mixed word/separators.
    """
    trie = DictTrieNode()
    word_map = collections.defaultdict(set)  # For fast single word lookup: word -> entries

    for key, entry in dictionary.items():
        seq = phrase_to_normalized_token_sequence(key)
        if not seq:
            continue
        # Insert into trie
        node = trie
        for token in seq:
            if token not in node.children:
                node.children[token] = DictTrieNode()
            node = node.children[token]
        node.entries.add(entry)
        # Also for word-only entries, record for fast lookup
        if len(seq) == 1 and is_word_token(seq[0]):
            word_map[seq[0]].add(entry)
    # Store all indices in a dict-like object
    return {'trie': trie, 'word_map': word_map}

# --- Annotation algorithm ---

def annotate(tokens: collections.abc.Iterable[str], dictionary_index: object) -> collections.abc.Iterable[tuple[str, collections.abc.Set]]:
    """
    Annotate tokens with dictionary entries (words and compound/phrase).
    Returns: [(token, set of entry ids), ...]
    """
    tokens = list(tokens)  # Support multiple passes
    n = len(tokens)
    result_annotations = [set() for _ in range(n)]

    trie = dictionary_index['trie']
    word_map = dictionary_index['word_map']

    # Precompute per-token is_word status and normalized token
    token_types = []
    norm_tokens = []
    for t in tokens:
        is_word = is_word_token(t)
        token_types.append(is_word)
        if is_word:
            norm_tokens.append(normalize_word(t))
        else:
            norm_tokens.append(t)

    # 1) Individual word annotation
    for i, (is_word, norm_token) in enumerate(zip(token_types, norm_tokens)):
        if is_word:
            entries = word_map.get(norm_token)
            if entries:
                result_annotations[i].update(entries)

    # 2) Compound/multi-token phrase matching (trie-walk)
    # For every token position, try matching forward in the trie.
    for start in range(n):
        node = trie
        match_indices = []
        match_tokens = []
        current = start

        while current < n:
            tok = norm_tokens[current]
            if tok in node.children:
                node = node.children[tok]
                match_indices.append(current)
                match_tokens.append(tok)
                # Found one or more entries at this trie node?
                if node.entries:
                    # Determine word token indices in match span
                    # For correct annotation of word and inner separator tokens.
                    span = match_indices
                    # Find which indices belong to words and which to separators
                    word_indices = [idx for idx in span if token_types[idx]]
                    if not word_indices:
                        # Skip: all separator
                        pass
                    else:
                        # Inner and word tokens determination
                        first_word = word_indices[0]
                        last_word = word_indices[-1]
                        for idx in span:
                            # Token is annotated iff:
                            # - It is a word token (always, if part of phrase)
                            # - Or: it is a separator AND not the first or last token of the span
                            if token_types[idx]:
                                result_annotations[idx].update(node.entries)
                            else:
                                if first_word < idx < last_word:
                                    result_annotations[idx].update(node.entries)
                current += 1
            else:
                break
    # Collect result
    return [(token, res) for token, res in zip(tokens, result_annotations)]
