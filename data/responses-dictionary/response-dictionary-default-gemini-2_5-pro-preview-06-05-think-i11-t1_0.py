def _is_word_like(token: str) -> bool:
    """
    A token is considered word-like if it contains at least one alphanumeric character.
    This helps distinguish words from pure separators like " ", "*", or ".".
    """
    return any(c.isalnum() for c in token)


def _split_phrase(phrase: str) -> list[str]:
    """
    Splits a phrase into a list of normalized "word" parts.
    Normalization involves lowercasing and splitting by non-alphanumeric characters.
    For example, "Black-Swan Event" becomes ["black", "swan", "event"].
    """
    # Split by any sequence of one or more non-alphanumeric characters.
    parts = re.split(r'[^a-zA-Z0-9]+', phrase.lower())
    # Filter out empty strings that can result from splitting.
    return [part for part in parts if part]


