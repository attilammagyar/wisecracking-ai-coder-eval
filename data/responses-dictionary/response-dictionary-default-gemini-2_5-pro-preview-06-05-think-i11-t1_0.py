class _DictionaryIndex:
    """A helper class to store the dictionary trie."""
    _TERMINAL_KEY = '_v_'

    def __init__(self, dictionary: collections.abc.Mapping):
        self.trie = {}
        for key, value in dictionary.items():
            parts = _split_phrase(key)
            if not parts:
                continue

            node = self.trie
            for part in parts:
                node = node.setdefault(part, {})
            node.setdefault(self._TERMINAL_KEY, set()).add(value)


def _search_and_annotate(
    start_token_idx: int,
    tokens: list[str],
    index: _DictionaryIndex,
    annotated_tokens: list[tuple[str, set]]
):
    """
    Searches for all dictionary entries starting from a given token index
    and updates annotations accordingly.
    """
    n = len(tokens)
    # Stack for iterative traversal of matching possibilities.
    # Item: (trie_node, token_cursor, phrase_start_token_idx).
    stack = [(index.trie, start_token_idx, -1)]

    while stack:
        trie_node, token_cursor, phrase_start_idx = stack.pop()

        # Find the start of the next chunk of word-like tokens, skipping separators.
        chunk_start_cursor = token_cursor
        while chunk_start_cursor < n and not _is_word_like(tokens[chunk_start_cursor]):
            chunk_start_cursor += 1

        if chunk_start_cursor >= n:
            continue

        current_phrase_start_idx = phrase_start_idx if phrase_start_idx != -1 else chunk_start_cursor
        
        chunk_str = ""
        for j in range(chunk_start_cursor, n):
            if not _is_word_like(tokens[j]):
                break  # A separator ends the current word-like chunk.

            chunk_str += tokens[j]
            chunk_end_cursor = j
            
            parts = _split_phrase(chunk_str)
            if not parts:
                continue

            # Traverse the trie with the parts from the current chunk.
            match_node = trie_node
            is_match_possible = True
            for part in parts:
                if part in match_node:
                    match_node = match_node[part]
                else:
                    is_match_possible = False
                    break
            
            if is_match_possible:
                # We found a path in the trie. Check if it's a valid dictionary entry.
                if index._TERMINAL_KEY in match_node:
                    values = match_node[index._TERMINAL_KEY]
                    # Annotate all tokens from the start of the phrase to the end of the current chunk.
                    for k in range(current_phrase_start_idx, chunk_end_cursor + 1):
                        annotated_tokens[k][1].update(values)
                
                # If the trie path can be extended, search for longer phrases.
                if any(key != index._TERMINAL_KEY for key in match_node):
                    stack.append((match_node, chunk_end_cursor + 1, current_phrase_start_idx))


