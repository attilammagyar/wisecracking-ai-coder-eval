import collections.abc
import string

def is_word_token(token):
    # Is token at least one alnum? Used for both dict entries and input tokens.
    # Markdown and punct are not word tokens.
    return any(c.isalnum() for c in token)

def normalize_token(token):
    # Lowercase (case insensitivity); strip does not matter
    return token.lower()

def tokenize_phrase(phrase):
    """Tokenizes a dictionary phrase into (is_word, token) tuples."""
    result = []
    buf = ''
    curr_type = None
    for c in phrase:
        if c.isspace() or c in string.punctuation:
            # Separator
            if curr_type is True:
                result.append((True, buf))
                buf = ''
            buf += c
            curr_type = False
        else:
            # Word character
            if curr_type is False:
                result.append((False, buf))
                buf = ''
            buf += c
            curr_type = True
    if buf:
        result.append((curr_type, buf))
    # Flatten consecutive separators so that " , " is one separator
    out = []
    for is_word, t in result:
        if is_word:
            out.append((True, normalize_token(t)))
        else:
            if out and not out[-1][0]:
                # Merge consecutive separators
                out[-1] = (False, out[-1][1] + t)
            else:
                out.append((False, t))
    return out

class PhraseTrieNode:
    __slots__ = ('children', 'meanings')
    def __init__(self):
        self.children = dict()  # (is_word,bool, norm token or None)->PhraseTrieNode
        self.meanings = set()   # set of meaning ids

def build_dictionary_index(dictionary: collections.abc.Mapping) -> object:
    """
    Build a normalized index (trie) from dictionary entries for fast annotation.
    """
    root = PhraseTrieNode()
    max_word_seq_len = 1
    for phrase, meaning in dictionary.items():
        tokens = tokenize_phrase(phrase)
        # Build trie path by (is_word, normalized token). For separators,
        # treat any separator as a generic 'SEP' key (placeholder).
        node = root
        word_count = 0
        for is_word, t in tokens:
            key = (is_word, normalize_token(t) if is_word else None)
            if is_word:
                word_count += 1
            if key not in node.children:
                node.children[key] = PhraseTrieNode()
            node = node.children[key]
        node.meanings.add(meaning)
        if word_count > max_word_seq_len:
            max_word_seq_len = word_count
    # Store max lookahead for efficient annotate
    root.max_word_seq_len = max_word_seq_len
    return root

def annotate(tokens: collections.abc.Iterable[str], dictionary_index: object) -> collections.abc.Iterable[tuple[str, collections.abc.Set]]:
    """
    Annotate tokens with dictionary entries ("meanings") based on the trie index.
    """
    PhraseTrieNode = type(dictionary_index)
    tokens = list(tokens)
    n = len(tokens)
    # Precompute for each token: is it a word token?
    token_is_word = [is_word_token(tok) for tok in tokens]
    norm_tokens = [normalize_token(tok) for tok in tokens]
    # Prepare annotation bag for each token
    token_annots = [set() for _ in tokens]

    max_word_seq_len = getattr(dictionary_index, 'max_word_seq_len', 16)  # fallback

    # For every possible phrase start...
    for i in range(n):
        node = dictionary_index
        t = i
        word_count = 0
        # Marks the start/end of phrase (by word tokens)
        trailing_sep_idxs = []
        path = []
        while t < n:
            key = (token_is_word[t], norm_tokens[t] if token_is_word[t] else None)
            if key not in node.children:
                # If separator: generic matching, try to match any separator?
                if not token_is_word[t]:
                    # Any separator in the dict is treated as (False, None)
                    key_any_sep = (False, None)
                    if key_any_sep in node.children:
                        node = node.children[key_any_sep]
                        path.append(t)
                        t += 1
                        trailing_sep_idxs.append(t-1)
                        continue
                break
            node = node.children[key]
            path.append(t)
            if token_is_word[t]:
                word_count += 1
                if word_count >= max_word_seq_len:
                    # Don't search way beyond what's possible
                    break
            if node.meanings:
                # Matched a phrase. Need to annotate it!
                # To apply the rules: mark all tokens in path, but:
                # Only inner separators are annotated, not leading/trailing ones
                # (i.e., if path starts/ends on a separator, don't annotate these seps)
                first = path[0]
                last = path[-1]
                leading = first if not token_is_word[first] else None
                trailing = last if not token_is_word[last] else None
                for idx in path:
                    # Annotate all, except leading/trailing sep(s)
                    if idx == leading or idx == trailing:
                        continue
                    token_annots[idx].update(node.meanings)
            t += 1

    # Now, for every token, optionally annotate as a single word
    # (single-token dictionary entries)
    node = dictionary_index
    for idx, (tok, is_w, norm) in enumerate(zip(tokens, token_is_word, norm_tokens)):
        if is_w:
            key = (True, norm)
            if key in node.children and node.children[key].meanings:
                token_annots[idx].update(node.children[key].meanings)

    return [(tok, anns) for tok, anns in zip(tokens, token_annots)]
