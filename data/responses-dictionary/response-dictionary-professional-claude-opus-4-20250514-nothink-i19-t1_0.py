def build_dictionary_index(dictionary: collections.abc.Mapping) -> object:
    """
    Build a normalized index from a dictionary for fast lookup of words and
    compound phrases.

    Parameters:
        dictionary: Mapping strings (keys) to meanings (values).
    """
    index = {
        'entries': {},  # normalized_key -> entry_id
        'word_positions': {},  # normalized_word -> list of (normalized_key, position)
        'phrase_lengths': {},  # normalized_key -> number of words in phrase
    }
    
    for key, value in dictionary.items():
        normalized_key = key.lower()
        index['entries'][normalized_key] = value
        
        # Split into words, keeping track of positions
        words = []
        current_word = []
        for char in normalized_key:
            if char.isalnum():
                current_word.append(char)
            else:
                if current_word:
                    words.append(''.join(current_word))
                    current_word = []
        if current_word:
            words.append(''.join(current_word))
        
        index['phrase_lengths'][normalized_key] = len(words)
        
        # Store word positions for compound phrase detection
        for i, word in enumerate(words):
            if word not in index['word_positions']:
                index['word_positions'][word] = []
            index['word_positions'][word].append((normalized_key, i))
    
    return index

