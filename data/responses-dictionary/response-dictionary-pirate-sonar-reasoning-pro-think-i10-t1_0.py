def build_dictionary_index(dictionary):
    """Build a trie and metadata for efficient lookups."""
    trie = {}
    max_length = 0
    single_words = {}

    for key, value in dictionary.items():
        # Normalize by removing non-alphanumeric characters and splitting into words
        normalized = ''.join([c if c.isalpha() else ' ' for c in key.lower()]).strip().split()
        if not normalized:
            continue
        
        # Update max phrase length
        if len(normalized) > max_length:
            max_length = len(normalized)

        current = trie
        for word in normalized:
            if word not in current:
                current[word] = {'children': {}, 'entries': set()}
            current = current[word]['children']
        
        # Store single words and phrase entries
        if len(normalized) == 1:
            if word in single_words:
                single_words[word].add(value)
            else:
                single_words[word] = {value}
        current['entries'].add(value)

    return {
        'trie': trie,
        'max_length': max_length,
        'single_words': single_words
    }

