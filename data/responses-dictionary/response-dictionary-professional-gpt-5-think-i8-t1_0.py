def _split_words(s: str) -> tuple[str, ...]:
    """
    Split a dictionary key into alphanumeric 'words' (lowercased).
    Non-alphanumeric characters are treated as separators and discarded.
    """
    words = []
    cur = []
    for ch in s:
        if ch.isalnum():
            cur.append(ch.lower())
        else:
            if cur:
                words.append("".join(cur))
                cur = []
    if cur:
        words.append("".join(cur))
    return tuple(words)


def build_dictionary_index(dictionary: collections.abc.Mapping) -> object:
    """
    Build a normalized index:
      - phrase_trie: trie of multi-word phrases (len(words) >= 2)
      - single_map:  dict word -> set(ids) for single-word entries
      - single_prefixes: set of all prefixes of single_map keys (for pruning)
    """
    root = _TrieNode()
    single_map = {}       # word -> set(ids)
    single_prefixes = set()

    for key, val in dictionary.items():
        words = _split_words(key)
        if not words:
            continue
        if len(words) == 1:
            w = words[0]
            s = single_map.get(w)
            if s is None:
                s = set()
                single_map[w] = s
                # add prefixes once per new word
