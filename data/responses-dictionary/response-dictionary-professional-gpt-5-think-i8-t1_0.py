def annotate(tokens: collections.abc.Iterable[str], dictionary_index: object) -> collections.abc.Iterable[tuple[str, collections.abc.Set]]:
    """
    Annotate tokens with dictionary entries (individual words and compound phrases).
    """
    tokens = list(tokens)
    n = len(tokens)
    annotated_tokens = [set() for _ in range(n)]
    if n == 0:
        return []

    phrase_root, single_map, single_prefixes = dictionary_index

    # Precompute classifications and lowercase forms
    is_word = [t.isalnum() for t in tokens]
    lower_tokens = [t.lower() for t in tokens]

    # 1) Direct single-word matches on individual tokens
    for i, (t_is_word, lt) in enumerate(zip(is_word, lower_tokens)):
        if t_is_word:
            vals = single_map.get(lt)
            if vals:
                annotated_tokens[i].update(vals)

    # 2) Single-word matches by concatenating adjacent word tokens with no separators
    i = 0
    while i < n:
        if not is_word[i]:
            i += 1
            continue
        j = i
        while j < n and is_word[j]:
            j += 1
        # Now [i, j) is a maximal run of contiguous word tokens with no separators
        run = lower_tokens[i:j]
        run_len = len(run)
        # Try all starts in this run
        for s in range(run_len):
            cur = ""
            # Extend to the right while prefixes match
            for k in range(s, run_len):
                # Build incrementally; break early if no prefix
                cur += run[k]
                if cur not in single_prefixes:
                    break
                vals = single_map.get(cur)
                if vals:
                    # Annotate tokens from global positions [i+s .. i+k]
                    for p in range(i + s, i + k + 1):
                        annotated_tokens[p].update(vals)
        i = j

    # 3) Multi-word phrase matches via trie over the sequence of word tokens
    word_positions = [idx for idx, w in enumerate(is_word) if w]
    word_values = [lower_tokens[idx] for idx in word_positions]
    W = len(word_positions)

    for start in range(W):
        node = phrase_root
        # Try to extend as long as edges exist
        for end in range(start, W):
            w = word_values[end]
            child = node.children.get(w)
            if child is None:
                break
            node = child
            if node.out:
                # Map word indices [start .. end] to token indices [s .. e]
                s_tok = word_positions[start]
                e_tok = word_positions[end]
                # Annotate the entire inclusive span, which includes only inner separators
                for p in range(s_tok, e_tok + 1):
                    annotated_tokens[p].update(node.out)

    # Prepare output
    return [(tok, anns) for tok, anns in zip(tokens, annotated_tokens)]
