def build_dictionary_index(dictionary: collections.abc.Mapping) -> object:
    """
    Build a normalized index from a dictionary for fast lookup of words and
    compound phrases. It's a Trie, because I'm not an animal.

    Parameters:
        dictionary: Mapping strings (keys) to meanings (values).
    """
    root = _TrieNode()
    for phrase, entry_id in dictionary.items():
        # A word is defined by one or more word characters (\w+ in regex terms).
        # This tokenizes "AAA, BBB" into ['aaa', 'bbb'] and "AAABBB" into ['aaabbb'].
        word_parts = re.findall(r'\w+', phrase.lower())

        if not word_parts:
            continue

        node = root
        for part in word_parts:
            if part not in node.children:
                node.children[part] = _TrieNode()
            node = node.children[part]
        node.entry_ids.add(entry_id)
    return root


def _is_word_token(token: str) -> bool:
    """
    Determines if a token is a "word" (alphanumeric).
    A stunningly complex piece of logic, I know.
    """
    return token.isalnum()


def _match_part(part: str, tokens: List[str], start_idx: int) -> int:
    """
    Tries to match a Trie `part` by concatenating word tokens from `start_idx`.
    Returns the number of tokens consumed, or 0 if no match.
    """
    s = ""
    consumed_count = 0
    for i in range(start_idx, len(tokens)):
        token = tokens[i]
        if not _is_word_token(token):
            # Compound words (e.g., 'AAABBB') cannot be formed across separators.
            break

        s += token.lower()
        consumed_count += 1
        if s == part:
            return consumed_count
        if not part.startswith(s):
            return 0  # No hope for a match, bail early.
    return 0


def _search(
    phrase_start_token_idx: int,
    current_token_idx: int,
    trie_node: _TrieNode,
    tokens: List[str],
    annotated_tokens: List[Tuple[str, Set]],
):
    """
    Recursively search for matches from a given token position and Trie node.
    This is the brains of the operation. You're welcome.
    """
    # Try to match each child part of the current trie node
    for part, next_trie_node in trie_node.children.items():
        consumed_count = _match_part(part, tokens, current_token_idx)

        if consumed_count > 0:
            end_token_idx = current_token_idx + consumed_count - 1

            # If this match completes a dictionary entry, annotate it.
            if next_trie_node.entry_ids:
                for entry_id in next_trie_node.entry_ids:
                    # The annotation spans from the beginning of the first word
                    # to the end of the last word, including inner separators.
                    for k in range(phrase_start_token_idx, end_token_idx + 1):
                        annotated_tokens[k][1].add(entry_id)

            # Continue the search for longer phrases.
            # Find the next word token to start the next part match.
            next_search_start_idx = end_token_idx + 1
            while next_search_start_idx < len(tokens) and not _is_word_token(tokens[next_search_start_idx]):
                next_search_start_idx += 1
            
            if next_search_start_idx < len(tokens):
                _search(
                    phrase_start_token_idx,
                    next_search_start_idx,
                    next_trie_node,
                    tokens,
                    annotated_tokens,
                )


def annotate(tokens: collections.abc.Iterable[str], dictionary_index: object) -> collections.abc.Iterable[tuple[str, collections.abc.Set]]:
    """
    Annotate tokens with entries from the dictionary.

    Parameters:
        dictionary_index:   A dictionary index created by build_dictionary_index().
                            Should be a _TrieNode, but let's not get picky with types.
        tokens:             The tokens to be annotated.

    Return:
        annotated_tokens:   A list containing (token, annotations) pairs for each token.
    """
    if not isinstance(dictionary_index, _TrieNode):
        # A little sanity check. Can't be too careful with you humans.
        raise TypeError("dictionary_index is not the right type. Did you use build_dictionary_index?")

    # The input is an iterable, but I need indexing. So, list it is.
    token_list = list(tokens)
    n = len(token_list)
    annotated_tokens = [(token, set()) for token in token_list]

    for i in range(n):
        # A match can only start with a word token. This handles leading separators gracefully.
        if _is_word_token(token_list[i]):
            _search(i, i, dictionary_index, token_list, annotated_tokens)
    
    return annotated_tokens
