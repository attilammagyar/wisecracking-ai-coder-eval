def build_dictionary_index(dictionary: collections.abc.Mapping) -> object:
    """
    Build a normalized index from a dictionary for fast lookup of words and
    compound phrases.

    The index consists of two parts:
    1. A dict for single-word/compound-word entries for O(1) lookup.
    2. A Trie (implemented with nested dicts) for multi-word phrases for
       efficient prefix-based matching.

    Parameters:
        dictionary: Mapping strings (keys) to meanings (values).
    
    Returns:
        A tuple containing the word_index and the phrase_index (Trie root).
    """
    # word_index for single/concatenated words:
    # { "normalized_word": {value1, value2, ...} }
    word_index = {}
    
    # phrase_index for multi-word phrases (Trie):
    # { 'children': { 'word': { ... } }, 'values': {value1, ...} }
    phrase_index = {'children': {}, 'values': set()}

    for key, value in dictionary.items():
        word_parts = _tokenize_dictionary_key(key)
        
        if not word_parts:
            continue

        if len(word_parts) == 1:
            # A single "word" entry, e.g., "cat" or "blackswan".
            normalized_word = word_parts[0]
            if normalized_word not in word_index:
                word_index[normalized_word] = set()
            word_index[normalized_word].add(value)
        else:
            # A multi-word phrase entry. Add it to the phrase trie.
            node = phrase_index
            for part in word_parts:
                if part not in node['children']:
                    node['children'][part] = {'children': {}, 'values': set()}
                node = node['children'][part]
            node['values'].add(value)
            
    return word_index, phrase_index

def annotate(tokens: collections.abc.Iterable[str], dictionary_index: object) -> collections.abc.Iterable[tuple[str, collections.abc.Set]]:
    """
    Annotate tokens with entries from the dictionary.

    This function iterates through each token, treating it as a potential
    starting point for a match. From each starting point, it performs two
    types of lookups:
    1. Concatenated word matching: For dictionary entries like "AAABBB" that
       match a sequence of tokens ["AAA", "BBB"].
    2. Phrase matching: For dictionary entries like "black swan" that match
       a sequence of tokens like ["black", " ", "swan"].

    Parameters:
        dictionary_index:   A dictionary index created by build_dictionary_index().
        tokens:             The tokens to be annotated.

    Return:
        annotated_tokens:   A list containing (token, annotations) pairs for
                            each token in tokens.
    """
    token_list = list(tokens)
    if not token_list:
        return []
    
    word_index, phrase_index = dictionary_index
    n = len(token_list)
    annotated_tokens = [(token, set()) for token in token_list]

    for i in range(n):
        # Part 1: Concatenated word matching (e.g., "AAABBB")
        current_concatenation = ""
        word_token_indices = []
        for j in range(i, n):
            token = token_list[j]
            if _is_word_token(token):
                current_concatenation += token.lower()
                word_token_indices.append(j)
                if current_concatenation in word_index:
                    values = word_index[current_concatenation]
                    # Annotate only the word tokens forming the match.
                    for token_idx in word_token_indices:
                        annotated_tokens[token_idx][1].update(values)
            else:
                # Separators break concatenated word matches.
                break

        # Part 2: Phrase matching (e.g., "AAA BBB")
        if not _is_word_token(token_list[i]):
            # A phrase must start with a word, not a separator.
            continue
        
        node = phrase_index
        for j in range(i, n):
            token = token_list[j]
            if _is_word_token(token):
                normalized_word = token.lower()
                if normalized_word in node.get('children', {}):
                    node = node['children'][normalized_word]
                    if node['values']:
                        # Found a phrase match ending at token j.
                        # Annotate all tokens from the start of the phrase (i)
                        # to the current token (j), including inner separators.
                        for k in range(i, j + 1):
                            annotated_tokens[k][1].update(node['values'])
                else:
                    # The word sequence is not in the phrase trie.
                    break
            # If token is a separator, we consume it by continuing the loop.
            
    return annotated_tokens
