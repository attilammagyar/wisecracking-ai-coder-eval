def build_dictionary_index(dictionary: collections.abc.Mapping) -> object:
    """
    Build a normalized index from a dictionary for fast lookup of words and
    compound phrases.
    """
    # 1. Build single-token word index: {normalized token: set(entries)}
    word_map = dict()
    # 2. Build multi-token phrase trie
    trie_root = _TrieNode()
    max_phrase_len = 1
    
    for entry, entry_id in dictionary.items():
        entry_tokens = _normalize_dict_entry(entry)
        if not entry_tokens:
            continue
        # 1. Single-word entries
        if len(entry_tokens) == 1:
            k = entry_tokens[0]
            word_map.setdefault(k, set()).add(entry_id)
        # 2. Compound entries (including multi-word and pure symbol "words")
        node = trie_root
        for t in entry_tokens:
            if t not in node.children:
                node.children[t] = _TrieNode()
            node = node.children[t]
        node.entry_ids.add(entry_id)
        if len(entry_tokens) > max_phrase_len:
            max_phrase_len = len(entry_tokens)
    return {
        'word_map': word_map,
        'trie_root': trie_root,
        'max_phrase_len': max_phrase_len,
    }

