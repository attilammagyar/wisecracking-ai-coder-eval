    for i in range(n):
        node = trie_root
        last_match = None     # (end_idx, entry_ids, first_word_idx, last_word_idx)
        j = i
        first_word_j = None   # index of first word token in window
        last_word_j = None    # index of last word token in window
        # We'll build the candidate window up to max_phrase_len tokens
        phrase_token_idxs = []
        for k in range(max_phrase_len):
            if j >= n:
                break
            norm_tok = normalized_tokens[j]
            if norm_tok not in node.children:
                break
            node = node.children[norm_tok]
            phrase_token_idxs.append(j)
            # update first_word/last_word indices
            if is_word[j]:
                if first_word_j is None:
                    first_word_j = j
                last_word_j = j
            if node.entry_ids:
                # Only treat as match if phrase starts and ends with word tokens (per test rules).
                # Leading/trailing separators outside them are not to be included in annotation.
                # But if phrase is e.g. [" ", "aaa", " ", "bbb", " "], we only annotate the subset ["aaa", " ", "bbb"] (the "inner" part).
                # So only if there is at least one word token, we match
                if first_word_j is not None and last_word_j is not None:
                    # Find extent from first_word_j to last_word_j (inclusive)
                    last_match = (first_word_j, last_word_j, set(node.entry_ids))
            j += 1
        if last_match:
            # Annotate the window from first_word_j to last_word_j inclusive
            start, end, entry_ids = last_match
            for k in range(start, end + 1):
                # Annotate all tokens in window.
                # Only annotate separators that are *within* window (that is, not at start/end of phrase as per rules)
                if is_word[k]:
                    ann[k].update(entry_ids)
                else:
                    # Only annotate if not at window boundary
                    if k != start and k != end:
                        ann[k].update(entry_ids)

    # 2. Single token words
    for i in range(n):
        if is_word[i]:
            entry_ids = word_map.get(normalized_tokens[i])
            if entry_ids:
                ann[i].update(entry_ids)

    return [(tokens[i], ann[i]) for i in range(n)]
