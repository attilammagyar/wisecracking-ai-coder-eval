def _is_word_token(token):
    # Heuristic: a word token has at least one alphanumeric char.
    return any(c.isalnum() for c in token)

def _normalize_token(token):
    # Lowercase and strip for normalization
    return token.lower()

def _normalize_dict_entry(entry):
    # Lowercase, and split on whitespace and common separators for index building.
    # We'll keep contiguous runs of word characters as tokens, and everything else as separators.
    # This simulates a generic tokenizer.
    tokens = []
    current = []
    for c in entry:
        if c.isalnum():
            current.append(c.lower())
        else:
            if current:
                tokens.append(''.join(current))
                current = []
            if not c.isspace():  # don't keep spaces as tokens at index build time
                tokens.append(c)
    if current:
        tokens.append(''.join(current))
    # Remove tokens that are only whitespace
    tokens = [t for t in tokens if t.strip()]
    return tokens

