import collections.abc
import re

def build_dictionary_index(dictionary: collections.abc.Mapping) -> object:
    """
    Build a normalized index from a dictionary for fast lookup of words and
    compound phrases.

    The index is a Trie data structure where each node represents a word in a
    phrase. This allows for efficient prefix-based searching of multi-word
    phrases.

    Parameters:
        dictionary: Mapping strings (keys) to meanings (values).
    
    Returns:
        The root of the word-based Trie index.
    """
    def _new_trie_node():
        # Each node contains children and a set of values for entries ending at this node.
        return {'children': {}, 'values': set()}

    root = _new_trie_node()
    for phrase, value in dictionary.items():
        # Normalize the phrase: lowercase and extract alphanumeric words.
        # This handles case-insensitivity and variations in separators.
        words = re.findall(r'[a-zA-Z0-9]+', phrase.lower())
        
        if not words:
            continue

        node = root
        for word in words:
            node = node['children'].setdefault(word, _new_trie_node())
        
        # Store the dictionary entry's value at the end of the phrase path.
        node['values'].add(value)
        
    return root


def annotate(tokens: collections.abc.Iterable[str], dictionary_index: object) -> collections.abc.Iterable[tuple[str, collections.abc.Set]]:
    """
    Annotate tokens with entries from the dictionary using a pre-built index.

    The algorithm works in two main stages:
    1. Token Segmentation: Groups consecutive word-like input tokens into
       logical "word segments". This unifies handling of single tokens,
       concatenated tokens (e.g., ["AAA", "BBB"] -> "aaabbb"), and phrases.
    2. Matching and Annotation: Iterates through the word segments, using the
       Trie to find all matching phrases. When a phrase is matched, all
       original tokens it spans (including inner separators) are annotated.

    Parameters:
        dictionary_index: A dictionary index created by build_dictionary_index().
        tokens:           The tokens to be annotated.

    Return:
        annotated_tokens: A list of (token, annotations) pairs.
    """
    # Using a namedtuple for clarity to represent a logical word segment.
    _WordSegment = collections.namedtuple('WordSegment', ['text', 'start_idx', 'end_idx'])

    def _is_word_token(token: str) -> bool:
        """A simple heuristic to classify tokens."""
        return token.isalnum()

    def _segment_tokens(tokens: collections.abc.Sequence[str]) -> list[_WordSegment]:
        """
        Groups consecutive word-like tokens into single segments.
        Example: ["AAA", "BBB", " ", "C"] -> [("aaabbb", 0, 1), ("c", 3, 3)]
        """
        word_segments = []
        i = 0
        n = len(tokens)
        while i < n:
            if _is_word_token(tokens[i]):
                start_idx = i
                word_parts = [tokens[i]]
                i += 1
                while i < n and _is_word_token(tokens[i]):
                    word_parts.append(tokens[i])
                    i += 1
                
                # A segment is formed by one or more consecutive word tokens.
                # Its text is the concatenation of these tokens, lowercased.
                segment_text = "".join(word_parts).lower()
                word_segments.append(_WordSegment(segment_text, start_idx, i - 1))
            else:
                # This is a separator, so we skip it and move to the next token.
                i += 1
        return word_segments

    # Ensure we can index tokens by converting the iterable to a list.
    token_list = list(tokens)
    if not token_list:
        return []

    annotated_tokens = [(token, set()) for token in token_list]
    word_segments = _segment_tokens(token_list)
    num_segments = len(word_segments)

    # Iterate through each word segment as a potential start of a phrase.
    for i in range(num_segments):
        node = dictionary_index
        # Try to match phrases starting from the i-th word segment.
        for j in range(i, num_segments):
            segment = word_segments[j]
            
            if segment.text in node['children']:
                node = node['children'][segment.text]
                
                # If the current node has values, we have found a dictionary entry.
                if node['values']:
                    # The matched phrase spans from the start of the i-th segment
                    # to the end of the j-th segment.
                    first_token_idx = word_segments[i].start_idx
                    last_token_idx = word_segments[j].end_idx
                    
                    # Annotate all original tokens within this span.
                    for value in node['values']:
                        for k in range(first_token_idx, last_token_idx + 1):
                            annotated_tokens[k][1].add(value)
            else:
                # No path in the Trie for the current segment, so no longer
                # phrases can be formed from this starting point.
                break
    
    return annotated_tokens
