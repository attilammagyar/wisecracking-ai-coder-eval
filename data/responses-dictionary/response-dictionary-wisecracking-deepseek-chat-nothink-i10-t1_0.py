class TrieNode:
    __slots__ = ('values', 'children')
    
    def __init__(self):
        self.values: Set = set()
        self.children: Dict[str, 'TrieNode'] = {}

def build_dictionary_index(dictionary: collections.abc.Mapping) -> object:
    """
    Build a case-insensitive trie index from the dictionary.
    """
    root = TrieNode()
    
    for phrase, value in dictionary.items():
        node = root
        # Split into words (normalized to lowercase) and separators
        parts = []
        current_word = []
        
        for c in phrase:
            if c.isalpha():
                current_word.append(c.lower())
            else:
                if current_word:
                    parts.append(''.join(current_word))
                    current_word = []
                parts.append(c)
        
        if current_word:
            parts.append(''.join(current_word))
        
        # Build the trie path
        for part in parts:
            if part not in node.children:
                node.children[part] = TrieNode()
            node = node.children[part]
        node.values.add(value)
    
    return root

def is_word_token(token: str) -> bool:
    """Check if token looks like a word (contains at least one letter)."""
    return any(c.isalpha() for c in token)

def annotate(tokens: collections.abc.Iterable[str], dictionary_index: object) -> collections.abc.Iterable[Tuple[str, Set]]:
    """
    Annotate tokens with dictionary entries using greedy phrase matching.
    """
    tokens = list(tokens)
    annotations = [set() for _ in tokens]
    root = dictionary_index
    
    for i in range(len(tokens)):
        if not is_word_token(tokens[i]):
            continue
            
        current_node = root
        j = i
        matched_indices = []
        
        while j < len(tokens):
            token = tokens[j]
            normalized = token.lower() if is_word_token(token) else token
            
            if normalized in current_node.children:
                current_node = current_node.children[normalized]
                matched_indices.append(j)
                j += 1
                
                # If this is a complete phrase, add annotations
                if current_node.values:
                    for idx in matched_indices:
                        annotations[idx].update(current_node.values)
            else:
                break
    
    # Handle individual word matches
    for i, token in enumerate(tokens):
        if is_word_token(token):
            normalized = token.lower()
            node = root.children.get(normalized, None)
            if node and node.values:
                annotations[i].update(node.values)
    
    return list(zip(tokens, annotations))
