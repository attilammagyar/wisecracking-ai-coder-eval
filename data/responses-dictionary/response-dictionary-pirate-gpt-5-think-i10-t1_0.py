def build_dictionary_index(dictionary: collections.abc.Mapping) -> object:
    """
    Build a normalized index from a dictionary for fast lookup of words and
    compound phrases.

    Parameters:
        dictionary: Mapping strings (keys) to meanings (values).
    """
    single_words: dict[str, set] = {}
    root = _TrieNode()

    for key, ident in dictionary.items():
        parts = _split_to_words(key)
        if not parts:
            continue
        if len(parts) == 1:
            w = parts[0]
            s = single_words.get(w)
            if s is None:
                s = set()
                single_words[w] = s
            s.add(ident)
        else:
            node = root
            for w in parts:
                nxt = node.children.get(w)
                if nxt is None:
                    nxt = _TrieNode()
                    node.children[w] = nxt
                node = nxt
            node.ids.add(ident)

    return _DictionaryIndex(single_words, root)

def annotate(tokens: collections.abc.Iterable[str], dictionary_index: object) -> collections.abc.Iterable[tuple[str, collections.abc.Set]]:
    """
    Annotate tokens with entries from the dictionary.

    Parameters:
        dictionary_index:   A dictionary index created by build_dictionary_index()
        tokens:             The tokens to be annotated.

    Return:
        annotated_tokens:   A list containing (token, annotations) pairs for each token in tokens.
    """
    idx = dictionary_index  # type: _DictionaryIndex
    toks = list(tokens)
    n = len(toks)
    ann = [set() for _ in range(n)]

    # Precompute word flags and lowercased words
    is_word = [_is_word_token(t) for t in toks]
    low = [t.lower() if is_word[i] else t for i, t in enumerate(toks)]

    # 1) Direct single-word matches per token
    sw = idx.single_words
    for i, ok in enumerate(is_word):
        if not ok:
            continue
        ids = sw.get(low[i])
        if ids:
            ann[i].update(ids)

    # Build list of (word_lower, token_index) for all word tokens
    words = [(low[i], i) for i in range(n) if is_word[i]]
    m = len(words)

    if m == 0:
        return [(toks[i], ann[i]) for i in range(n)]

    # Precompute gaps: had_separator_between[k] says there is >=1 non-word token
    # between words[k] and words[k+1]
    had_sep = []
    for k in range(m - 1):
        left = words[k][1]
        right = words[k + 1][1]
        had_sep.append(right > left + 1)

    # Helper to annotate word range [a..b] and inner separators
    def annotate_phrase_range(a: int, b: int, ids: collections.abc.Set):
        # Annotate words
        for wi in range(a, b + 1):
            ann[words[wi][1]].update(ids)
        # Annotate inner separators only
        for wi in range(a, b):
            lti = words[wi][1]
            rti = words[wi + 1][1]
            # tokens strictly between lti and rti
            for ti in range(lti + 1, rti):
                ann[ti].update(ids)

    # 2) Multi-word phrases (with separators) via trie
    root = idx.phrase_trie
    for s in range(m):
        first_word = words[s][0]
        node = root.children.get(first_word)
        if node is None:
            continue
        j = s
        current = node
        # We record matches at each node that has an id set
        while True:
            if current.ids:
                annotate_phrase_range(s, j, current.ids)
            # Try extend to next word; require there be a separator between words[j] and words[j+1]
            if j + 1 >= m:
                break
            if not had_sep[j]:
                break
            nxt = current.children.get(words[j + 1][0])
            if nxt is None:
                break
            current = nxt
            j += 1

    # 3) Single-word entries matched by concatenating adjacent word tokens (no separators)
    # Process maximal runs where had_sep is False between neighbors
    i = 0
    while i < m:
        # Find end of run with no separators between words
        run_end = i
        while run_end + 1 < m and not had_sep[run_end]:
            run_end += 1

        # For each start in the run, try concatenations of length >= 2
        for s in range(i, run_end + 1):
            concat = words[s][0]
            for e in range(s + 1, run_end + 1):
                concat += words[e][0]
                ids = sw.get(concat)
                if ids:
                    annotate_phrase_range(s, e, ids)

        i = run_end + 1

    return [(toks[i], ann[i]) for i in range(n)]
