def _is_word_token(tok: str) -> bool:
    # Word token: all chars alphanumeric, non-empty
    return bool(tok) and all(ch.isalnum() for ch in tok)

def _split_to_words(text: str) -> list[str]:
    # Split by non-alnum, keep only alnum runs, lowercase
    words = []
    cur = []
    for ch in text:
        if ch.isalnum():
            cur.append(ch.lower())
        else:
            if cur:
                words.append("".join(cur))
                cur = []
    if cur:
        words.append("".join(cur))
    return words

