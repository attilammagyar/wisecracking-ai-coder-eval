import collections.abc

def build_dictionary_index(dictionary: collections.abc.Mapping) -> object:
    """
    Build a normalized index from a dictionary for fast lookup of words and
    compound phrases.

    Parameters:
        dictionary: Mapping strings (keys) to meanings (values).
    """
    # Create an index that maps normalized word sequences to dictionary entries
    index = {
        'entries': {},  # Maps normalized keys to list of (entry_id, is_phrase)
        'max_phrase_length': 0  # Track max phrase length for efficiency
    }
    
    for text, entry_id in dictionary.items():
        # Extract words from the text (normalize and remove separators)
        words = []
        current_word = []
        
        for char in text.lower():
            if char.isalnum():
                current_word.append(char)
            elif current_word:
                words.append(''.join(current_word))
                current_word = []
        
        if current_word:
            words.append(''.join(current_word))
        
        if not words:
            continue
        
        # Determine if this is a phrase (has separators) or compound word
        is_phrase = len(words) > 1 or any(not c.isalnum() for c in text)
        
        # Store in index
        key = tuple(words)
        if key not in index['entries']:
            index['entries'][key] = []
        index['entries'][key].append((entry_id, is_phrase))
        
        # Update max phrase length
        index['max_phrase_length'] = max(index['max_phrase_length'], len(words))
    
    return index

def annotate(tokens: collections.abc.Iterable[str], dictionary_index: object) -> collections.abc.Iterable[tuple[str, collections.abc.Set]]:
    """
    Annotate tokens with entries from the dictionary.

    Parameters:
        dictionary_index:   A dictionary index created by build_dictionary_index()
        tokens:             The tokens to be annotated.

    Return:
        annotated_tokens:   A list containing (token, annotations) pairs for each token in tokens.
    """
    tokens = list(tokens)
    n = len(tokens)
    annotations = [set() for _ in range(n)]
    
    # Process each starting position
    for start in range(n):
        # Skip if starting with pure separator
        if not any(c.isalnum() for c in tokens[start]):
            continue
        
        # Try to build sequences of increasing length
        words_collected = []
        positions = []  # Track token positions for each word
        current_chars = []
        current_positions = []
        
        for pos in range(start, min(n, start + dictionary_index['max_phrase_length'] * 2)):
            token = tokens[pos]
            is_word_token = any(c.isalnum() for c in token)
            
            if is_word_token:
                # Extract alphanumeric characters
                token_chars = [c.lower() for c in token if c.isalnum()]
                current_chars.extend(token_chars)
                current_positions.append(pos)
                
                # Check if we need to complete this word
                # (next token is separator or we're at the end)
                next_is_sep = (pos + 1 >= n or not any(c.isalnum() for c in tokens[pos + 1]))
                
                if next_is_sep and current_chars:
                    words_collected.append(''.join(current_chars))
                    positions.append(current_positions[:])
                    current_chars = []
                    current_positions = []
            else:
                # It's a separator
                if current_chars:
                    # Complete current word first
                    words_collected.append(''.join(current_chars))
                    positions.append(current_positions[:])
                    current_chars = []
                    current_positions = []
            
            # After each token, check for matches
            if words_collected:
                key = tuple(words_collected)
                
                if key in dictionary_index['entries']:
                    # We have a match!
                    for entry_id, is_phrase in dictionary_index['entries'][key]:
                        # Determine which tokens to annotate
                        if is_phrase or len(words_collected) > 1:
                            # For phrases, annotate all tokens from first to last word
                            all_word_positions = []
                            for word_pos in positions:
                                all_word_positions.extend(word_pos)
                            
                            if all_word_positions:
                                min_pos = min(all_word_positions)
                                max_pos = max(all_word_positions)
                                
                                for i in range(min_pos, max_pos + 1):
                                    annotations[i].add(entry_id)
                        else:
                            # Single word match
                            for i in positions[0]:
                                annotations[i].add(entry_id)
    
    # Build result
    annotated_tokens = []
    for i, token in enumerate(tokens):
        annotated_tokens.append((token, annotations[i]))
    
    return annotated_tokens
