import collections.abc

def is_word_token(token):
    """Check if a token is a word (contains alphanumeric characters)."""
    return any(c.isalnum() for c in token)

def extract_words_from_string(s):
    """Extract words from a string, treating non-alphanumeric characters as separators."""
    words = []
    current_word = []
    for c in s:
        if c.isalnum():
            current_word.append(c)
        else:
            if current_word:
                words.append(''.join(current_word))
                current_word = []
    if current_word:
        words.append(''.join(current_word))
    return words

def build_dictionary_index(dictionary: collections.abc.Mapping) -> object:
    """
    Build a normalized index from a dictionary for fast lookup of words and
    compound phrases.

    Parameters:
        dictionary: Mapping strings (keys) to meanings (values).
    """
    index = {
        'normalized': {},  # normalized full string -> set of entry IDs
        'word_sequences': {},  # tuple of normalized words -> set of entry IDs (for compound phrases)
    }
    
    for key, value in dictionary.items():
        normalized_key = key.lower()
        
        # Index by normalized full string (for single words and compound words)
        if normalized_key not in index['normalized']:
            index['normalized'][normalized_key] = set()
        index['normalized'][normalized_key].add(value)
        
        # For strings with multiple words separated by non-word characters,
        # also index by word sequence
