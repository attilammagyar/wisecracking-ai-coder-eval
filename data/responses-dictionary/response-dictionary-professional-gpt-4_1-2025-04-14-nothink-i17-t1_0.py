def _is_word_token(token):
    # Heuristic: token is a word if it contains at least one alphanumeric
    return any(c.isalnum() for c in token)

def _normalize_token(token):
    return token.lower()

def _normalize_dict_phrase(phrase):
    """
    Lowercase and normalize all separators to a single space between words (and strip).
    So e.g. "AAA, *** BBB" -> "aaa bbb"
    """
    import string
    parts = []
    last_was_space = False
    for c in phrase.lower():
        if c.isalnum():
            parts.append(c)
            last_was_space = False
        else:
            if not last_was_space:
                parts.append(' ')
                last_was_space = True
    # Remove leading/trailing/multiple spaces.
    norm = ''.join(parts)
    return ' '.join(norm.strip().split())

