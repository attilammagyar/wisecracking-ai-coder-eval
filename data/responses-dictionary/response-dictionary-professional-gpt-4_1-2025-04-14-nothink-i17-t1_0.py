    """
    Annotate tokens with entries from the dictionary (single words and compound phrases).
    """
    tokens = list(tokens)
    n = len(tokens)
    result = [(token, set()) for token in tokens]
    # Helper for separating word tokens from separators
    word_token_flags = [_is_word_token(t) for t in tokens]
    norm_tokens = [_normalize_token(t) for t in tokens]

    # Single-word annotation
    word_dict = dictionary_index['word_dict']
    for idx, (is_word, norm_tok) in enumerate(zip(word_token_flags, norm_tokens)):
        if is_word:
            if norm_tok in word_dict:
                result[idx][1].update(word_dict[norm_tok])

    # Compound phrase annotation using the trie
    trie_root = dictionary_index['trie_root']
    max_phrase_len = dictionary_index['max_phrase_len']

    idx = 0
    while idx < n:
        # To handle all overlapping/embedded matches, 
        # at every position, try *all* windows from len=1 to max_phrase_len
        for window_len in range(1, max_phrase_len+1):
            # window = tokens[idx : idx+window_len tokens]
            # Step 1: get the word tokens and their positions
            words = []
            word_positions = []
            k = idx
            while len(words) < window_len and k < n:
                if word_token_flags[k]:
                    words.append(norm_tokens[k])
                    word_positions.append(k)
                k += 1
            if len(words) != window_len:
                continue  # Not enough tokens left for this window
            # Step 2: attempt a trie match
            node = trie_root
            found = True
            for w in words:
                if w in node.children:
                    node = node.children[w]
                else:
                    found = False
                    break
            if found and node.dict_ids:
                # Step 3: Identify the phrase span in tokens:
                # from word_positions[0] to word_positions[-1], includes all tokens in between
                phrase_start = word_positions[0]
                phrase_end = word_positions[-1]
                # According to the requirements:
                #  - annotate every token in the window, including separators in-between,
                #  - but do NOT annotate leading/trailing separators bordering the phrase!
                # That is: annotate only tokens from phrase_start to phrase_end, inclusive.
                # But do not annotate if the current window does not begin bordering a word token
                for pos in range(phrase_start, phrase_end+1):
                    # Annotate:
                    result[pos][1].update(node.dict_ids)
        idx += 1

    # Now fix leading and trailing separators: 
    # For every phrase match above, it only annotates tokens inside window [phrase_start, phrase_end]
    # This already solves the "do not annotate leading/trailing separators" requirement because
    # the logic above only includes the span from first word to last word of phrase.

    return result
