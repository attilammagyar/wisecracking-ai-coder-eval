import collections.abc
import re

def build_dictionary_index(dictionary: collections.abc.Mapping) -> object:
    """
    Build a normalized index from a dictionary for fast lookup of words and
    compound phrases.

    The index is a Trie (prefix tree) where each path from the root represents
    a sequence of normalized "word parts" from a dictionary key.

    Parameters:
        dictionary: Mapping strings (keys) to meanings (values).
    
    Returns:
        A Trie, represented as a nested dictionary.
    """
    # The Trie root node.
    # Structure: {'children': {<word_part>: <node>}, 'values': {<ids>}}
    trie_root = {'children': {}, 'values': set()}

    for phrase, value in dictionary.items():
        # Normalize the phrase into a list of word parts. A word part is a
        # sequence of alphanumeric characters. This makes matching insensitive
        # to case and the specific separators used (e.g., space, comma).
        word_parts = re.findall(r'[a-z0-9]+', phrase.lower())
        
        if not word_parts:
            continue

        node = trie_root
        for part in word_parts:
            # Descend the Trie, creating nodes as necessary.
            if part not in node['children']:
                node['children'][part] = {'children': {}, 'values': set()}
            node = node['children'][part]
        
        # Mark the end of a valid phrase by adding its dictionary value.
        node['values'].add(value)
            
    return trie_root

def annotate(tokens: collections.abc.Iterable[str], dictionary_index: object) -> collections.abc.Iterable[tuple[str, collections.abc.Set]]:
    """
    Annotate tokens with entries from the dictionary.

    This function iterates through each token as a potential start of a phrase
    and uses the Trie to find all possible matches beginning at that token.

    Parameters:
        dictionary_index: A dictionary index created by build_dictionary_index().
        tokens:           The tokens to be annotated.

    Return:
        annotated_tokens: A list containing (token, annotations) pairs for each
                          token in tokens.
    """
    token_list = list(tokens)
    if not token_list:
        return []

    num_tokens = len(token_list)
    annotated_tokens = [(token, set()) for token in token_list]
    trie_root = dictionary_index

    # Iterate through each token, treating it as a potential start of a phrase.
    for i in range(num_tokens):
        # According to the test cases, phrases must start with a word, not a separator.
        if not token_list[i].isalnum():
            continue

        node = trie_root
        word_buffer = ""
        last_word_idx = -1

        # Look ahead from the starting token `i` to find matching phrases.
        for j in range(i, num_tokens):
            token = token_list[j]
            is_word_token = token.isalnum()

            if is_word_token:
                # Accumulate consecutive word tokens. This handles cases where a
                # single dictionary word part is split across multiple tokens
                # (e.g., "AAA", "BBB" -> "aaabbb").
                word_buffer += token.lower()
                last_word_idx = j

            # A word part boundary is detected if we hit a separator or the end of the token stream.
            # We must have something in the buffer to constitute a word part.
            is_separator = not is_word_token
            is_end_of_stream = (j == num_tokens - 1)
            
            if word_buffer and (is_separator or is_end_of_stream):
                if word_buffer in node['children']:
                    # A word part was successfully matched. Descend into the Trie.
                    node = node['children'][word_buffer]
                    
                    # Check if this node marks the end of a valid dictionary entry.
                    if node['values']:
                        # A phrase match is found. Annotate all tokens that form it.
                        # The span is from the phrase start `i` to the last word
                        # token `last_word_idx`. This includes inner separators but
                        # excludes trailing ones.
                        for k in range(i, last_word_idx + 1):
                            annotated_tokens[k][1].update(node['values'])
                    
                    # Reset the buffer to look for the next word part in a longer phrase.
                    word_buffer = ""
                else:
                    # The accumulated word_buffer does not match any path in the Trie.
                    # This search path is a dead end.
                    break
        
    return annotated_tokens
