def annotate(tokens: collections.abc.Iterable[str], dictionary_index: object) -> collections.abc.Iterable[tuple[str, collections.abc.Set]]:
    """
    Annotate tokens with entries from the dictionary.

    Parameters:
        dictionary_index:   A dictionary index created by build_dictionary_index()
        tokens:             The tokens to be annotated.

    Return:
        annotated_tokens:   A list containing (token, annotations) pairs for each token in tokens.
    """
    toks = list(tokens)
    n = len(toks)
    ann = [set() for _ in range(n)]
    if n == 0:
        return []

    idx = dictionary_index
    words_map = idx.words_map
    root = idx.phrase_root

    # Precompute normalized tokens and word flags
    norm = [t.casefold() for t in toks]
    is_word = [_is_word_token(nt) for nt in norm]

    # 1) Match single words and solid-word concatenations over runs of adjacent word tokens.
    i = 0
    while i < n:
        if not is_word[i]:
            i += 1
            continue
        # Determine run [i..j_run] of consecutive word tokens
        j_run = i
        while j_run + 1 < n and is_word[j_run + 1]:
            j_run += 1

        # For each start in run, build concatenation progressively and check words_map
        for start in range(i, j_run + 1):
            concat = []
            for end in range(start, j_run + 1):
                concat.append(norm[end])
                key = "".join(concat)
                ids = words_map.get(key)
                if ids:
                    for val in ids:
                        # annotate tokens from start..end inclusive
                        for k in range(start, end + 1):
                            ann[k].add(val)
        i = j_run + 1

    # 2) Match multi-word phrases using trie (words separated by >=1 non-word token).
    # Build list of positions of word tokens
    word_positions = [i for i in range(n) if is_word[i]]

    W = len(word_positions)
    for wi in range(W):
        start_idx = word_positions[wi]
        first_word = norm[start_idx]
        node = root.children.get(first_word)
        if node is None:
            continue

        # Walk to next word tokens that are separated by >=1 non-word token.
        last_word_pos_index = wi
        last_word_token_index = start_idx

        wj = wi + 1
        while wj < W:
            curr_word_idx = word_positions[wj]

            # Require at least one separator token between consecutive words of a phrase.
            if curr_word_idx == last_word_token_index + 1:
                # Adjacent words => cannot be part of a "phrase with separators".
                break

            next_word = norm[curr_word_idx]
            child = node.children.get(next_word)
            if child is None:
                break

            node = child
            # We have matched at least two words in the phrase now.
            if node.ends:
                # Annotate all words in [start_idx..curr_word_idx] and inner separators only.
                s = start_idx
                e = curr_word_idx
                for val in node.ends:
                    for k in range(s, e + 1):
                        if is_word[k] or (k != s and k != e):
                            ann[k].add(val)

            last_word_pos_index = wj
            last_word_token_index = curr_word_idx
            wj += 1

    return [(toks[i], ann[i]) for i in range(n)]
