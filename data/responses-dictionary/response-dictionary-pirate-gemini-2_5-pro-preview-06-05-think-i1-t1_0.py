import collections.abc

def build_dictionary_index(dictionary: collections.abc.Mapping) -> object:
    """
    Build a normalized index from a dictionary for fast lookup of words and
    compound phrases.

    Parameters:
        dictionary: Mapping strings (keys) to meanings (values).
    """
    def _split_into_key_words(text: str) -> list[str]:
        """Splits a string into a list of alphanumeric words, lowercased."""
        key_words = []
        current_word = []
        for char in text:
            if char.isalnum():
                current_word.append(char.lower())
            else:
                if current_word:
                    key_words.append("".join(current_word))
                    current_word = []
        if current_word:
            key_words.append("".join(current_word))
        return key_words

    # The trie is represented by a nested dictionary.
    # 'values' holds a set of dictionary entry IDs for phrases ending at this node.
    # 'children' maps the next key-word to a subsequent trie node.
    trie_root = {'children': {}, 'values': set()}

    for phrase, value in dictionary.items():
        key_words = _split_into_key_words(phrase)
        if not key_words:
            continue

        node = trie_root
        for key_word in key_words:
            if key_word not in node['children']:
                node['children'][key_word] = {'children': {}, 'values': set()}
            node = node['children'][key_word]
        
        node['values'].add(value)

    return trie_root

def annotate(tokens: collections.abc.Iterable[str], dictionary_index: object) -> collections.abc.Iterable[tuple[str, collections.abc.Set]]:
    """
    Annotate tokens with entries from the dictionary.

    Parameters:
        dictionary_index:   A dictionary index created by build_dictionary_index()
        tokens:             The tokens to be annotated.

    Return:
        annotated_tokens:   A list containing (token, annotations) pairs for each token in tokens.
    """
