import re
import collections.abc

# Internal trie node helpers
def _new_trie_node():
    return {"ids": set(), "ch": {}}

def _tokenize_dict_key(key: str):
    # Extract alphanumeric "words", lowercase for case-insensitive matching
    # Example: "AAA, BBB" -> ["aaa", "bbb"]
    return re.findall(r"[A-Za-z0-9]+", key.lower())

def build_dictionary_index(dictionary: collections.abc.Mapping) -> object:
    """
    Build a normalized index (trie) from a dictionary for fast lookup of words and
    compound phrases. Dictionary lookup is case-insensitive and separator-insensitive
    for phrases (only word sequences matter).
    """
    root = _new_trie_node()
    for k, v in dictionary.items():
        words = _tokenize_dict_key(k)
        if not words:
            continue  # ignore entries without any word characters
        node = root
        for w in words:
            node = node["ch"].setdefault(w, _new_trie_node())
        node["ids"].add(v)
    return root


def annotate(tokens: collections.abc.Iterable[str], dictionary_index: object) -> collections.abc.Iterable[tuple[str, collections.abc.Set]]:
    """
    Annotate tokens with entries from the dictionary index.
    """
    tokens = list(tokens)
    n = len(tokens)
    annotated = [set() for _ in range(n)]

    # Helper: identify "word" tokens (alphanumeric only, non-empty)
    def is_word_token(tok: str) -> bool:
        return bool(tok) and tok.isalnum()

    # Build units: merge consecutive word tokens into word segments,
    # keep separators as individual units.
    # Each unit is either:
    #   ("W", text_lower, start_idx, end_idx)  # word segment covering tokens [start_idx..end_idx]
    #   ("S", idx)                              # separator at token index idx
    units = []
    i = 0
    while i < n:
        if is_word_token(tokens[i]):
            start = i
            buf = [tokens[i].lower()]
            i += 1
            while i < n and is_word_token(tokens[i]):
                buf.append(tokens[i].lower())
                i += 1
            units.append(("W", "".join(buf), start, i - 1))
        else:
            units.append(("S", i))
            i += 1

    # Collect indices of word units for phrase scanning
    word_unit_indices = [ui for ui, u in enumerate(units) if u[0] == "W"]

    root = dictionary_index

    # Match phrases starting at each word unit
    for wstart_pos_in_list, start_unit_idx in enumerate(word_unit_indices):
        node = root
        pos = wstart_pos_in_list
        while True:
            uidx = word_unit_indices[pos]
            u = units[uidx]  # ("W", text, start, end)
            wtext = u[1]
            child = node["ch"].get(wtext)
            if child is None:
                break
            node = child

            # Found one or more entries ending here; annotate the span
            if node["ids"]:
                # Word span from start_unit_idx to current word unit index uidx (inclusive)
                # Annotate all tokens covered by the word segments in this span
                # and all inner separators between them.
                # 1) Annotate word tokens
                # Iterate through units between start_unit_idx and uidx inclusive
                # and update for each word unit its token range.
                for k in range(start_unit_idx, uidx + 1):
                    uk = units[k]
                    if uk[0] == "W":
                        _, _, t0, t1 = uk
                        for ti in range(t0, t1 + 1):
                            annotated[ti].update(node["ids"])
                # 2) Annotate inner separators only
                if uidx > start_unit_idx:
                    for k in range(start_unit_idx + 1, uidx):
                        uk = units[k]
                        if uk[0] == "S":
                            _, sep_idx = uk
                            annotated[sep_idx].update(node["ids"])

            # Advance to next word unit if possible
            pos += 1
            if pos >= len(word_unit_indices):
                break

    # Produce the (token, annotations) pairs
    return [(tok, ann) for tok, ann in zip(tokens, annotated)]
