def build_dictionary_index(dictionary: collections.abc.Mapping) -> object:
    """
    Build a normalized index from a dictionary for fast lookup of words and
    compound phrases.

    The index is a Trie data structure where each path from the root represents
    a sequence of word components from a dictionary key.

    Parameters:
        dictionary: Mapping strings (keys) to meanings (values).
    
    Return:
        The root node of the Trie.
    """
    root = _TrieNode()
    
    # A word is considered a sequence of one or more alphanumeric characters.
    word_component_re = re.compile(r'\w+')

    for key, value in dictionary.items():
        # Normalize the dictionary key by splitting it into lowercase word components.
        # e.g., "Once in a blue moon" -> ["once", "in", "a", "blue", "moon"]
        # e.g., "AAABBB" -> ["aaabbb"]
        word_components = word_component_re.findall(key.lower())
        
        if not word_components:
            continue

        node = root
        for component in word_components:
            if component not in node.children:
                node.children[component] = _TrieNode()
            node = node.children[component]
        
        node.values.add(value)
        
    return root

def annotate(tokens: collections.abc.Iterable[str], dictionary_index: object) -> collections.abc.Iterable[tuple[str, collections.abc.Set]]:
    """
    Annotate tokens with entries from the dictionary.

    This function iterates through each token as a potential start of a match
    and uses a recursive search on the Trie to find all possible phrases.

    Parameters:
        dictionary_index:   A dictionary index created by build_dictionary_index().
        tokens:             The tokens to be annotated.

    Return:
        annotated_tokens:   A list containing (token, annotations) pairs for
                            each token in tokens.
    """
    token_list = list(tokens)
    if not token_list:
        return []

    num_tokens = len(token_list)
    annotations = [set() for _ in range(num_tokens)]
    root = dictionary_index

    def is_word_token(token: str) -> bool:
        """Check if a token is a word (consists of alphanumeric characters)."""
        # We check for non-empty string because "".isalnum() is False.
        return token and token.isalnum()

    def _walk_after_separators(node: _TrieNode, token_cursor: int, matched_word_indices: list[int]):
        """Find the start of the next word component after skipping separators."""
        for i in range(token_cursor, num_tokens):
            if is_word_token(token_list[i]):
                # Found the next word, continue the main walk from here.
                _walk(node, i, matched_word_indices)
                # After starting a walk, we don't need to check further from this position.
                break

    def _walk(node: _TrieNode, token_cursor: int, matched_word_indices: list[int]):
        """
        Recursively walk the Trie and tokens to find matches.
        
        This function tries to form a word component by concatenating subsequent
        word tokens and checking for a match in the current Trie node's children.
        """
        current_word_from_concat = ""
        indices_for_current_word = []

        for i in range(token_cursor, num_tokens):
            token = token_list[i]

            if is_word_token(token):
                current_word_from_concat += token.lower()
                indices_for_current_word.append(i)

                if current_word_from_concat in node.children:
                    next_node = node.children[current_word_from_concat]
                    new_matched_indices = matched_word_indices + indices_for_current_word

                    if next_node.values:
                        # Found a match. Annotate all tokens from the start of the
                        # phrase to the end of the current component.
                        start_idx = new_matched_indices[0]
                        end_idx = i
                        for k in range(start_idx, end_idx + 1):
                            annotations[k].update(next_node.values)

                    # Continue searching for longer phrases.
                    _walk_after_separators(next_node, i + 1, new_matched_indices)
            else:
                # A separator breaks a concatenated word component.
                break

    # Start a search from every token position.
    for i in range(num_tokens):
        _walk(root, i, [])

    return list(zip(token_list, annotations))
