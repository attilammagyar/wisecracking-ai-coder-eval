    for start in range(word_n):
        node = root
        matched_entries = []
        wi = start
        # Advance up to max_phrase_len words
        for l in range(max_phrase_len):
            if wi + l >= word_n:
                break
            word = word_lowers[wi + l]
            if word in node.children:
                node = node.children[word]
                if node.entries:
                    matched_entries.append((wi + l, set(node.entries)))
            else:
                break
        # For each phrase match ending at wi+l, annotate corresponding tokens
        for end_idx, entries in matched_entries:
            # Convert word_indices[start:end_idx+1] -> token span
            start_tok = word_indices[start]
            end_tok = word_indices[end_idx]
