def _is_word(token):
    # If token contains at least one alphanumeric character, we call it "word"
    return any(char.isalnum() for char in token)

class TrieNode:
    def __init__(self):
        self.children = dict()  # word->TrieNode
        self.entries = set()    # set of dict entry IDs for phrase ending here

def build_dictionary_index(dictionary: collections.abc.Mapping) -> object:
    """
    Build a normalized index (trie) from the dictionary, handling phrases,
    separators, and case-insensitivity. Returns a dict:
    {
        'root': TrieNode(),
        'single_word': {word: set(entries)},
        'max_phrase_len': int
    }
    """
    root = TrieNode()
    single_word = defaultdict(set)
    max_phrase_len = 1

    for phrase, entry_id in dictionary.items():
        # Lowercase, and split dict phrase into word segments, skipping separators
        tokens = []
        for chunk in phrase.split():
            subtoks = []
            i = 0
            while i < len(chunk):
                if chunk[i].isalnum():
                    j = i
                    while j < len(chunk) and chunk[j].isalnum():
                        j += 1
                    subtoks.append(chunk[i:j].lower())
                    i = j
                else:
                    i += 1  # skip non-word char
            if subtoks:
                tokens.extend(subtoks)
        if not tokens:
            continue
        if len(tokens) == 1:
            single_word[tokens[0]].add(entry_id)
        else:
            max_phrase_len = max(max_phrase_len, len(tokens))
            node = root
            for w in tokens:
                if w not in node.children:
                    node.children[w] = TrieNode()
                node = node.children[w]
            node.entries.add(entry_id)

    return {
        'root': root,
        'single_word': single_word,
        'max_phrase_len': max_phrase_len,
    }

def annotate(tokens: collections.abc.Iterable[str], dictionary_index: object) -> collections.abc.Iterable[tuple[str, collections.abc.Set]]:
    """
    Annotate tokens with single-word and phrase entries.
    """

