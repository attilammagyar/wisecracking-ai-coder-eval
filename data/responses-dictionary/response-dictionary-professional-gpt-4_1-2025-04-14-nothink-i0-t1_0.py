def is_word(token: str) -> bool:
    """
    Returns True if the token is considered a 'word'.
    We'll treat a token as a word if it contains any alphanumeric character.
    (More sophisticated rules can be applied if needed.)
    """
    return any(char.isalnum() for char in token)

def normalize_phrase_words(phrase: str):
    """
    Split a phrase into its word components (casefolded, and ignoring separator patterns).
    """
    # We split by whitespace for phrases, but "words" in the dictionary may contain internal punctuation.
    # So, for simplicity, we'll treat any runs of whitespace as separators.
    return [w.casefold() for w in phrase.split() if w]

def build_dictionary_index(dictionary: collections.abc.Mapping) -> object:
    """
    Build a normalized index from a dictionary for fast lookup of words and
    compound phrases.
    """
    # For single tokens, direct mapping: word_casefolded -> set(ids)
