def build_dictionary_index(dictionary: collections.abc.Mapping) -> object:
    """
    Build a normalized index from a dictionary for fast lookup of words and
    compound phrases.

    The index contains:
      - single_words: dict[word -> set(ids)]
      - phrase_trie: trie over sequences of words (>=2 words)
        node = {"next": {word: node}, "out": set(ids)}
    """
    word_re = re.compile(r"[0-9A-Za-z]+")
    single_words: Dict[str, Set[Any]] = {}
    # Trie node: {"next": dict, "out": set}
    def new_node():
        return {"next": {}, "out": set()}

    phrase_root = new_node()

    def insert_phrase(words: List[str], value: Any) -> None:
        node = phrase_root
        for w in words:
            nxt = node["next"].get(w)
            if nxt is None:
                nxt = new_node()
                node["next"][w] = nxt
            node = nxt
        node["out"].add(value)

    for key, val in dictionary.items():
        words = word_re.findall(str(key).lower())
        if not words:
            # Ignore entries without any alphanumeric word
            continue
        if len(words) == 1:
            w = words[0]
            if w not in single_words:
                single_words[w] = set()
            single_words[w].add(val)
        else:
            insert_phrase(words, val)

    return {
        "single_words": single_words,
        "phrase_root": phrase_root,
    }


