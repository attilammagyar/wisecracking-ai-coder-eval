import re
from collections import defaultdict

def build_dictionary_index(dictionary: dict) -> dict:
    word_map = {}
    phrase_map = defaultdict(list)
    max_length = 0

    for phrase, identifier in dictionary.items():
        # Normalize phrases by removing punctuation and case
        cleaned = re.sub(r'[^\w]+', ' ', phrase).lower().strip()
        
        if ' ' in cleaned:
            # Compound phrase (multiple words)
            words = cleaned.split()
            phrase_map[tuple(words)].append(identifier)
            max_length = max(max_length, len(words))
        else:
            # Single word
            word = cleaned
            word_map[word] = identifier
    
    return {
        'word_map': word_map,
        'phrase_map': phrase_map,
        'max_length': max_length
    }

def annotate(tokens: list[str], dictionary_index: dict) -> list[tuple[str, set]]:
    word_map, phrase_map, max_length = dictionary_index.values()
    annotations: dict[int, set] = defaultdict(set)
    tokens = list(tokens)
    token_lower = [token.lower() for token in tokens]
    num_tokens = len(tokens)

    # Individual word matching first
    for i, token in enumerate(tokens):
        if token.isalpha():
            lower_token = token_lower[i]
            if lower_token in word_map:
                annotations[i].add(word_map[lower_token])

    # Compound phrase matching using sliding window
    for i in range(num_tokens):
        # Check all possible phrase lengths from max down to 1
        for length in reversed(range(1, max_length + 1)):
            word_positions = []
            current = i
            
            # Collect word tokens backward
            while len(word_positions) < length and current >= 0:
                if tokens[current].isalpha():
                    word_positions.append(token_lower[current])
                    current -= 1
                else:
                    current -= 1
            
            if len(word_positions) != length:
                continue
            
            word_sequence = tuple(reversed(word_positions))
            if word_sequence in phrase_map:
                # Find the earliest token index in the phrase
                start_idx = -1
                for j in range(i, current, -1):
                    if j in annotations:
                        start_idx = j
                        break
                # If no word found in the phrase, find the actual start
                actual_start = current
                while actual_start >= 0 and tokens[actual_start].isalpha():
                    actual_start += 1
                actual_start -= 1
                phrase_start = actual_start
                phrase_end = i
                for k in range(phrase_start, phrase_end + 1):
                    annotations[k].update(phrase_map[word_sequence])

    # Compile results in token order
    return [(token, annotations.get(i, set())) for i, token in enumerate(tokens)]
