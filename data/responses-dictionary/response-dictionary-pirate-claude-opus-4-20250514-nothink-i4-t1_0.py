        normalized_phrase = phrase.lower()
        
        # Split into tokens (words and separators)
        tokens = []
        current_token = []
        is_word = None
        
        for char in normalized_phrase:
            char_is_word = char.isalnum()
            if is_word is None:
                is_word = char_is_word
            elif is_word != char_is_word:
                # Boundary between word and non-word
                if current_token:
                    tokens.append(''.join(current_token))
                current_token = []
