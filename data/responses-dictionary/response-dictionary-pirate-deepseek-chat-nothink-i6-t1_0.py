def build_dictionary_index(dictionary: collections.abc.Mapping) -> object:
    """
    Build a normalized index from a dictionary for fast lookup of words and
    compound phrases.
    """
    root = TrieNode()
    
    for phrase, entry_id in dictionary.items():
        # Normalize phrase to lowercase and split into words
        normalized_phrase = phrase.lower()
        current = root
        
        # Build trie path for this phrase
        for char in normalized_phrase:
            if char not in current.children:
                current.children[char] = TrieNode()
            current = current.children[char]
        
        # Add entry ID to the end node
        current.entry_ids.add(entry_id)
    
    return root

