def build_dictionary_index(dictionary: collections.abc.Mapping) -> object:
    """
    Build a normalized index from a dictionary for fast lookup of words and
    compound phrases.

    Parameters:
        dictionary: Mapping strings (keys) to meanings (values).
    """
    # Helpers kept local to avoid polluting module scope.
    def split_words_lower(s: str) -> list[str]:
        # Extract contiguous alphanumeric runs, casefolded.
        out = []
        n = len(s)
        i = 0
        while i < n:
            # Skip non-alnum
            while i < n and not s[i].isalnum():
                i += 1
            if i >= n:
                break
            j = i
            while j < n and s[j].isalnum():
                j += 1
            out.append(s[i:j].casefold())
            i = j
        return out

    class TrieNode:
        __slots__ = ("children", "ids")
        def __init__(self):
            self.children: dict[str, TrieNode] = {}
            self.ids: set = set()

    root = TrieNode()
    word_ids: dict[str, set] = {}

    def insert_phrase(words: list[str], entry_id):
        node = root
        for w in words:
            child = node.children.get(w)
            if child is None:
                child = TrieNode()
                node.children[w] = child
            node = child
        node.ids.add(entry_id)

    for key, entry_id in dictionary.items():
        words = split_words_lower(key)
        if not words:
            continue
        if len(words) == 1:
            w = words[0]
            s = word_ids.get(w)
            if s is None:
                s = set()
                word_ids[w] = s
            s.add(entry_id)
        else:
            insert_phrase(words, entry_id)

    return {
        "word_ids": word_ids,
        "phrase_trie": root,
    }


def annotate(tokens: collections.abc.Iterable[str], dictionary_index: object) -> collections.abc.Iterable[tuple[str, collections.abc.Set]]:
    """
    Annotate tokens with entries from the dictionary.

    Parameters:
        dictionary_index:   A dictionary index created by build_dictionary_index()
        tokens:             The tokens to be annotated.

    Return:
        annotated_tokens:   A list containing (token, annotations) pairs for each token in tokens.
    """
    tokens = list(tokens)
    n = len(tokens)
    anns = [set() for _ in range(n)]

    # Extract index structures.
    word_ids: dict[str, set] = dictionary_index["word_ids"]
    trie_root = dictionary_index["phrase_trie"]

    # Classify tokens and normalize words.
    def is_word_token(tok: str) -> bool:
        # A "word token" contains only alphanumeric characters and is non-empty.
        return bool(tok) and tok.isalnum()

    isword = [is_word_token(t) for t in tokens]
    norm_word = [tokens[i].casefold() if isword[i] else None for i in range(n)]

    # 1) Single-token word lookup.
    for i in range(n):
        if isword[i]:
            ids = word_ids.get(norm_word[i])
            if ids:
                anns[i].update(ids)

    # 2) Compound word matching across runs of consecutive word tokens (no separators).
    i = 0
    while i < n:
        if not isword[i]:
            i += 1
            continue
        # Find the end of this run of consecutive word tokens [i, j)
        j = i
        while j < n and isword[j]:
            j += 1
        # Try all concatenations within the run.
        for s in range(i, j):
            concat = ""
            for e in range(s, j):
                # Concatenate normalized tokens incrementally.
                concat += norm_word[e]
                ids = word_ids.get(concat)
                if ids:
                    # Annotate all tokens in [s, e]
                    for k in range(s, e + 1):
                        anns[k].update(ids)
        i = j  # Continue after the run (next token is non-word or end)

    # 3) Phrase matching using trie (requires at least one non-word between words).
    for start in range(n):
        if not isword[start]:
            continue
        first = norm_word[start]
        node = trie_root.children.get(first)
        if node is None:
            continue

        last_word_idx = start
        word_positions = [start]

        # Extend with subsequent words where each step has at least one separator in between.
        while True:
            j = last_word_idx + 1
            # If next token is a word, there is zero separator; cannot extend as a phrase.
            if j < n and isword[j]:
                break
            # Skip one or more separators to next word.
            while j < n and not isword[j]:
                j += 1
            if j >= n:
                break
            next_w = norm_word[j]
            node = node.children.get(next_w)
            if node is None:
                break
            word_positions.append(j)

            if node.ids:
                ids = node.ids
                # Annotate all participating word tokens.
                for pos in word_positions:
                    anns[pos].update(ids)
                # Annotate inner separators between consecutive words.
                for a, b in zip(word_positions[:-1], word_positions[1:]):
                    for k in range(a + 1, b):
                        anns[k].update(ids)

            last_word_idx = j

    annotated_tokens = [(tokens[i], anns[i]) for i in range(n)]
    return annotated_tokens
