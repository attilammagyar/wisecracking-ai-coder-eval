def build_dictionary_index(dictionary: collections.abc.Mapping) -> object:
    """
    Build a normalized index from a dictionary for fast lookup of words and
    compound phrases.
    """
    root = _TrieNode()
    for phrase, dict_id in dictionary.items():
        word_tokens = _phrase_to_word_tokens(phrase)
        if not word_tokens:
            continue
        node = root
        for wtoken in word_tokens:
            key = _token_normalize(wtoken)
            if key not in node.children:
                node.children[key] = _TrieNode()
            node = node.children[key]
        node.dict_ids.add(dict_id)
