import collections.abc

def _is_word_token(token):
    # Token is a "word" if it has at least one alphanumeric character.
    return any(ch.isalnum() for ch in token)

def _token_normalize(token):
    # Helper for case-insensitive matching of tokens
    return token.casefold()

def _phrase_to_word_tokens(phrase):
    # Normalize, split a dictionary phrase into word tokens (ignore separators)
    import re
    # Split on non-alphanumeric; remove empty tokens
    return [t for t in re.split(r'\W+', phrase) if t]

