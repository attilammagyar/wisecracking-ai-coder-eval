def _new_node():
    # Trie node: children maps word->node, ends is set of entry IDs
    return {"children": {}, "ends": set()}

def _normalize_dict_words(entry_key: str):
    # Lowercase and extract alphanumeric word chunks
    # This tolerates any separators inside the dictionary key.
    return re.findall(r"[0-9A-Za-z]+", entry_key.lower())

def _is_word_token(tok: str) -> bool:
    # Word token iff entirely alphanumeric (and non-empty)
    return tok.isalnum()

