def _is_word_token(tok: str) -> bool:
    # A token be a "word" if all chars be alphanumeric.
    return bool(tok) and all(c.isalnum() for c in tok)

def _split_words_lower(s: str) -> list[str]:
    # Split a dictionary key into lowercase words (alnum runs), ignorin' separators.
    words = []
    cur = []
    for ch in s:
        if ch.isalnum():
            cur.append(ch.lower())
        else:
            if cur:
                words.append(''.join(cur))
                cur = []
    if cur:
        words.append(''.join(cur))
    return words

