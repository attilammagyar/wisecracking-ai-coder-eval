import collections.abc

class _TrieNode:
    __slots__ = ("children", "ids")
    def __init__(self):
        self.children = {}  # word -> _TrieNode
        self.ids = set()    # phrase ids ending here

def _split_words_lower(s: str):
    # Split by non-alphanumeric chars; keep only alnum runs; lowercased
    words = []
    curr = []
    for ch in s:
        if ch.isalnum():
            curr.append(ch.lower())
        else:
            if curr:
                words.append("".join(curr))
                curr = []
    if curr:
        words.append("".join(curr))
    return words

def build_dictionary_index(dictionary: collections.abc.Mapping) -> object:
    """
    Build an index with:
      - word_to_ids: single-word entries (normalized) -> set(ids)
      - word_prefixes: set of prefixes of all single-word entries (for glued matching)
      - phrase_trie: trie over multi-word sequences (each child keyed by normalized word)
    """
    word_to_ids = {}    # str -> set(ids)
    word_prefixes = set()
    phrase_trie = _TrieNode()

    for key, entry_id in dictionary.items():
        words = _split_words_lower(str(key))
        if not words:
            continue
        if len(words) == 1:
            w = words[0]
            s = word_to_ids.get(w)
            if s is None:
                s = set()
                word_to_ids[w] = s
            s.add(entry_id)
            # record prefixes for glued matching
            for i in range(1, len(w) + 1):
                word_prefixes.add(w[:i])
        else:
            # insert into phrase trie
            node = phrase_trie
            for w in words:
                child = node.children.get(w)
                if child is None:
                    child = _TrieNode()
                    node.children[w] = child
                node = child
            node.ids.add(entry_id)

    return {
        "word_to_ids": word_to_ids,
        "word_prefixes": word_prefixes,
        "phrase_trie": phrase_trie,
    }

def annotate(tokens: collections.abc.Iterable[str], dictionary_index: object) -> collections.abc.Iterable[tuple[str, collections.abc.Set]]:
    tokens = list(tokens)
    n = len(tokens)

    word_to_ids = dictionary_index["word_to_ids"]
    word_prefixes = dictionary_index["word_prefixes"]
    phrase_trie = dictionary_index["phrase_trie"]

    # Classify tokens and precompute normalized forms
    is_word = [False] * n
    norm_word = [None] * n
    for i, tok in enumerate(tokens):
        # A "word token" is a token consisting only of alphanumeric characters
        if tok and all(c.isalnum() for c in tok):
            is_word[i] = True
            norm_word[i] = tok.lower()

    # Prepare annotation sets
    ann = [set() for _ in range(n)]

    # Direct single-word matches
    for i in range(n):
        if is_word[i]:
            ids = word_to_ids.get(norm_word[i])
            if ids:
                ann[i].update(ids)

    # Glued matches: concatenate adjacent word tokens (no separators)
    i = 0
    while i < n:
        if not is_word[i]:
            i += 1
            continue
        # find maximal run of consecutive word tokens
        run_start = i
        j = i
        while j < n and is_word[j]:
            j += 1
        run_end = j - 1
        # for each start in the run, grow end while prefix exists
        for s in range(run_start, run_end + 1):
            cum = ""
            for e in range(s, run_end + 1):
                cum += norm_word[e]
                ids = word_to_ids.get(cum)
                if ids:
                    # annotate all tokens in [s, e]
                    for t in range(s, e + 1):
                        ann[t].update(ids)
                if cum not in word_prefixes:
                    break  # cannot grow further
        i = j

    # Phrase matches (>= 2 words), separator-insensitive, but require at least one separator between words
    # Collect positions of word tokens
    word_pos = [idx for idx in range(n) if is_word[idx]]
    W = len(word_pos)

    # Helper to check if there is at least one separator between two word token indices in the original token list
    def _has_separator_between(tok_i: int, tok_j: int) -> bool:
        return tok_j - tok_i > 1  # there exists index strictly between them

    # Traverse trie from each word position
    for start_idx in range(W):
        node = phrase_trie
        # step through subsequent word tokens
        for k in range(start_idx, W):
            wi = word_pos[k]
            w = norm_word[wi]
            child = node.children.get(w)
            if child is None:
                break
            # from the 2nd matched word onward, require at least one separator between successive words
            if k > start_idx:
                prev_wi = word_pos[k - 1]
                if not _has_separator_between(prev_wi, wi):
                    break
            node = child
            if node.ids and (k - start_idx + 1) >= 2:
                # annotate span from first word token to current word token
                span_start = word_pos[start_idx]
                span_end = wi
                ids = node.ids
                for t in range(span_start, span_end + 1):
                    if is_word[t]:
                        ann[t].update(ids)
                    else:
                        # annotate only inner separators (strictly between the boundary words)
                        if span_start < t < span_end:
                            ann[t].update(ids)

    # Build final annotated list
    return [(tokens[i], ann[i]) for i in range(n)]
