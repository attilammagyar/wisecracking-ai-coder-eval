def is_word_token(token):
    """Check if a token contains any alphabetic characters."""
    return any(c.isalpha() for c in token)

def normalize_token(token):
    """Normalize a token for case-insensitive lookup."""
    return token.lower()

def extract_words_from_phrase(phrase):
    """Extract normalized words from a dictionary phrase."""
    words = []
    current_word = []
    
    for char in phrase:
        if char.isalpha():
            current_word.append(char.lower())
        elif current_word:
            words.append(''.join(current_word))
            current_word = []
    
    if current_word:
        words.append(''.join(current_word))
    
    return words

def build_dictionary_index(dictionary: collections.abc.Mapping) -> object:
    """
    Build a normalized index from a dictionary for fast lookup of words and
    compound phrases.

    Parameters:
        dictionary: Mapping strings (keys) to meanings (values).
    """
    root = TrieNode()
    
    for phrase, entry_id in dictionary.items():
        words = extract_words_from_phrase(phrase)
