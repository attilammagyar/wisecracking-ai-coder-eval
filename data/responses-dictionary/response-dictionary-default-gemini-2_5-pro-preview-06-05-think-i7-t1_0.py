class _TrieNode:
    """A node in the dictionary Trie used for the index."""
    def __init__(self):
        # Maps a character to a child _TrieNode.
        self.children: dict[str, _TrieNode] = {}
        # Stores entries that terminate at this node. Each entry is a tuple:
        # (entry_id, num_word_parts, is_phrase)
        self.entries: list[tuple[any, int, bool]] = []

def _is_word(token: str) -> bool:
    """
    Determines if a token is a "word" token, meaning it consists only of
    alphanumeric characters. This check is consistent with how dictionary
    keys are normalized. An empty string is not considered a word.
    """
    return token.isalnum()

def build_dictionary_index(dictionary: collections.abc.Mapping) -> object:
    """
    Build a normalized index from a dictionary for fast lookup of words and
    compound phrases.

    The index is a Trie data structure where paths represent normalized,
    concatenated dictionary keys.

    Parameters:
        dictionary: Mapping strings (keys) to meanings (values).
    
    Returns:
        The root node of the Trie, which serves as the index.
    """
    root = _TrieNode()
    word_pattern = re.compile(r'\w+')
    separator_pattern = re.compile(r'\W')

    for key, entry_id in dictionary.items():
        num_word_parts = len(word_pattern.findall(key))
        if num_word_parts == 0:
            continue

        # A key represents a phrase if it contains any non-word characters.
        # We check the stripped key to ignore leading/trailing whitespace.
        is_phrase = bool(separator_pattern.search(key.strip()))

        # Normalize the key by making it lowercase and alphanumeric.
        # This ensures matching is insensitive to case and separators.
        normalized_key = "".join(filter(str.isalnum, key.lower()))
        if not normalized_key:
            continue

        node = root
        for char in normalized_key:
            node = node.children.setdefault(char, _TrieNode())
        
        node.entries.append((entry_id, num_word_parts, is_phrase))
    
    return root

def annotate(tokens: collections.abc.Iterable[str], dictionary_index: object) -> collections.abc.Iterable[tuple[str, collections.abc.Set]]:
    """
    Annotate tokens with entries from the dictionary.

    Parameters:
        dictionary_index: A dictionary index created by build_dictionary_index().
        tokens: The tokens to be annotated.

    Return:
        annotated_tokens: A list containing (token, annotations) pairs for each token in tokens.
    """
    token_list = list(tokens)
    num_tokens = len(token_list)
    annotated_tokens = [(token, set()) for token in token_list]
    
    if not token_list:
        return []

    root: _TrieNode = dictionary_index

    for i in range(num_tokens):
        # A valid match must start with a word token.
        if not _is_word(token_list[i]):
            continue

        node = root
        word_indices = []

        for j in range(i, num_tokens):
            token = token_list[j]
            
            if _is_word(token):
                # Attempt to traverse the Trie with the current word token.
                current_node = node
                is_possible_path = True
                for char in token.lower():
                    if char not in current_node.children:
                        is_possible_path = False
                        break
                    current_node = current_node.children[char]

                if not is_possible_path:
                    # This path in the Trie is a dead end, so we can't extend the match.
                    break
                
                node = current_node
                word_indices.append(j)
                
                if node.entries:
                    num_word_tokens = len(word_indices)
                    
                    has_separators = (word_indices[-1] > word_indices[0] + num_word_tokens - 1)

                    for entry_id, num_parts, is_phrase in node.entries:
                        is_match = False
                        if is_phrase:
                            # A phrase matches if it has the correct number of word parts.
                            # A multi-word phrase requires separators in the text.
                            if num_parts == num_word_tokens:
                                if num_parts > 1:
                                    if has_separators:
                                        is_match = True
                                else:  # Single-word phrase
                                    is_match = True
                        else:  # A compound word
                            # A compound word must be formed by contiguous word tokens.
                            if not has_separators:
                                is_match = True
                        
                        if is_match:
                            start_idx, end_idx = word_indices[0], word_indices[-1]
                            for k in range(start_idx, end_idx + 1):
                                annotated_tokens[k][1].add(entry_id)
            # If token is a separator, we just continue, effectively consuming it.
            
    return annotated_tokens
