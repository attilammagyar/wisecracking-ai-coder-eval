import collections.abc

# Helper: determine if a token be a word (alnum or not!)
def _is_word(token):
    # We treat word tokens as having at least one alphanumeric character
    return any(c.isalnum() for c in token)

class TrieNode:
    __slots__ = ('children', 'entries', 'is_separator')
    def __init__(self, is_separator=False):
        self.children = dict()
        self.entries = set()
        self.is_separator = is_separator

class DictionaryIndex:
    __slots__ = ('root', 'word_lookup')
    def __init__(self, root, word_lookup):
        self.root = root
        self.word_lookup = word_lookup

def build_dictionary_index(dictionary: collections.abc.Mapping) -> object:
    """
    Build a normalized trie index for fast lookup of words and
    compound phrases.
    """
    # Lowercase map for single-word/direct matches (for O(1) lookup)
    word_lookup = dict()
    # Phrase trie
    root = TrieNode(is_separator=False)

    for phrase, entry in dictionary.items():
        tokens = []
        current = ''
        # Tokenize the dictionary entry - split by 'word'/'sep' alternation
        for c in phrase:
            if c.isspace():
                if current:
                    tokens.append(current)
                    current = ''
                tokens.append(c)
            elif c.isalnum():
                current += c
            else:
                if current:
                    tokens.append(current)
                    current = ''
                tokens.append(c)
        if current:
            tokens.append(current)
        # Group separators together, and words together
        phrase_tokens = []
        buf = ''
        buf_is_word = None
        for tok in tokens:
            now_is_word = _is_word(tok)
            if buf_is_word is None:
                buf = tok
                buf_is_word = now_is_word
            elif buf_is_word == now_is_word:
                buf += tok
            else:
                phrase_tokens.append((buf, buf_is_word))
                buf = tok
                buf_is_word = now_is_word
        if buf:
            phrase_tokens.append((buf, buf_is_word))
        
        # Insert phrase into trie
        node = root
        for token, is_word in phrase_tokens:
            key = token.lower()
            child = node.children.get(key)
            if not child:
                child = TrieNode(is_separator=not is_word)
                node.children[key] = child
            node = child
        node.entries.add(entry)
        # If phrase consists of only a single word, add it to direct lookup
        just_tokens = [token for (token, is_word) in phrase_tokens if is_word]
        if len(just_tokens) == 1 and all(is_word for (_, is_word) in phrase_tokens):
            word_lookup[just_tokens[0].lower()] = entry
    return DictionaryIndex(root, word_lookup)

def annotate(tokens: collections.abc.Iterable[str], dictionary_index: object) -> collections.abc.Iterable[tuple[str, collections.abc.Set]]:
    """
    Annotate tokens with entries from the dictionary.
    """
    # Convert to list for index access and repeated walks
    tokens = list(tokens)
    N = len(tokens)
    annots = [set() for _ in tokens]
    dindex = dictionary_index

    # 1. Direct matches (single-word entries)
    for idx, tok in enumerate(tokens):
        key = tok.lower()
        entry = dindex.word_lookup.get(key)
        if entry is not None:
            annots[idx].add(entry)

    # 2. Phrase matching (using trie)
    # At each token, try to match from that position as far as possible
    for start in range(N):
        # Only word tokens can start a phrase
        if not _is_word(tokens[start]):
            continue
        queue = [(dindex.root, start, None)]  # (node, pos, last_word_idx)
        while queue:
            node, pos, last_word = queue.pop()
            if pos >= N:
                continue
            tok = tokens[pos].lower()
            is_word = _is_word(tokens[pos])
            next_node = node.children.get(tok)
            if not next_node:
                continue
            next_last_word = pos if is_word else last_word
            # We'll only consider a valid match if the phrase covers >=1 word
            if next_node.entries and last_word is not None:
                # The match covers from `start` to `pos` (inclusive)
                # Now, rules for annotation:
                # - annotate all tokens from start to pos (inclusive) with this entry,
                # - but only annotate *inner* separators, i.e. those not at boundaries
                # -- for each position i in start..pos:
                #    - if it's a word, annotate always
                #    - if it's a separator, only if not at start or end
                entryset = next_node.entries
                for i in range(start, pos + 1):
                    if _is_word(tokens[i]):
                        annots[i].update(entryset)
                    else:
                        # Only annotate separator if *not* at phrase boundaries
                        if i != start and i != pos:
                            annots[i].update(entryset)
            # Push next (even if this is a leaf, as phrases may nest)
            queue.append((next_node, pos + 1, next_last_word))
    # Output the results
    return [(token, annotations) for token, annotations in zip(tokens, annots)]
