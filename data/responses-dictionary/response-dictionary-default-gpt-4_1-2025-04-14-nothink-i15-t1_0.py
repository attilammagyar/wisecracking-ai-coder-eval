# Helper: defines what is a word token.
def is_word_token(token):
    # Consider a token word-like if it contains at least one alphanumeric character.
    # This covers natural language and embedded markdown (which is separator).
    return any(c.isalnum() for c in token)

def normalize_token(token):
    # Lowercase for case-insensitive matching.
    return token.lower()

def tokenize_phrase(phrase):
    """
    Converts a phrase from the dictionary into a list of tokens.
    A token is either a run of alphanumerics or a single non-alphanumeric char.
    """
    tokens = []
    i = 0
    n = len(phrase)
    while i < n:
        c = phrase[i]
        if c.isalnum():
            # Start of a word token
            start = i
            while i < n and phrase[i].isalnum():
                i += 1
            tokens.append(phrase[start:i])
        else:
            # Single non-word char as its own token (space, punctuation, etc)
            tokens.append(phrase[i])
            i += 1
    return tokens

class TrieNode:
    __slots__ = ['children', 'entries']
    def __init__(self):
        self.children = dict()   # token -> TrieNode
        self.entries = set()     # set of entry IDs (for phrases ending here)

def build_dictionary_index(dictionary: collections.abc.Mapping) -> object:
    """
    Build a normalized index from a dictionary for fast lookup of words and compound phrases.
    We'll build a tokenized, lowercased trie index for fast prefix+span matching.
    """
    # The outer structure:
    # - root TrieNode for all phrases (including single words).
    # - We'll track the set of entry_ids for every phrase ending at a node.
    root = TrieNode()

    for phrase, entry_id in dictionary.items():
        # Tokenize the phrase into tokens as the input will be received.
        tokens = tokenize_phrase(phrase)
        # Normalize all tokens (e.g., lowercase).
        norm_tokens = tuple(normalize_token(tok) for tok in tokens)
        node = root
        for tok in norm_tokens:
            if tok not in node.children:
                node.children[tok] = TrieNode()
            node = node.children[tok]
        node.entries.add(entry_id)
    return root


def annotate(tokens: collections.abc.Iterable[str], dictionary_index: object) -> collections.abc.Iterable[tuple[str, collections.abc.Set]]:
    """
    Annotate tokens with entries from the dictionary.
    Returns a list containing (token, annotations) pairs for each token in tokens.
    """
    tokens = list(tokens)
    n = len(tokens)
    # We need annotation sets for each token index.
    token_annotations = [set() for _ in range(n)]
    # Pre-lowercase all tokens for efficient comparisons.
    norm_tokens = [normalize_token(tok) for tok in tokens]
    is_word = [is_word_token(tok) for tok in tokens]

    root = dictionary_index

    # For each start position in the list of tokens:
    for start in range(n):
        node = root
        # To enforce compound phrase semantics, we want to walk as far as possible.
        # We'll use span: [start, end)
        end = start
        while end < n:
            tok = norm_tokens[end]
            if tok not in node.children:
                break
            node = node.children[tok]
            end += 1

            if node.entries:
                # Now, should we annotate all tokens in [start, end)?
                # - For phrases longer than one token, annotate only inner separators: 
                #   annotate all tokens **except** leading/trailing separators
                #   (if any) surrounding the phrase.
                indices_to_annotate = list(range(start, end))
                if end - start > 1:
                    # Remove leading separator
                    if not is_word[start]:
                        indices_to_annotate = indices_to_annotate[1:]
                    # Remove trailing separator
                    if indices_to_annotate and not is_word[end-1]:
                        indices_to_annotate = indices_to_annotate[:-1]
                for idx in indices_to_annotate:
                    token_annotations[idx].update(node.entries)
        # Additionally, single-token individual word annotation is attempted here as well,
        # but the above loop catches all when phrases of length 1 are present in the dictionary.

    # Return list of (token, annotation_set) tuples.
    return [(token, annotations) for token, annotations in zip(tokens, token_annotations)]
